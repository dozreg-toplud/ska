#!/usr/bin/env python3
# usage: sccloop.py OUTDIR      then
#   RUNHOON_LIB=OUTDIR/lib.hoon tools/hoon/runhoon.sh OUTDIR/ck.hoon 900 > out.txt
#   tools/hoon/sccloop.py --lean out.txt > lemmas/Ska/SccLoopData.lean
# The sweep loop of +compile-scc-in (README Gaps 21, lemmas/Ska/SccLoop.lean) on the real
# compiler.  The instrumented copy of the library prints, as raw nouns (bells as their mugs):
#   [%scc S done mem kids]     at the start of the arm (kids: each member with its kids' mugs)
#   [%ord S order]             the DFS postorder
#   [%top S top]               the needs of the %may sweep
#   [%rd S b mode keep views]  at the start of member: each kid's need (map-local, else top,
#                              else none) and its entry of sure.cache (else none)
#   [%out S b mode keep need-new sur-raw sur was moved cape prev need-pessimized]
#   [%swp S counter any tick]  after each sweep of the loop
#   [%fin S entries]           the needs of the entries the final pass returns
import os, re, sys
D = os.path.dirname(os.path.abspath(__file__))
W = os.path.abspath(os.path.join(D, '..', '..', '..'))


def cord(n):
    s = b''
    while n:
        s += bytes([n & 255]); n >>= 8
    return s.decode('latin1')


def parse(t):
    """A raw noun as printed by ~& of a `*`: atoms in @ud with dots, cells in brackets."""
    toks = re.findall(r'\[|\]|[0-9.]+|~', t)
    pos = [0]

    def one():
        x = toks[pos[0]]; pos[0] += 1
        if x == '[':
            xs = []
            while toks[pos[0]] != ']':
                xs.append(one())
            pos[0] += 1
            r = xs[-1]
            for y in reversed(xs[:-1]):
                r = (y, r)
            return r
        if x == '~':
            return 0
        return int(x.replace('.', ''))
    return one()


def lst(n):
    out = []
    while n != 0:
        out.append(n[0]); n = n[1]
    return out


def need(n):
    """need-ordered as Lean."""
    h, t = n
    if isinstance(h, tuple):
        return '(.pair %s %s)' % (need(h), need(t))
    c = cord(h)
    if c == 'none': return '.none'
    if c == 'this': return '.this'
    if c == 'both': return '(.both %s %s)' % (need(t[0]), need(t[1]))
    raise Exception(c)


def cape(n):
    if isinstance(n, tuple):
        return '(.cell %s %s)' % (cape(n[0]), cape(n[1]))
    return '.yes' if n == 0 else '.no'


def loy(n): return 'true' if n == 0 else 'false'


if sys.argv[1] == '--lean':
    raw = open(sys.argv[2]).read().split('\n')
    ls = []; cur = None; dep = 0
    for l in raw:
        if cur is None:
            if not l.startswith('['):
                continue
            cur = ''
        cur += ' ' + l.strip()
        dep += l.count('[') - l.count(']')
        if dep == 0:
            ls.append(cur.strip()); cur = None
    h = len(ls) // 2
    if ls[:h] == ls[h:]:
        ls = ls[:h]
    evs = [parse(l) for l in ls]
    # group per case and scc
    case = None; groups = {}; keys = []
    for e in evs:
        tag = cord(e[0])
        if tag == 'case':
            case = cord(e[1]); continue
        s = e[1][0]
        k = (case, s)
        if k not in groups:
            groups[k] = []; keys.append(k)
        groups[k].append((tag, e[1][1]))
    print('import lemmas.Ska.SccLoop\n')
    print('/-! Generated by `tools/hoon/sccloop.py --lean` from the dump of `tools/hoon/sccloop.py`')
    print('    (the instrumented `+compile-scc-in`).  Bells are their mugs. -/\n')
    print('namespace Formalization.SkaModel.SccLoop\nopen Formalization.SkaModel\n')
    n = 0
    names = []
    for (cs, s) in keys:
        g = groups[(cs, s)]
        scc = [x for t, x in g if t == 'scc']
        if not scc: continue
        done, rest = scc[0]
        if done == 0: continue          # a lone bell that does not call itself
        mem = lst(rest[0]); kids = [(b, lst(ks)) for b, ks in lst(rest[1])]
        order = lst([x for t, x in g if t == 'ord'][0])
        top = [(b, need(v)) for b, v in lst([x for t, x in g if t == 'top'][0])]
        rds = [x for t, x in g if t == 'rd']
        outs = [x for t, x in g if t == 'out']
        swps = [x for t, x in g if t == 'swp']
        fin = [(b, need(v)) for b, v in lst([x for t, x in g if t == 'fin'][0])]
        assert len(rds) == len(outs)
        comp = []
        capes = {}
        for r, o in zip(rds, outs):
            b, (mode, (keep, views)) = r
            b2, (mode2, (keep2, rest2)) = o
            assert (b, mode, keep) == (b2, mode2, keep2)
            nn, (surr, (sur, (was, (moved, (cp, (prev, np)))))) = rest2
            capes[b] = cape(cp)
            vs = ', '.join('(%d, %s, %s)' % (k, need(kn), need(ks)) for k, (kn, ks) in
                           [(v[0], v[1]) for v in lst(views)])
            comp.append('{ b := %d, mode := .%s, keep := %s, views := [%s], nn := %s, surRaw := %s, sur := %s, was := %s, moved := %s, prev := %s, np := %s }'
                        % (b, cord(mode), loy(keep), vs, need(nn), need(surr), need(sur),
                           'none' if was == 0 else 'some ' + need(was[1]), loy(moved),
                           'none' if prev == 0 else 'some ' + need(prev[1]), need(np)))
        nm = 'd%d' % n; n += 1; names.append(nm)
        print('/-- case `%%%s`, SCC of %d bells, %d sweeps. -/' % (cs, len(mem), len(swps)))
        print('def %s : Dump where' % nm)
        print('  mem := %s' % mem)
        print('  order := %s' % order)
        print('  kids := [%s]' % ', '.join('(%d, %s)' % (b, ks) for b, ks in kids))
        print('  capes := [%s]' % ', '.join('(%d, %s)' % (b, capes.get(b, '.no')) for b in mem))
        print('  top := [%s]' % ', '.join('(%d, %s)' % x for x in top))
        print('  comps := [\n    %s]' % ',\n    '.join(comp))
        print('  sweeps := [%s]' % ', '.join(loy(x[1][0]) for x in swps))
        print('  fin := [%s]\n' % ', '.join('(%d, %s)' % x for x in fin))
    print('def dumps : List Dump := [%s]\n' % ', '.join(names))
    print('end Formalization.SkaModel.SccLoop')
    sys.exit(0)

out = sys.argv[1]
os.makedirs(out, exist_ok=True)
src = open(os.path.join(W, 'desk/lib/nock-compilation.hoon')).read().split('\n')
a = src.index('++  compile-scc-in')
z = src.index('++  bake-need')


def ins(anchor, lines, after=True):
    z = src.index('++  bake-need')
    k = [i for i in range(a, z) if src[i] == anchor]
    assert len(k) == 1, anchor
    i = k[0] + 1 if after else k[0]
    src[i:i] = lines


ins('  =/  done=?  &(?=([* ~ ~] scc) !(~(has ju kids) n.scc n.scc))', [
    '  ~&  ^-  *',
    '      :*  %scc  (mug scc)  done  (turn ~(tap in scc) mug)',
    '          %+  turn  ~(tap in scc)',
    '          |=(b=bell [(mug b) (turn ~(tap in (~(get ju kids) b)) mug)])',
    '      ==',
])
ins('    =/  comp  (comp scc long-ska jets-hot map-local top b)', [
    '    ~&  ^-  *',
    '        :*  %rd  (mug scc)  (mug b)  mode  keep',
    '            %+  turn  ~(tap in (~(get ju kids) b))',
    '            |=  k=bell',
    '            :+  (mug k)',
    '              ?^  s=(~(get by map-local) k)  need.u.s',
    '              (~(gut by top) k [%none ~])',
    '            (~(gut by sure.cache) k [%none ~])',
    '        ==',
])
ins('    ?~  s-previous=(~(get by map-local) b)', [
    '    ~&  ^-  *',
    '        =/  sp  (~(get by map-local) b)',
    '        :*  %out  (mug scc)  (mug b)  mode  keep  need-new  ^sur  sur  was  moved',
    '            cape.less.b',
    '            ?~(sp ~ `need.u.sp)',
    '            ?~(sp need-new (msg-need-ord need-new need.u.sp cape.less.b))',
    '        ==',
], after=False)
ins('      [m c(nary (~(uni by nary.c) m))]', [
    '      ~&  ^-  *',
    '          [%fin (mug scc) (turn ~(tap by m) |=([b=bell s=straight] [(mug b) need.s]))]',
], after=False)
ins('  ::  A callee in the SCC that has no shape yet is not taken to read', [
    '  ~&  ^-(* [%ord (mug scc) (turn order mug)])',
], after=False)
ins('  =/  top=(map bell need-ordered)  (~(run by may) |=(s=straight need.s))', [
    '  ~&  ^-  *',
    '      [%top (mug scc) (turn ~(tap by top) |=([b=bell n=need-ordered] [(mug b) n]))]',
])
ins('  ?.  any.st.res  (final & map-local cache)', [
    '  ~&  ^-(* [%swp (mug scc) counter any.st.res tick.st.res])',
], after=False)
open(os.path.join(out, 'lib.hoon'), 'w').write('\n'.join(src))

# The driver: each case is a gate (built here, context included) slammed on the subject.
CASES = r'''
=/  cases=(list [nam=@tas gat=*])
  :~  :-  %dec   =>  ~  |=(a=@ =|(b=@ |-(?:(.=(a .+(b)) b $(b .+(b))))))
      :-  %lent  =>  ~  |=(l=* =|(n=@ |-(?@(l n $(l +.l, n .+(n))))))
      :-  %lfl   =>  ~  |=(t=* |-(?@(t t $(t -.t))))
      :-  %flat  =>  ~  |=(t=* =|(a=* |-(?@(t [t a] $(t -.t, a $(t +.t))))))
      :-  %evod
        =>  ~  =<  ev
        |%  ++  ev  |=(n=@ ?:(.=(0 n) & (od (dc n))))
            ++  od  |=(n=@ ?:(.=(0 n) | (ev (dc n))))
            ++  dc  |=(a=@ =|(b=@ |-(?:(.=(a .+(b)) b $(b .+(b))))))
        --
      :-  %cyc3
        =>  ~  =<  a
        |%  ++  a  |=(n=@ ?:(.=(0 n) 0 (b (dc n))))
            ++  b  |=(n=@ ?:(.=(0 n) 1 (c (dc n))))
            ++  c  |=(n=@ ?:(.=(0 n) 2 (a (dc n))))
            ++  dc  |=(a=@ =|(b=@ |-(?:(.=(a .+(b)) b $(b .+(b))))))
        --
      :-  %pq
        =>  ~  =<  p
        |%  ++  p  |=(x=* ?@(x 0 (q +.x)))
            ++  q  |=(x=* ?@(x 1 (p -.x)))
        --
      :-  %pq2
        =>  ~  =<  p
        |%  ++  p  |=(x=* ?@(x 0 ?@(-.x 1 (q +.x))))
            ++  q  |=(x=* ?@(x 1 (r -.x)))
            ++  r  |=(x=* ?@(x 2 ?@(+.x (p x) (p +.x))))
        --
      :-  %swap  =>  ~  |=([a=@ b=@ c=@] |-(?:(.=(a 0) b $(a +(a), b c, c b))))
      :-  %fld   =>  ~  |=(s=[i=@ j=@ k=*] |-(?:(.=(i.s 0) k.s $(i.s .+(i.s), k.s [j.s k.s]))))
      :-  %self2
        =>  ~  =<  a
        |%  ++  a  |=(x=* ?@(x 0 ?@(-.x (a +.x) (b -.x))))
            ++  b  |=(x=* ?@(x 1 (a [+.x -.x])))
        --
      :-  %deep
        =>  ~  =<  a
        |%  ++  a  |=(x=[p=* q=*] ?@(p.x q.x (b [-.p.x q.x])))
            ++  b  |=(y=[p=* q=*] ?@(q.y (a [+.y p.y]) (c [q.y p.y])))
            ++  c  |=(z=[p=* q=*] ?@(p.z (a z) (a [+.p.z q.z])))
        --
      :-  %ack
        =>  ~  =<  ack
        |%  ++  ack
              |=  [m=@ n=@]
              ?:  .=(0 m)  .+(n)
              ?:  .=(0 n)  (ack (dc m) 1)
              (ack (dc m) (ack m (dc n)))
            ++  dc  |=(a=@ =|(b=@ |-(?:(.=(a .+(b)) b $(b .+(b))))))
        --
      :-  %tree
        =>  ~  =<  sz
        |%  ++  sz  |=(t=* ?@(t 0 (ad (sz -.t) (sz +.t))))
            ++  ad  |=([a=@ b=@] |-(?:(.=(0 a) b $(a (dc a), b .+(b)))))
            ++  dc  |=(a=@ =|(b=@ |-(?:(.=(a .+(b)) b $(b .+(b))))))
        --
      :-  %grow
        =>  ~  =<  a
        |%  ++  a  |=(x=* ?@(x 0 (b x)))
            ++  b  |=(x=* ?@(x 1 ?@(+.x (a -.x) (c x))))
            ++  c  |=(x=* ?@(x 2 ?@(-.x (a +.x) (b [-.-.x +.x]))))
        --
      :-  %deep4
        =>  ~  =<  a
        |%  ++  a  |=(x=[p=* q=*] ?@(p.x q.x (b [-.p.x q.x])))
            ++  b  |=(y=[p=* q=*] ?@(q.y (c [+.y p.y]) (c [q.y p.y])))
            ++  c  |=(z=[p=* q=*] ?@(p.z (d z) (d [+.p.z q.z])))
            ++  d  |=(w=[p=* q=*] ?@(q.w (a w) (a [q.w p.w])))
        --
      :-  %deep2
        =>  ~  =<  a
        |%  ++  a  |=(x=[p=* q=*] ?@(p.x q.x ?@(q.x (b x) (c [-.p.x q.x]))))
            ++  b  |=(y=[p=* q=*] (a [q.y p.y]))
            ++  c  |=(z=[p=* q=*] ?@(q.z (a [+.z p.z]) (b [-.q.z p.z])))
        --
      :-  %rot3
        =>  ~  =<  a
        |%  ++  a  |=(s=[i=* j=* k=*] ?@(i.s j.s (b [j.s k.s -.i.s])))
            ++  b  |=(s=[i=* j=* k=*] ?@(j.s k.s (c [k.s +.j.s i.s])))
            ++  c  |=(s=[i=* j=* k=*] ?@(k.s i.s (a [i.s j.s -.k.s])))
        --
  ==
'''

