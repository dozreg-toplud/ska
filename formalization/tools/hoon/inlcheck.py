#!/usr/bin/env python3
"""Read the output of tools/hoon/inldump.hoon (runhoon.sh) and
* --sum OUT: per entry of inl.cache, how many direct calls of the code's nomm
  became a %7 (inlined) and how many stayed;
* --lean OUT: write lemmas/Glue/InlineData.lean: `inl` (the entries [bell nomm]
  of inl.cache) and `cod` ([bell nomm single self] per bell of code) as Lean
  nouns, from the cued jam.
"""
import sys, os
sys.setrecursionlimit(100000)
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'gen'))
from hintcheck import records, parse, atom, cue, lean, strip


def lst(n):
    out = []
    while isinstance(n, tuple):
        out.append(n[0]); n = n[1]
    return out


def calls(n, acc):
    """Count direct calls [2 p q [~ info]] (info a unit, non-null) in a nomm noun."""
    if not isinstance(n, tuple):
        return
    h, t = n
    if isinstance(h, tuple):
        calls(h, acc); calls(t, acc); return
    if h == 2:
        p, (q, info) = t
        if info != 0:
            acc.append(1)
        calls(p, acc); calls(q, acc); return
    if isinstance(t, tuple):
        if h in (3, 4):
            calls(t, acc)
        elif h in (5, 7, 12):
            calls(t[0], acc); calls(t[1], acc)
        elif h == 6:
            calls(t[0], acc); calls(t[1][0], acc); calls(t[1][1], acc)
        elif h == 10:
            calls(t[0][1], acc); calls(t[1], acc)
        elif h == 11:
            if isinstance(t[0], tuple):
                calls(t[0][1], acc)
            calls(t[1][0], acc)
        elif h == 0x6e61656d:
            calls(t[0], acc); calls(t[1][1][0], acc)


if __name__ == '__main__':
    mode, path = sys.argv[1], sys.argv[2]
    recs = [parse(r) for r in records(open(path).read())]
    jam = next(atom(r[1]) for r in recs if strip(r[0]) == '%jam')
    inl, cod = cue(jam)
    inl, cod = lst(inl), lst(cod)
    if mode == '--sum':
        code = {repr(c[0]): c[1][0] for c in cod}
        for b, n in inl:
            a, k = [], []
            calls(code[repr(b)], a); calls(n, k)
            print('entry', 'calls before', len(a), 'after', len(k), 'same' if code[repr(b)] == n else 'changed')
        print('entries', len(inl), 'code', len(cod))
    else:
        out = ['import lemmas.Ska.Types', '',
               '/-! Generated by `tools/hoon/inlcheck.py --lean` from the output of',
               '`tools/hoon/inldump.hoon`: `inl`, the entries `[bell nomm]` of `inl.cache` after 20',
               'pokes, and `cod`, per bell of `code`, `[bell nomm single self]`. -/', '',
               'namespace Formalization', 'namespace SkaModel', 'namespace InlineData', '', 'open Nock', '']
        for i, (b, n) in enumerate(inl):
            out.append(f'def i{i} : Noun × Noun :=\n  ({lean(b)},\n   {lean(n)})\n')
        for i, (b, (n, (s, f))) in enumerate(cod):
            out.append(f'def c{i} : Noun × Noun × Bool × Bool :=\n  ({lean(b)},\n   {lean(n)},\n   '
                       f'{"true" if s == 0 else "false"}, {"true" if f == 0 else "false"})\n')
        out.append('def inl : List (Noun × Noun) := [' + ', '.join(f'i{i}' for i in range(len(inl))) + ']')
        out.append('def cod : List (Noun × Noun × Bool × Bool) := [' +
                   ', '.join(f'c{i}' for i in range(len(cod))) + ']')
        out += ['', 'end InlineData', 'end SkaModel', 'end Formalization', '']
        open('lemmas/Glue/InlineData.lean', 'w').write('\n'.join(out))
        print('wrote', len(inl), 'inl entries', len(cod), 'code entries')
