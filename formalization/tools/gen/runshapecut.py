"""The cut of `+run-shape` (door arm `0xabee`, battery axis 27630 of `comp.door`) from the pill.

    tools/capped.sh -m 3G python3 tools/gen/runshapecut.py OUT.lean

The arm is `[7 [8 [1 bunt] [1 gate] 0 1] [11 [%fast ..] 0 1]]`; the gate's battery pushes
`none`, `this` and `simple` (`=/`) and then runs the `?-` over the nomm: twelve tests
(`[^ *]`, `%0`, `%1`, `%2`, `%3`, `%4`, `%5`, `%6`, `%7`, `%10`, `%11`, `%mean`) and the last
case `%12`.  Writes `rsArm` and its parts, each case `rsK..` written out (the ones that are
linked) or read from the pill by its axis in `comp.door`, the theorem `rs_arm_at` (by
`kernel_rfl`) and `rs_dol_eq` (the chain, by `rfl`).  Prints the cells of each case and the
door arms (`[9 ax [0 k]]`) each case pulls."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from nouns import *

BAX = 0b110101111101110
DOOR = ('R', 'comp.door')
OUT = sys.argv[1]
WRITE = {'Kc', 'K0', 'K1', 'K7', 'K10', 'K3', 'K4', 'K5', 'K12'}
memo = {}


def cells(n):
    if n[0] == 'R':
        k = n[1]
        if k not in memo:
            memo[k] = cells(get(k))
        return memo[k]
    if n[0] == 'A':
        return 0
    return 1 + cells(n[1]) + cells(n[2])


def pulls(n, acc, seen):
    st = [n]
    while st:
        x = st.pop()
        if x[0] == 'R':
            if x[1] in seen: continue
            seen.add(x[1]); st.append(get(x[1])); continue
        if x[0] == 'A': continue
        h, t = norm(x[1]), norm(x[2])
        if h == ('A', 9) and t[0] == 'C':
            a, r = norm(t[1]), norm(t[2])
            if a[0] == 'A' and r[0] == 'C' and norm(r[1]) == ('A', 0) and norm(r[2])[0] == 'A':
                acc.add((a[1], norm(r[2])[1]))
        st.append(x[1]); st.append(x[2])
    return acc


def seq(n, k):
    out = []
    n = norm(n)
    for _ in range(k - 1):
        assert n[0] == 'C', n
        out.append(norm(n[1]))
        n = norm(n[2])
    out.append(n)
    return out


arm = norm(slot(BAX, DOOR))
# [7 [8 [1 bunt] [1 gate] 0 1] [11 hint 0 1]]
_, mk, hint = seq(arm, 3)
_, b1, rest = seq(mk, 3)
g1, _ = seq(rest, 2)
bunt = norm(b1[2]); gate = norm(g1[2])
_, noneF, r1 = seq(gate, 3)
_, thisF, r2 = seq(r1, 3)
_, simpleF, dol = seq(r2, 3)
# the axes, in comp.door, of the parts (for the cases read from the pill)
# arm at BAX; gate battery: arm -> 6 (mk) -> 6 (b1g... ) careful: compute by search
def axis_of(target, n, ax=1, depth=0):
    """first axis of `target` (by identity of the normalized tuple) below n, breadth-limited"""
    return None

names = ['Kc', 'K0', 'K1', 'K2', 'K3', 'K4', 'K5', 'K6', 'K7', 'K10', 'K11', 'Kmean']
tags = [None, 0, 1, 2, 3, 4, 5, 6, 7, 10, 11, cord('mean')]
tests, ks = [], []
n = dol
# the axis of dol inside comp.door: arm = BAX; mk = 2*BAX+1 ... computed along the seq walk
def peg(a, b):
    k = b.bit_length() - 1
    return (a << k) | (b - (1 << k))
ax_mk = peg(BAX, 6)
ax_gate = peg(ax_mk, 29)
assert eqn(slot(ax_gate, DOOR), gate)
ax_dol = peg(peg(peg(ax_gate, 7), 7), 7)
assert eqn(slot(ax_dol, DOOR), dol)
ax = ax_dol
axes = {}
for nm, tg in zip(names, tags):
    n = norm(n)
    _, t, rest = seq(n, 3)
    c, r = seq(rest, 2)
    tests.append(t); ks.append((nm, c))
    axes[nm] = peg(ax, 14)  # [6 t c r]: c at 14
    ax = peg(ax, 15)
    n = r
last = norm(n)
axes['K12'] = ax
assert eqn(slot(axes['K7'], DOOR), ks[8][1])
ks.append(('K12', last))

with open(OUT, 'w') as f:
    f.write('''import lemmas.Compiler.CompRunLink

/-!
# The cut of `+run-shape` (generated by `tools/gen/runshapecut.py`; do not edit by hand)

`+run-shape` is arm `27630` of the door's battery `comp.door` (door axis `0xabee`):
`[7 [8 [1 rsBunt] [1 rsGate] 0 1] [11 [%fast ..] 0 1]]`.  The gate's battery `rsGate`
pushes `none` (`rsNoneF`), `this` (`rsThisF`) and `simple` (`rsSimpleF`) and runs `rsDol`,
the `?-` over the nomm: the tests `rsTc`, `rsT k` and the cases `rsKc`, `rsK0` .. `rsKmean`,
then `rsK12`.  So the cases run on

    [simple [this [none [rsGate [[nomm goal sup] [comp.door [gen ctx]]]]]]]

with `nomm` at `124`, `goal` at `250`, `sup` at `251`, the door's core at `63`, `gen` at
`254`.  The cases that are linked are written out; the others are read from the pill.
-/

namespace Formalization
namespace Compiler

open Nock Pill Hoon

''')
    def d(name, n, doc=None):
        if doc: f.write('/-- %s -/\n' % doc)
        f.write('def %s : Noun :=\n  %s\n\n' % (name, lean(n)))
    d('rsBunt', bunt, 'The bunt of the sample `[nomm goal sup]`.')
    d('rsNoneF', noneF, '`=/  none=laze  *laze`.')
    d('rsThisF', thisF, '`=/  this=laze  [[this+~ ~] ~ ~]`.')
    d('rsSimpleF', simpleF, '`=/  simple  ?:(?=(%next -.goal) goal [%next this])`.')
    f.write('/-- The test `?=([%k *] nomm)`, the nomm at `124`. -/\n')
    f.write('def rsT (k : Nat) : Noun :=\n  C (A 6) (C (C (A 3) (C (A 0) (A 124))) (C (C (A 5) (C (C (A 1) (A k)) (C (A 0) (A 248)))) (C (A 1) (A 1))))\n\n')
    f.write('/-- The test `?=([^ *] nomm)`. -/\n')
    f.write('def rsTc : Noun :=\n  C (A 6) (C (C (A 3) (C (A 0) (A 124))) (C (C (A 3) (C (A 0) (A 248))) (C (A 1) (A 1))))\n\n')
    for (nm, c) in ks:
        if nm in WRITE:
            d('rs' + nm, c, 'The case `%s` (%d cells).' % (nm[1:], cells(c)))
        else:
            f.write('/-- The case `%s` (%d cells), read from the pill. -/\n' % (nm[1:], cells(c)))
            f.write('def rs%s : Noun := (slot? %d comp.door).getD (A 0)\n\n' % (nm, axes[nm]))
    chain = 'C (A 6) (C rsTc (C rsKc\n'
    for nm, tg in zip(names[1:], tags[1:]):
        chain += '  (C (A 6) (C (rsT %s) (C rs%s\n' % (hex(tg) if tg > 9999 else tg, nm)
    chain += '  rsK12' + ')))' * 11 + '))'
    f.write('/-- The `?-` over the nomm. -/\ndef rsDol : Noun :=\n  %s\n\n' % chain)
    f.write('/-- The gate\'s battery: three pushes, then `rsDol`. -/\n')
    f.write('def rsGate : Noun :=\n  C (A 8) (C rsNoneF (C (A 8) (C rsThisF (C (A 8) (C rsSimpleF rsDol)))))\n\n')
    f.write('/-- The arm. -/\ndef rsArm : Noun :=\n  C (A 7) (C (C (A 8) (C (C (A 1) rsBunt) (C (C (A 1) rsGate) (C (A 0) (A 1))))) %s)\n\n' % lean(hint))
    f.write('/-- **`+run-shape` is arm `27630` of the door\'s battery.** -/\n')
    f.write('theorem rs_arm_at : slot? %d comp.door = some rsArm := by kernel_rfl\n\n' % BAX)
    f.write('end Compiler\nend Formalization\n')

print('case cells pulls')
for (nm, c) in ks:
    ps = sorted(pulls(c, set(), set()))
    print(nm, cells(c), ' '.join('%s@%d' % (hex(a), k) for a, k in ps))
print('tests', [cells(t) for t in tests], 'pushes', cells(noneF), cells(thisF), cells(simpleF), 'total arm', cells(arm))
