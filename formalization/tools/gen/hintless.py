#!/usr/bin/env python3
"""Read the outputs of tools/hoon/hintless.hoon and tools/hoon/hintmeanless.hoon (runhoon.sh;
track J, README Gaps 24.24) and
* --sum OUT OUT2: per entry, its name and the cape of its bell's `less`;
* --lean OUT OUT2: write lemmas/Ska/CompHintXData.lean, the cued jam `[less nomm]` of each
  entry as a Lean `Noun`: `lessT` for the 21 code-table entries of hintdump3.hoon (t01.., in
  `~(tap by code)` order) and `lessM` for the 36 entries of hintmean.hoon (m01..m31,
  g01..g05).  The nomm is there to check (`#guard`) that the entry is the one of the older
  dumps (`HintClsData`, `MeanData`).
"""
import sys, re, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hintcheck as H

def text(path):
    t = open(path).read()
    return re.sub(r'"[^"]*"', 'TAPE', t)

def entries(path, num):
    recs = [H.parse(r) for r in H.records(text(path))]
    es = {}
    for r in recs:
        if H.strip(r[0]) != '%less': continue
        k = H.strip(r[1][0]); v = H.cue(H.atom(r[1][1]))
        nam = f't{int(k):02d}' if num else k.lstrip('%')
        es.setdefault(nam, [])
        if v not in es[nam]: es[nam].append(v)
    for n, l in es.items():
        assert len(l) == 1, (n, len(l))
    return {n: l[0] for n, l in es.items()}

if __name__ == '__main__':
    mode, p1, p2 = sys.argv[1], sys.argv[2], sys.argv[3]
    ts, ms = entries(p1, True), entries(p2, False)
    if mode == '--sum':
        for n, v in list(ts.items()) + list(ms.items()):
            print(n, v[0][0])
    else:
        out = ['import lemmas.Ska.Types', '',
               '/-! Generated by `tools/gen/hintless.py --lean` from the outputs of',
               '`tools/hoon/hintless.hoon` and `tools/hoon/hintmeanless.hoon` (track J, README Gaps',
               '24.24): the cued jam `[less nomm]` of every entry of `code.long-ska` after the 16 pokes',
               'of `hintdump3.hoon` (`lessT`, t01.. in `~(tap by code)` order) and of the 36 entries of',
               '`hintmean.hoon` (`lessM`, m01..m31, g01..g05). -/', '',
               'namespace Formalization', 'namespace SkaModel', 'namespace HintXData', '', 'open Nock', '']
        for n, v in list(ts.items()) + list(ms.items()):
            out.append(f'def l{n} : Noun :=\n  {H.lean(v)}\n')
        out.append('def lessT : List (String × Noun) := [' + ', '.join(f'("{n}", l{n})' for n in ts) + ']')
        out.append('')
        out.append('def lessM : List (String × Noun) := [' + ', '.join(f'("{n}", l{n})' for n in ms) + ']')
        out += ['', 'end HintXData', 'end SkaModel', 'end Formalization', '']
        open('lemmas/Ska/CompHintXData.lean', 'w').write('\n'.join(out))
        print('wrote', len(ts), 'code-table entries,', len(ms), 'hintmean entries')
