#!/usr/bin/env python3
"""Write lemmas/Ska/CompRingRun.lean: runLCMR env mono, the model of +run with
its flag `mono` and the direct call through a ring, generated from the text of
runLCM in lemmas/Ska/CompRunLCM.lean (itself generated by runlcm.py; neither is
changed).  Track K, README Gaps 19 (h).

Run from formalization/.  Every extraction and replacement asserts its count.

* runLCMR env mono: runLCM with the case %2 as `callLMR env mono`
  (lemmas/Ska/CompRingCall.lean), every recursive run renamed.  Why a script
  and not a parameter: runLCM fixes its case %2 to `callLM` (no parameter for
  the call), so the only way to keep every other case the same text is a copy.
"""
src = open('lemmas/Ska/CompRunLCM.lean').read()

def extract(start, end):
    i = src.index(start)
    assert src.count(start) == 1, start
    j = src.index(end, i)
    return src[i:j]

def rep(s, old, new, n):
    c = s.count(old)
    assert c == n, (old, c, n)
    return s.replace(old, new)

run = extract('def runLCM [HoonMapKeys Map] (env : CallEnv) (mono : Bool) :', 'end Comp')
run = rep(run, 'def runLCM [HoonMapKeys Map] (env : CallEnv) (mono : Bool) :',
          'def runLCMR [HoonMapKeys Map] (env : CallEnv) (mono : Bool) :', 1)
run = rep(run, 'callLM env mono (runLCM env mono sup p) (runLCM env mono sup q)',
          'callLMR env mono (runLCM env mono sup p) (runLCM env mono sup q)', 1)
n = run.count('runLCM env mono ')
assert n == 25, n
run = run.replace('runLCM env mono ', 'runLCMR env mono ')
assert 'runLCM ' not in run and 'callLM ' not in run

head = '''import lemmas.Ska.CompRunLCM
import lemmas.Ska.CompRingCall

/-!
# `run` with the flag `mono` and calls through rings: `runLCMR` (generated)

Written by `tools/gen/runlcmr.py` from the text of `runLCM`
(`CompRunLCM.lean`); do not edit by hand.  Track K, README Gaps 19 (h).

* `runLCMR env mono sup`: `runLCM env mono sup` with the case `%2` as
  `callLMR env mono` (`CompRingCall.lean`): a direct call to a callee with a
  ring emits `%caf` / `%csf` / `%jmf` / `%jsf` where `callLM` fails.

Where no direct callee has a ring it is `runLCM` (`runLCMR_eq`,
`CompRingRunEq.lean`).
-/

set_option linter.unusedSectionVars false
set_option linter.unusedVariables false

namespace Formalization
namespace SkaModel
namespace Comp

open Nock Lazy

variable {S : Type} [HoonSet S] {Map : Type → Type} [HoonMap Map]

'''
tail = '''end Comp
end SkaModel
end Formalization
'''
out = head + run + tail
open('lemmas/Ska/CompRingRun.lean', 'w').write(out)
print('wrote lemmas/Ska/CompRingRun.lean', len(out.splitlines()), 'lines')
