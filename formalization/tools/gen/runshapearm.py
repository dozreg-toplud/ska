"""The cut of one helper arm of `+run-shape` (a door arm of `comp.door`) from the pill.

    tools/capped.sh -m 3G python3 tools/gen/runshapearm.py OUT.lean PREFIX COREAX DOC NAME=AX ...

COREAX is the arm's axis in the door's core (as the Nock `[9 COREAX ..]` of the caller
names it); the battery axis is COREAX with its leading `10` replaced by `1`.  Each
`NAME=AX` names the subterm of the arm at axis AX (an axis in the arm's formula); the
defs are written smallest first, each one with the names written before it substituted
(by structural equality), then `PREFIXArm` (the whole arm) and the two kernel facts
`PREFIX_at` (`slot?` of the battery axis on `comp.door`) and `PREFIX_at'` (the core axis
on any core `[comp.door y]`).  DOC is the file's doc text (Markdown).  Prints the cells of
each part."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from nouns import *

OUT, PRE, COREAX, DOC = sys.argv[1], sys.argv[2], int(sys.argv[3], 0), sys.argv[4]
parts = [(a.split('=')[0], int(a.split('=')[1], 0)) for a in sys.argv[5:]]
b = bin(COREAX)[2:]
assert b[:2] == '10', 'not an arm of the battery'
BAX = int('1' + b[2:], 2)
DOOR = ('R', 'comp.door')
arm = norm(slot(BAX, DOOR))
memo = {}


def cells(n):
    n = norm(n)
    if n[0] == 'A':
        return 0
    k = id(n)
    if k not in memo:
        memo[k] = 1 + cells(n[1]) + cells(n[2])
    return memo[k]


terms = [(PRE + nm, slot(ax, arm)) for nm, ax in parts]
for nm, t in terms:
    assert t is not None, nm
terms.sort(key=lambda e: cells(e[1]))
with open(OUT, 'w') as f:
    f.write('import lemmas.Compiler.CompRunLink\n\n/-!\n%s\n\nGenerated by\n`tools/gen/runshapearm.py OUT %s %s DOC %s`;\ndo not edit by hand.\n-/\n\n'
            % (DOC, PRE, hex(COREAX), ' '.join(sys.argv[5:])))
    f.write('namespace Formalization\nnamespace Compiler\n\nopen Nock Pill Hoon\n\n')
    sub = []
    for nm, t in terms:
        f.write('def %s : Noun :=\n  %s\n\n' % (nm, lean(t, sub)))
        sub.append((nm, t))
    f.write('def %sArm : Noun :=\n  %s\n\n' % (PRE, lean(arm, sub)))
    f.write('theorem %s_at : slot? %d comp.door = some %sArm := by kernel_rfl\n\n' % (PRE, BAX, PRE))
    f.write('theorem %s_at\' (y : Noun) : slot? %s (C comp.door y) = some %sArm := by kernel_rfl\n'
            % (PRE, hex(COREAX), PRE))
    f.write('\nend Compiler\nend Formalization\n')
for nm, t in terms:
    print(nm, cells(t))
print(PRE + 'Arm', cells(arm), 'battery axis', BAX)
