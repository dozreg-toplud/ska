#!/usr/bin/env python3
"""Generate `consNC_okF` of lemmas/Ska/CompConsGH.lean from `consNC_ok` of
lemmas/Ska/CompConsCall.lean (the text between `-- BEGIN consNC_ok` and
`-- END consNC_ok`): the same proof, with one more conclusion, that a
subject that does not fit the cons's need does not fit the head's (the fact
`CF` of `+copy` that the proof of `nec` uses).  A head relation whose `nec`
is the semantic one (`RunOKGC`) is passed as a `RunOKNC` with the pure part
`[0 0]`, whose `nec` holds trivially, and the cons's `NecC` is then made
from the head's with this conclusion.  Exact-match replacements with
asserted counts.  Usage: consokf.py > body.lean (the text between the
markers `-- BEGIN consNC_okF` and `-- END consNC_okF` of CompConsGH.lean)."""
import os
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, '../../lemmas/Ska/CompConsCall.lean')).read()
i = src.index('-- BEGIN consNC_ok\n') + len('-- BEGIN consNC_ok\n')
j = src.index('-- END consNC_ok')
body = src[i:j]
def rep(a, b, n=1):
    global body
    c = body.count(a)
    assert c == n, (a, c)
    body = body.replace(a, b)
k = body.index('theorem consNC_ok ')
body = """/-- **`consNC_ok` with the fit of the head's need**: a subject that does not
fit the cons's need does not fit the head's (the tail's fits every subject).
Generated by `tools/gen/consokf.py` from `consNC_ok`. -/
""" + body[k:]
rep('theorem consNC_ok ', 'theorem consNC_okF ')
rep("""    RunOKNC lib P (C fh ft) pp sur th g0 g3 nex := by""",
    """    RunOKNC lib P (C fh ft) pp sur th g0 g3 nex ∧
      (∀ s, ¬ FitsS nex.laz.sure s → ¬ FitsS nexp.laz.sure s) := by""")
rep("""  refine {
""", """  refine ⟨{
""")
rep("""hI htr hs hm ag hned regs hh hn => ?_ }
""", """hI htr hs hm ag hned regs hh hn => ?_ },
    fun s hs a => hs ((CF s).mpr ⟨a, hqt s⟩)⟩
""")
print(body, end='')
