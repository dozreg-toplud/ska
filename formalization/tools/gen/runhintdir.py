#!/usr/bin/env python3
"""Write lemmas/Compiler/CompRunHintDir.lean: a copy of the direct-call part
of `CompRunDirectMonoP.lean` (the model of the case at `mono` `&`, the case
`%2` on a direct call dropped or not, its result) against the model with
hints `runLCH env snd true msup` (README Gaps 25), so that the parts `p` and
`q` of a direct call may hold hints.  The original is not changed; rerun
after it changes.  Run from formalization/.

The rules of `runhintr.py`, each with its count asserted:

* the range from `## The model of the case at` to `## Parts with no direct
  call`, without the declarations that are generic in the model `R`
  (`ResForR`, `crd_fq_resR`, `crd_nfR`, `crd_dropR`: they are used as they
  are);
* every declaration `n` of the range is renamed `nH` (and so are its uses),
  but `runLCM_n2_direct`, which becomes `runLCH_n2_direct`;
* `runLCM env true` -> `runLCH env snd true`, `rw [runLCM]` -> `rw [runLCH]`;
* the defs `CompRunAtMMH`, `PartLMH` take `snd` after `env`, and every use
  `XH env msup` becomes `XH env snd msup`;
* the file gets `variable {snd : Nomm → NeedOrd → Bool}`.
"""
import re, sys

D = 'lemmas/Compiler/'
src = open(D + 'CompRunDirectMonoP.lean').read()
i = src.index('/-! ## The model of the case at `mono` `&` -/')
j = src.index('/-! ## Parts with no direct call')
body = src[i:j]

# split into chunks, each a doc comment (optional) and its declaration
starts = [m.start() for m in re.finditer(r'^(?:/-!|/--|theorem |def |structure )', body, re.M)]
chunks, k = [], 0
for s in starts:
    if s < k:
        continue
    # a doc comment belongs to the declaration after it
    if body.startswith('/--', s):
        e = body.index('-/', s) + 2
        m = re.compile(r'^(?:theorem |def |structure )', re.M).search(body, e)
        nxt = [t for t in starts if t > m.start()]
        end = nxt[0] if nxt else len(body)
    else:
        nxt = [t for t in starts if t > s]
        end = nxt[0] if nxt else len(body)
    chunks.append(body[s:end])
    k = end
assert ''.join(chunks) == body[starts[0]:], 'chunking'

DECL = re.compile(r'^(?:theorem|def|structure) ([^\s(:{\[]+)', re.M)
GENERIC = {'ResForR', 'crd_fq_resR', 'crd_nfR', 'crd_dropR'}
kept, dropped = [], []
for c in chunks:
    ds = DECL.findall(c)
    if ds and ds[0] in GENERIC:
        dropped.append(ds[0])
    else:
        kept.append(c)
assert sorted(dropped) == sorted(GENERIC), dropped
s = ''.join(kept)
names = set(DECL.findall(s))
assert len(names) == 13, sorted(names)

def newname(n):
    return 'runLCH_n2_direct' if n == 'runLCM_n2_direct' else n + 'H'

for n in sorted(names, key=len, reverse=True):
    s = re.sub(r"(?<![\w.'])" + re.escape(n) + r"(?![\w'])", newname(n), s)

counts = {}
def sub(key, pat, rep):
    global s
    s, n = re.subn(pat, rep, s, flags=re.M)
    counts[key] = n

sub('model', r'\brunLCM env true\b', 'runLCH env snd true')
sub('rw', r'rw \[runLCM\]', 'rw [runLCH]')
sub('doc', r'\brunLCM env(\s+)true\b', r'runLCH env snd\1true')
for d in ['CompRunAtMMH', 'PartLMH']:
    sub('def ' + d, r'(def|structure) %s \(env : CallEnv\) \(msup' % d,
        r'\1 %s (env : CallEnv) (snd : Nomm → NeedOrd → Bool) (msup' % d)
    sub('use ' + d, r'\b%s env msup\b' % d, '%s env snd msup' % d)
    assert not re.search(r'\b%s env (?!snd|\(snd)' % d, s), d
assert 'runLCM' not in s, s[s.index('runLCM') - 80:s.index('runLCM') + 80]

EXPECT = {'model': 44, 'rw': 1, 'doc': 1, 'def CompRunAtMMH': 1, 'use CompRunAtMMH': 3, 'def PartLMH': 1, 'use PartLMH': 6}
if '--counts' in sys.argv:
    print(counts)
    sys.exit(0)
assert counts == EXPECT, counts

hdr = '''import lemmas.Compiler.CompRunHintClass

/-! Generated by `tools/gen/runhintdir.py` from `CompRunDirectMonoP.lean`
(README Gaps 25): the direct call of `%2` under `mono` `&` against `runLCH
env snd true msup`, every name `n` as `nH`, so that the parts of a direct
call may hold hints.  The lemmas generic in the model (`ResForR`,
`crd_fq_resR`, `crd_nfR`, `crd_dropR`) are used as they are. -/

namespace Formalization
namespace Compiler

open Nock Pill Hoon SkaModel SkaModel.Comp

set_option linter.unusedSimpArgs false
set_option linter.unusedSectionVars false

variable {ctx : Noun} {snd : Nomm → NeedOrd → Bool}

'''
out = hdr + s + 'end Compiler\nend Formalization\n'
open(D + 'CompRunHintDir.lean', 'w').write(out)
print('wrote CompRunHintDir.lean;', len(names), 'names renamed;', counts)
