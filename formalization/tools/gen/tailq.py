#!/usr/bin/env python3
"""Generate `lemmas/Compiler/CompRunTCallQ.lean` (README Gaps 19 (g)): copies of `crd_cnfRT` and
`crd_ctailRT` (`CompRunTCall.lean`) whose hypothesis on the run of the formula `q` is asked only
when `safe-fol-fol` fails (`safeFolFol q = false → RunAtRT ..`): a soft tail call of the corpus
has a quote as `q`, which the pill never runs.  Renamed with suffix `Q`; every replacement is
asserted.  Usage: python3 tools/gen/tailq.py   (from `formalization/`)
"""
import re
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
CDIR = ROOT / 'lemmas' / 'Compiler'
STARTS = ('/--', '/-!', 'theorem ', 'def ', 'end ', 'structure ', 'noncomputable ', '@[', 'private ', 'abbrev ')


def block(path, name):
    lines = (CDIR / path).read_text().split('\n')
    pat = re.compile(r'^(theorem|def|structure|abbrev) ' + re.escape(name) + r'\b')
    idx = [i for i, l in enumerate(lines) if pat.match(l)]
    assert len(idx) == 1, (path, name, idx)
    i = idx[0]
    s = i
    if i > 0 and lines[i - 1].rstrip().endswith('-/'):
        s = i - 1
        while not lines[s].startswith('/--'):
            s -= 1
    e = i + 1
    while e < len(lines) and not lines[e].startswith(STARTS):
        e += 1
    while lines[e - 1].strip() == '':
        e -= 1
    return '\n'.join(lines[s:e])


def sub(text, old, new, count):
    n = text.count(old)
    assert n == count, (old[:80], n, count)
    return text.replace(old, new)


HQ = '(hq : RunAtRT R ctx Y x mono sup q (CGoalL.next (Lazy.ofSure Sure.bunt) nexA.th) region g)'
HQN = '(hq : safeFolFol q = false → RunAtRT R ctx Y x mono sup q (CGoalL.next (Lazy.ofSure Sure.bunt) nexA.th) region g)'
F_CNF = [(HQ, HQN, 1), ('obtain ⟨x1, hy, hq1⟩ := hq\n', 'obtain ⟨x1, hy, hq1⟩ := hq hs\n', 1),
         ('theorem crd_cnfRT ', 'theorem crd_cnfRTQ ', 1)]
F_TAIL = [(HQ, HQN, 1), ('crd_cnfRT h7', 'crd_cnfRTQ h7', 1), ('theorem crd_ctailRT ', 'theorem crd_ctailRTQ ', 1)]

HEAD = '''import lemmas.Compiler.CompRunTCall

/-!
# The tail of a direct call with the run of `q` asked only when it runs (README Gaps 19 (g))

GENERATED by `tools/gen/tailq.py` from `CompRunTCall.lean`: `crd_cnfRTQ`, `crd_ctailRTQ` are
`crd_cnfRT`, `crd_ctailRT` with the hypothesis `hq` on the run of `q` under
`safeFolFol q = false` (the pill skips the run when `+safe-fol-fol` holds).  Do not edit by hand.
-/

namespace Formalization
namespace Compiler

open Nock Pill Hoon SkaModel SkaModel.Comp

set_option linter.unusedSimpArgs false
set_option linter.unusedSectionVars false
set_option linter.unusedVariables false

variable {ctx : Noun}

'''
parts = []
for name, fx in [('crd_cnfRT', F_CNF), ('crd_ctailRT', F_TAIL)]:
    t = block('CompRunTCall.lean', name)
    for o, n, c in fx:
        t = sub(t, o, n, c)
    parts.append(t)
(CDIR / 'CompRunTCallQ.lean').write_text(HEAD + '\n\n'.join(parts) + '\n\nend Compiler\nend Formalization\n')
print('ok')
