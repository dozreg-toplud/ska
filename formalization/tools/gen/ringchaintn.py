#!/usr/bin/env python3
"""Write lemmas/Compiler/CompRunTNG*.lean: the threaded run link at `mono` `|` (the n-ary run,
the TN chain) against `runLCMR env false` (calls through rings, track K, README Gaps 19 (h)).
Run from formalization/:  python3 tools/gen/ringchaintn.py

Sources: the RN chain (CompRunRN*.lean) and the TN chain (CompRunTN{Base,...,SixAll,Class}.lean),
themselves generated by runn.py.  The cases other than the direct call do not read the ring, and
`runLCMR` is `runLCM`'s text with the case `%2` as `callLMR` (Ska/CompRingRun.lean), so the copy
changes the model alone: `runLCM` -> `runLCMR` (and `callLM` / `callL` -> `callLMR` / `callLR`
where a proof unfolds the indirect `%2`).  A declaration is TAINTED when its text names `runLCM`
or a tainted declaration; the copies are the tainted declarations the goal theorems reach
(downward closure from GOALS), renamed `n` -> `nG`, every rename and patch asserted by count.
The direct call is the hand-written `comp_run_n2_directNTTG` (CompRunDirectRingN.lean) under
`CallOkTNG` (the ring `env.ring b` with `RinOkN`, in place of `env.ring b = none`).
"""
import re, sys

D = 'lemmas/Compiler/'

TOP = re.compile(r'^(?:/--|/-!|theorem |def |noncomputable def |structure |end |example|@\[|abbrev |variable |open |namespace |set_option |section)', re.M)
DECL = re.compile(r'^(?:/--.*?-/\s*)?(?:@\[[^\]]*\]\s*)?(?:theorem|def|noncomputable def|structure|abbrev) (\S+)', re.S)

def chunks(src):
    st = [m.start() for m in TOP.finditer(src)] + [len(src)]
    cs = [src[a:b] for a, b in zip(st, st[1:])]
    out = []
    i = 0
    while i < len(cs):
        if cs[i].startswith('/--') and i + 1 < len(cs):
            out.append(cs[i] + cs[i + 1]); i += 2
        else:
            out.append(cs[i]); i += 1
    return out

SRC = ['CompRunRNBase', 'CompRunRNRes', 'CompRunRNLeaf', 'CompRunRNCons', 'CompRunRNFive', 'CompRunRNTen',
       'CompRunRNSixS', 'CompRunRNSixN', 'CompRunRNSixF', 'CompRunRNSixL', 'CompRunRNSixAll',
       'CompRunTNBase', 'CompRunTNLeaf', 'CompRunTNCons', 'CompRunTNFive', 'CompRunTNTen',
       'CompRunTNSixS', 'CompRunTNSixN', 'CompRunTNSixF', 'CompRunTNSixL', 'CompRunTNSixAll',
       'CompRunTNClass']

def tgt(s):
    return 'CompRunTNG' + s[len('CompRunTN'):] if s.startswith('CompRunTN') else 'CompRunTNGR' + s[len('CompRunRN'):]

GOALS = ['comp_run_dirTN', 'comp_run_dirXTN', 'res_dirTN']
# names replaced by existing / hand-written ones, never copied
EXT = {'PartRTN': 'PartRTNR', 'CallOkTN': 'CallOkTNG', 'comp_run_n2_directNTT': 'comp_run_n2_directNTTG',
       'res_n2_directN': 'res_n2_directNR'}
# declarations copied although not tainted (they name a replaced name)
FORCE = {'DirCallsTN', 'callCode_of_dirTN'}

def refs(n, c):
    return re.search(r"(?<![\w.'])" + re.escape(n) + r"(?![\w'])", c) is not None

def sub_name(n, new, c):
    return re.sub(r"(?<![\w.'])" + re.escape(n) + r"(?![\w'])", new, c)

data = []
names = {}
for s in SRC:
    cs = chunks(open(D + s + '.lean').read())
    data.append((s, cs))
    for c in cs:
        m = DECL.match(c)
        if m:
            assert m.group(1) not in names, m.group(1)
            names[m.group(1)] = (s, c)

RUN = re.compile(r'(?<![\w.\'])runLCM(?![\w\'])')
taint = {n for n, (s, c) in names.items() if RUN.search(c)} | FORCE
taint -= set(EXT)
while True:
    more = {n for n, (s, c) in names.items() if n not in taint and n not in EXT
            and any(refs(k, c) for k in taint | set(EXT))}
    if not more:
        break
    taint |= more

copied = set()
todo = [g for g in GOALS]
while todo:
    n = todo.pop()
    if n in copied:
        continue
    assert n in taint, n
    copied.add(n)
    c = names[n][1]
    for k in taint:
        if k not in copied and refs(k, c):
            todo.append(k)

def newname(n):
    m = re.match(r"^(.*?)('*)$", n)
    return m.group(1) + 'G' + m.group(2)

ren = sorted(copied, key=len, reverse=True)

# per-declaration patches: (name, old, new, count)
PATCH = [
    ('runLCM_n2_noneN', 'simp only [runLCMR, callLM_none, callL] at h', 'simp only [runLCMR, callLMR, callLR] at h', 1),
    ('crx_of_runLCN', 'rw [runLCM_false env n msup]', 'rw [runLCMR_false_ndNG env hn msup]', 1),
    ('resR_of_resN', 'rw [runLCM_false env n msup] at e', 'rw [runLCMR_false_ndNG env hn msup] at e', 1),
    ('comp_run_dirTN', 'obtain ⟨⟨hcd, -, hri, nb, hnb, hsof, hE⟩, hdp, hdq⟩ := hd',
     'obtain ⟨⟨hcd, -, hro, nb, hnb, hsof, hE⟩, hdp, hdq⟩ := hd', 1),
    ('comp_run_dirTN', 'comp_run_n2_directNTTG (hY msup) h7 hcode env p q P Q b hcd nb hE hri hnb hsof goal g hi',
     'comp_run_n2_directNTTG (hY msup) h7 hcode env p q P Q b hcd (env.ring b) hro nb hE rfl hnb hsof goal g hi', 1),
    ('comp_run_dirTN', 'res_n2_directNR P.res Q.res hri hnb hsof', 'res_n2_directNR P.res Q.res hnb hsof', 1),
]
PATCHED = {}
for n, a, b, k in PATCH:
    PATCHED.setdefault(n, []).append((a, b, k))

def transform(n, c):
    c, k = RUN.subn('runLCMR', c)
    for e, new in EXT.items():
        c = sub_name(e, new, c)
    for m in ren:
        c = sub_name(m, newname(m), c)
    for a, b, k in PATCHED.get(n, []):
        assert c.count(a) == k, (n, a, c.count(a))
        c = c.replace(a, b)
    return c

PRELUDE = r'''
/-! ## What the copies take of the model -/

/-- With no direct call, `runLCMR` is `runLC` at `mono` `|` (`runLCMR_eq`, `runLCM_false`). -/
theorem ringFreeN_of_noDirectNG (env : CallEnv) : ∀ (nm : Nomm), nm.noDirect = true → RingFreeN env nm := by
  intro nm
  induction nm with
  | cons p q ihp ihq =>
    intro h; simp only [Nomm.noDirect, Bool.and_eq_true] at h; exact ⟨ihp h.1, ihq h.2⟩
  | n2 p q info ihp ihq =>
    intro h; simp only [Nomm.noDirect, Bool.and_eq_true] at h
    refine ⟨fun b k hk => ?_, ihp h.1.2, ihq h.2⟩
    rw [hk] at h; simp at h
  | n3 p ihp => intro h; exact ihp h
  | n4 p ihp => intro h; exact ihp h
  | n5 p q ihp ihq =>
    intro h; simp only [Nomm.noDirect, Bool.and_eq_true] at h; exact ⟨ihp h.1, ihq h.2⟩
  | n6 p q r ihp ihq ihr =>
    intro h; simp only [Nomm.noDirect, Bool.and_eq_true] at h; exact ⟨ihp h.1.1, ihq h.1.2, ihr h.2⟩
  | n7 p q ihp ihq =>
    intro h; simp only [Nomm.noDirect, Bool.and_eq_true] at h; exact ⟨ihp h.1, ihq h.2⟩
  | n10 a v q ihv ihq =>
    intro h; simp only [Nomm.noDirect, Bool.and_eq_true] at h; exact ⟨ihv h.1, ihq h.2⟩
  | n0 _ => intro _; trivial
  | n1 _ => intro _; trivial
  | n11s _ _ _ _ => intro _; trivial
  | n11d _ _ _ _ _ _ => intro _; trivial
  | n12 _ _ _ _ => intro _; trivial
  | mean _ _ _ _ _ _ _ => intro _; trivial

theorem runLCMR_false_ndNG {S : Type} [HoonSet S] {Map : Type → Type} [HoonMap Map] [HoonMapKeys Map]
    (env : CallEnv) {nm : Nomm} (h : nm.noDirect = true) (sup : Option Nomm) :
    (runLCMR env false sup nm : CGoalL S → List Nat → CM Map (NextL S)) = runLC env sup nm := by
  funext goal region
  rw [runLCMR_eq env false nm (ringFreeN_of_noDirectNG env nm h) sup goal region, runLCM_false]

'''

CLASS = r'''
/-! ## The direct call through a ring -/

/-- **What one direct call takes, threaded, through its ring** (`CallOkTN` with `env.ring b = none`
replaced by `RinOkN (env.ring b)`, the entry `env.ring b` read by `CallNounMTG`). -/
def CallOkTNG (env : CallEnv) (cod ctx : Noun) (E : GenRest → Prop) (Y : GenRest → GenRest → Prop)
    (msup : Option Nomm) (p q : Nomm) (b : Bell) : Prop :=
  CodePure cod env b ∧ env.cod b = some (env.pure b) ∧ RinOkN (env.ring b) ∧
    ∃ nb, env.need b = some nb ∧ env.sof (made p msup) p q b nb = false ∧ ∀ x, x.NoSoft → E x → ∃ x' sur, Y x x' ∧
      CallNounMTG msup ctx p q b nb sur x x' (A 1) (A 1) (env.ring b)

/-- The old `CallOkTN` (no ring) is a `CallOkTNG`. -/
theorem callOkTNG_of_TN {env : CallEnv} {cod : Noun} {E : GenRest → Prop} {Y : GenRest → GenRest → Prop}
    {msup : Option Nomm} {p q : Nomm} {b : Bell} (h : CallOkTN env cod ctx E Y msup p q b) :
    CallOkTNG env cod ctx E Y msup p q b := by
  obtain ⟨h1, h2, h3, nb, h4, h5, h6⟩ := h
  refine ⟨h1, h2, by rw [h3]; trivial, nb, h4, h5, fun x hx hE => ?_⟩
  obtain ⟨x', sur, hy, hT, -⟩ := h6 x hx hE
  exact ⟨x', sur, hy, by rw [h3]; exact callNounMTG_of_mt hT⟩

'''

TAIL = r'''
/-- **`DirCallsTN` gives `DirCallsTNG`**: the old hypothesis (no ring at any call) is the new one. -/
theorem dirCallsTNG_of_TN {env : CallEnv} {cod : Noun} {E : GenRest → Prop} {Y : GenRest → GenRest → Prop} :
    ∀ (ms : Option Nomm) (n : Nomm), DirCallsTN env cod ctx E Y ms n → DirCallsTNG env cod ctx E Y ms n
  | ms, Nomm.cons p q, h => ⟨dirCallsTNG_of_TN ms p h.1, dirCallsTNG_of_TN ms q h.2⟩
  | ms, Nomm.n2 p q Option.none, h => ⟨dirCallsTNG_of_TN ms p h.1, dirCallsTNG_of_TN ms q h.2⟩
  | ms, Nomm.n2 p q (some (b, _)), h => ⟨callOkTNG_of_TN h.1, dirCallsTNG_of_TN ms p h.2.1, dirCallsTNG_of_TN ms q h.2.2⟩
  | ms, Nomm.n3 p, h => dirCallsTNG_of_TN ms p h
  | ms, Nomm.n4 p, h => dirCallsTNG_of_TN ms p h
  | ms, Nomm.n5 p q, h => ⟨dirCallsTNG_of_TN ms p h.1, dirCallsTNG_of_TN ms q h.2⟩
  | ms, Nomm.n6 p q r, h => ⟨dirCallsTNG_of_TN ms p h.1, dirCallsTNG_of_TN ms q h.2.1, dirCallsTNG_of_TN ms r h.2.2⟩
  | ms, Nomm.n7 p q, h => ⟨dirCallsTNG_of_TN ms p h.1, dirCallsTNG_of_TN (some p) q h.2⟩
  | ms, Nomm.n10 _ v q, h => ⟨dirCallsTNG_of_TN ms v h.1, dirCallsTNG_of_TN ms q h.2⟩
  | _, Nomm.n0 _, _ => trivial
  | _, Nomm.n1 _, _ => trivial
  | _, Nomm.n11s _ _ _, _ => trivial
  | _, Nomm.n11d _ _ _ _, _ => trivial
  | _, Nomm.n12 _ _, _ => trivial
  | _, Nomm.mean _ _ _ _ _, _ => trivial

'''

HEAD_UNUSED = '''namespace Formalization
namespace Compiler

open Nock Pill Hoon SkaModel SkaModel.Comp

set_option linter.unusedSimpArgs false
set_option linter.unusedSectionVars false
set_option linter.unusedVariables false

variable {ctx : Noun}
'''

used = set()
prev = None
written = []
for s, cs in data:
    body = []
    ndecl = 0
    first = True
    for c in cs:
        m = DECL.match(c)
        if c.startswith('example') or c.startswith('/-!'):
            continue
        if m:
            if m.group(1) in copied:
                if first:
                    if prev is None:
                        body.append(PRELUDE)
                    if s == 'CompRunTNClass':
                        body.append(CLASS)
                    first = False
                body.append(transform(m.group(1), c))
                used.add(m.group(1))
                ndecl += 1
            else:
                body.extend(l + '\n' for l in c.split('\n') if re.match(r'^end\s*$', l))
        else:
            if c.startswith('end Compiler') and s == 'CompRunTNClass':
                body.append(TAIL)
            assert not re.search(r'\benv (true|false)\b', c), (s, c[:200])
            body.append(c)
    if not ndecl:
        continue
    t = tgt(s)
    imps = ['lemmas.Compiler.CompRunDirectRingN', 'lemmas.Ska.CompRingRunEq']
    if prev:
        imps.append('lemmas.Compiler.' + prev)
    else:
        imps += ['lemmas.Compiler.' + x for x in SRC if x != 'CompRunTNClass']
    if s == 'CompRunTNClass':
        imps.append('lemmas.Compiler.CompRunTNClass')
    head = ''.join('import ' + i + '\n' for i in imps)
    doc = ('\n/-!\n# `{s}.lean` against `runLCMR env false` (track K, README Gaps 19 (h))\n\n'
           'Generated by `tools/gen/ringchaintn.py` from `{s}.lean`: `runLCM` -> `runLCMR` (calls through\n'
           'rings), the declarations the goal theorems reach renamed `n` -> `nG`; do not edit.\n-/\n\n').format(s=s)
    txt = ''.join(body)
    assert not re.search(r"(?<![\w.'])runLCM(?![\w'])", txt), s
    open(D + t + '.lean', 'w').write(head + doc + txt)
    written.append(t)
    prev = t
assert used == copied, copied - used
print(len(copied), 'declarations copied into', ' '.join(written), file=sys.stderr)
