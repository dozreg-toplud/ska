#!/usr/bin/env python3
"""Generate lemmas/Ska/AnnotSBake.lean (track Q, InvBSR) from the originals.

`variant_annotK` is `variant_annot` (BakeGraph.lean) with an `AnnotK` datum
in and `Glue.AnnotS` out; `skaPokeB_soundK` is the CodeOKS strand of
`skaPokeB_sound` (PokeBake.lean): the setup and the `hcodeOK` block, with the
ghost of `PokeInvK` in place of `InvB`'s.  The originals are only read.
Usage: annots_bake.py FORMALIZATION_DIR OUT
"""
import sys

root, out = sys.argv[1], sys.argv[2]

def piece(path, start, end):
    s = open(root + '/' + path).read()
    assert s.count(start) == 1, (path, start)
    i = s.index(start)
    j = s.index(end, i)
    return s[i:j]

def rep(s, old, new, n=1):
    assert s.count(old) == n, (old, s.count(old))
    return s.replace(old, new)

# variant_annot
va = piece('lemmas/Ska/BakeGraph.lean', 'theorem variant_annot ', '\nend Bake')
va = rep(va, 'theorem variant_annot ', 'theorem variant_annotK ')
va = rep(va, '(hA : Annot lib code (Fits t.less) t.fol d.nomm)', '(hA : AnnotK lib code (Fits t.less) t.fol d.nomm)')
va = rep(va, '    Annot lib code\' (fun x => Fits t.less x ∧ Fits s x) t.fol nomm :=',
         '    Glue.AnnotS lib code\' (fun x => Fits t.less x ∧ Fits s x) t.fol nomm :=')
va = rep(va, '  know_annot hc', '  know_annotK hc')

# skaPokeB_sound: from its statement to the end of `hcodeOK`
sk = piece('lemmas/Ska/PokeBake.lean', 'theorem skaPokeB_sound ', '  have hnorm := bakes_norm hloop')
sk = rep(sk, 'theorem skaPokeB_sound ', 'theorem skaPokeB_soundK ')
sk = rep(sk, '{lib : Lib} (env : Env R)', '{lib : Lib} (hK : FolTopK lib) (env : Env R)')
sk = rep(sk, '    (hinv : InvB lib L) (hw',
         '    (hinv : InvB lib L) (hpk : ∃ code, PokeInvK lib L.memo code)\n'
         '    (hS : Glue.CodeOKS lib (realOf L.code)) (hw')
sk = rep(sk, '    InvB lib L\' ∧ ∃ nb, realOf L\'.code rb = some nb := by\n',
         '    InvB lib L\' ∧ (∃ code, PokeInvK lib L\'.memo code) ∧ Glue.CodeOKS lib (realOf L\'.code) ∧\n'
         '      ∃ nb, realOf L\'.code rb = some nb := by\n')
sk = rep(sk, '  obtain ⟨code, hpi⟩ := hinv.ghost\n',
         '  have hB := skaPokeB_sound env hinv hw hnr hnvr h\n  obtain ⟨code, hpi⟩ := hpk\n')
sk = rep(sk, '  obtain ⟨hpi\', -⟩ := skaPoke_sound env hpi hw hnr hnvr hsk\n'
             '  have hds := skaPoke_dats env hpi hw hnr hnvr hsk\n',
         '  obtain ⟨hpi\', hdsK⟩ := skaPoke_soundK hK env hpi hw hnr hnvr hsk\n'
         '  have hds := skaPoke_dats env hpi.base hw hnr hnvr hsk\n')
sk = rep(sk, '  obtain ⟨hdatOK, hA⟩ := pokeDat_ok hpi\' hlk\' hds\n',
         '  obtain ⟨hdatOK, -⟩ := pokeDat_ok hpi\'.base hlk\' hds\n'
         '  have hA := pokeDat_annotK hpi\' hlk\' hdsK\n')
sk = rep(sk, '  obtain ⟨f1, -, f3, f4⟩ := finalFold_spec', '  obtain ⟨f1, -, f3, -⟩ := finalFold_spec')
sk = rep(sk, '  obtain ⟨qs, hI⟩ := bakeLoop_inv E _ _ _ _ st (loopInv_init E) hloop\n', '')
sk = rep(sk, '  have hcodeOK : CodeOK lib code\' := by', '  have hcodeOK : Glue.CodeOKS lib code\' := by')
sk = rep(sk, '      exact (hinv.codeOK bl _ hr).mono_code hold', '      exact (hS bl _ hr).mono_code hold')
sk = rep(sk, 'variant_annot (code := extendCode code dats) (code\' := code\') hpi\'.codeOK',
         'variant_annotK (code := extendCode code dats) (code\' := code\') hpi\'.base.codeOK')
sk += ("  refine ⟨hB.1, ⟨_, hpi'⟩, hcodeOK, ?_⟩\n"
       "  rw [← hc', ← hE]; exact hB.2\n")

head = '''import lemmas.Ska.AnnotSKnow
import lemmas.Ska.AnnotSPoke

/-!
# `InvBSR`: the bake keeps `CodeOKS` (track Q, README Gaps 27)

Generated by `tools/gen/annots_bake.py` from `variant_annot`
(`BakeGraph.lean`) and `skaPokeB_sound` (`PokeBake.lean`).

`variant_annotK`: a variant of the final pass of `+bake-graph`, from a datum
whose nomm satisfies `AnnotK` (the analysis's, `pokeDat_annotK`), satisfies
`AnnotS` (`know_annotK`: `+know` keeps `DetK` or `KC`, so a droppable folded
formula part returns).

`skaPokeB_soundK`: a whole poke keeps `InvB` (by `skaPokeB_sound`), the
ghost `PokeInvK` of the memo (by `skaPoke_soundK`; its table need not be the
ghost table of `InvB`), and `CodeOKS` of the real table: an old entry by
`Glue.AnnotS.mono_code`, a new variant by `variant_annotK` on the subjects of
its bake.
-/

namespace Formalization
namespace SkaModel

open Nock Ana AnnotSF

namespace Bake

variable {M : Type → Type → Type} [Treap M] {R : Type}

'''
tail = '''
end Bake

end SkaModel
end Formalization
'''
open(out, 'w').write(head + va.rstrip() + '\n\n' + sk + tail)
