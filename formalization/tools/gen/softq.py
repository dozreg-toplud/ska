#!/usr/bin/env python3
"""Write lemmas/Compiler/CompRunSoftQ.lean: the cons and `%10` cases of `+run` at `mono` `|` with
the rest predicate `x.NoSoft` replaced by any `Q x` (README Gaps 19 (g)).

Copied from `CompRunTNCons.lean` and `CompRunTNTen.lean` (which only thread `x.NoSoft` through
`YOk.soft`): `CompRunAtXT` -> `CompRunAtXQ Q`, `YOk` -> `YOkQ Q`, `PartRTN` -> `PartRTQ Q`,
`(hx : x.NoSoft)` -> `(hx : Q x)`, `xt_trans` -> `xq_trans`, names `..TN` -> `..TQ`.
Asserted replacements; do not edit the output."""
import os, re
here = os.path.dirname(os.path.abspath(__file__))
C = os.path.join(here, '..', '..', 'lemmas', 'Compiler')

def body(path):
    s = open(os.path.join(C, path)).read()
    i = s.index('variable {ctx : Noun}')
    i = s.index('\n', i) + 1
    j = s.rindex('end Compiler')
    return s[i:j]

def rep(s, a, b):
    assert a in s, a
    return s.replace(a, b)

out = []
for f, names in [('CompRunTNCons.lean', ['crc_ntailLRTN', 'crc_nextLRTN', 'crc_pickLRTN', 'comp_run_consLRTN']),
                 ('CompRunTNTen.lean', ['cr10_tailLRTN', 'comp_run_n10LRTN'])]:
    s = body(f)
    s = rep(s, 'CompRunAtXT (runLCM env false msup) ctx X Y', 'CompRunAtXQ Qs (runLCM env false msup) ctx X Y')
    s = rep(s, '(hYk : YOk X Y)', '(hYk : YOkQ Qs X Y)')
    s = rep(s, 'PartRTN env msup ctx X Y', 'PartRTQ Qs env msup ctx X Y')
    s = rep(s, '(hx : x.NoSoft)', '(hx : Qs x)')
    if 'xt_trans' in s:
        s = s.replace('xt_trans', 'xq_trans')
    for n in names:
        assert n in s, n
        s = re.sub(r'\b' + n + r'\b', n[:-2] + 'TQ', s)
    assert 'NoSoft' not in s, f
    out.append(s)

head = '''import lemmas.Compiler.CompRunTNCons
import lemmas.Compiler.CompRunTNTen

/-!
# The cons and `%10` cases at any rest predicate (README Gaps 19 (g))

Generated by `tools/gen/softq.py` from `CompRunTNCons.lean` and `CompRunTNTen.lean`; do not edit.
Those cases read nothing of `soft`: they only thread `x.NoSoft` to the runs of their parts.  Here
the rest predicate is any `Q` kept along `Y` (`YOkQ`), so the same cases hold at a rest whose
`soft` is the noun of a non-empty map (after a soft call), with the parts' links at `Q`
(`PartRTQ`).

* `CompRunAtXQ Q`: `CompRunAtXT` with `Q x` for `x.NoSoft`; `YOkQ`, `xq_trans`, `PartRTQ`;
* **`comp_run_consLRTQ`**, **`comp_run_n10LRTQ`** (and their tails).
-/

namespace Formalization
namespace Compiler

open Nock Pill Hoon SkaModel SkaModel.Comp

set_option linter.unusedSimpArgs false
set_option linter.unusedSectionVars false
set_option linter.unusedVariables false

/-- **The threaded run link at the rest predicate `Q`**. -/
def CompRunAtXQ (Q : GenRest → Prop) (R : Nomm → CGoalL CSet → List Nat → CM (TreapMap mugF) (NextL CSet))
    (ctx : Noun) (X : GenRest → Noun → Noun → Prop) (Y : GenRest → GenRest → Prop) (n : Nomm) (goal : CGoalL CSet)
    (region : List Nat) (g : Gen (TreapMap mugF)) : Prop :=
  ∀ (x : GenRest) (mono sup : Noun), Q x → X x mono sup → ∃ x', Y x x' ∧
    nock (crSubj mono n.toNoun goal.toNoun (listNoun A region) sup (compCore g x ctx)) crDol
      = (R n goal region g).map fun p => C p.1.goal.toNoun (genNoun p.2 x')

/-- `YOk` with `Q` for `NoSoft`. -/
structure YOkQ (Q : GenRest → Prop) (X : GenRest → Noun → Noun → Prop) (Y : GenRest → GenRest → Prop) : Prop where
  refl : ∀ x, Y x x
  trans : ∀ {x y z : GenRest}, Y x y → Y y z → Y x z
  soft : ∀ {x y : GenRest}, Q x → Y x y → Q y
  pres : ∀ {x y : GenRest} {mono sup : Noun}, X x mono sup → Y x y → X y mono sup

theorem xq_trans {Q : GenRest → Prop} {X : GenRest → Noun → Noun → Prop} {Y : GenRest → GenRest → Prop}
    (hYk : YOkQ Q X Y) {x0 x : GenRest} (h0 : Y x0 x) {P : GenRest → Prop} (h : ∃ x', Y x x' ∧ P x') :
    ∃ x', Y x0 x' ∧ P x' := by
  obtain ⟨x', hy, hp⟩ := h
  exact ⟨x', hYk.trans h0 hy, hp⟩

/-- `PartRTN` at the rest predicate `Q`. -/
structure PartRTQ (Q : GenRest → Prop) (env : CallEnv) (msup : Option Nomm) (ctx : Noun)
    (X : GenRest → Noun → Noun → Prop) (Y : GenRest → GenRest → Prop) (n : Nomm) (region : List Nat) : Prop where
  link : ∀ (goal : CGoalL CSet) (g : Gen (TreapMap mugF)), GInv g goal →
    CompRunAtXQ Q (runLCM env false msup) ctx X Y n goal region g
  res : ResForR (runLCM env false msup) n region
  past : PastAt ctx env.cod n

variable {ctx : Noun} {X : GenRest → Noun → Noun → Prop} {Y : GenRest → GenRest → Prop} {Qs : GenRest → Prop}
'''
s = head + '\n'.join(out) + 'end Compiler\nend Formalization\n'
open(os.path.join(C, 'CompRunSoftQ.lean'), 'w').write(s)
print('ok', len(s))
