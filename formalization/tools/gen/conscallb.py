#!/usr/bin/env python3
"""Generate `consNC_bwd` of lemmas/Ska/CompConsCallB.lean from the output of
`conscall.py` (the text of `consNC_ok`): the same hypotheses with the head's
backward relation `SemNCB` and the tail's `+mink` run `MqB` added, the
conclusion `SemNCB` of the cons, no structural fields, and the head's
`GoalSemCM` at a tone `rh` that `SemNCB` gives (with `+mink`'s run of the
cons from `mink_consC_bwd`) in place of the one `minkF_consC` gives.  The
rest of the proof, from the head's `GoalSemCM` at `rh` to the cons's at `r`,
is the forward text unchanged.  Exact-match replacements with asserted
counts.  Usage: conscallb.py > body.lean (the text between the markers
`-- BEGIN consNC_bwd` and `-- END consNC_bwd` of CompConsCallB.lean)."""
import os, subprocess, sys
here = os.path.dirname(os.path.abspath(__file__))
body = subprocess.run([sys.executable, os.path.join(here, 'conscall.py')], capture_output=True, text=True,
                      check=True).stdout
def rep(a, b, n=1):
    global body
    c = body.count(a)
    assert c == n, (a, c)
    body = body.replace(a, b)
i = body.index('/-- **A cons whose head calls')
j = body.index('theorem consNC_ok {')
body = body[:i] + """/-- **A cons whose head calls, under a fork-free `%next`, backward**: the
hypotheses of `consNC_ok` with the head's `SemNCB` (`hpB`) and the tail's
`+mink` run (`MqB`): if the code returns, the copy block passes it to the
head's code, whose `SemNCB` gives `+mink`'s tone `rh` on the head with the
head's `GoalSemCM` at `rh`; `mink_consC_bwd` makes the cons's `+mink` run
from it, and the rest is the forward text of `consNC_ok`.  Generated by
`tools/gen/conscallb.py` from the output of `tools/gen/conscall.py`. -/
""" + body[j:]
rep('theorem consNC_ok {', 'theorem consNC_bwd {')
rep("""      r = toneOf tm (pureEval q s))
""", """      r = toneOf tm (pureEval q s))
    (MqB : ∀ {s gul : Noun} {tm : Trace}, P s → Mink lib gul tm s ft (toneOf tm (pureEval q s)))
""")
rep("""    (hp : RunOKNC lib P fh pp lp nexq.th g1 g2 nexp)
""", """    (hp : RunOKNC lib P fh pp lp nexq.th g1 g2 nexp)
    (hpB : SemNCB lib P fh lp nexq.th g1 g2 nexp)
""")
rep("""    RunOKNC lib P (C fh ft) pp sur th g0 g3 nex := by""", """    SemNCB lib P (C fh ft) sur th g0 g3 nex := by""")
i = body.index('  refine {\n    ext := hpre.trans E\'3')
j = body.index('  · -- the copy block')
body = body[:i] + '  intro cf hcf c ned σ Inv ν O gul hS hB st t tm s0 s hI htr hs ag hned regs hh hn res hres\n' + body[j:]
rep("""    obtain ⟨n', rh, hn', hmh, hr⟩ := minkF_consC hfh Mq hs hm
    have Hp := hp.sem cf hcf2 c ned σ Inv ν O n' gul hS (oracleFwd_le hF (Nat.le_of_lt hn')) st t tm
      s0 s rh hI htr hs hmh agP hned2 R1 hs1 hn1
""", """    obtain ⟨rh, hmh, Hp⟩ := hpB cf hcf2 c ned σ Inv ν O gul hS hB st t tm s0 s hI htr hs agP hned2 R1 hs1 hn1
      res (e1.symm.trans hres)
    obtain ⟨r, hmr, hr⟩ := mink_consC_bwd (q := q) hfh hmh (MqB hs)
    refine ⟨r, hmr, ?_⟩
""")
print(body, end='')
