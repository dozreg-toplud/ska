#!/usr/bin/env python3
"""Write lemmas/Compiler/CompRunShapeSixNCut.lean: the parts of `rs6Arm` that the case `%6` under
`[%next laz]` takes, cut out of the nouns of `CompRunShapeSixCaseCut.lean`.

* `sixTailN F1 F2 F3`: the runs of `r` and `q`, `+laze-sect`, `+laze-past-fork`, `+laze-big`, the
  run of `p` and `+laze-copy`, with the formulas of the three goals as holes.  `rs6Rest` is it on
  `[0 2]`, `[0 6]`, `[1 %pick ~]` (`goal-branch` twice, `%pick`); the fork of `rs6Kerf` on
  `[%next [0 5]]`, `[%next [0 12]]`, `[%next [0 254]]` (`goal-1`, `goal-0`, `this`).
* `rs6Kerf` as `?:  kerf-test  $(goal [%next this])  fork`: `rs6KTest`, `rs6KRec`, `rs6KLbr`
  (the call of `+laze-branch`) and the tail.
Every equation is checked by `rfl`, and here by assertion.  Run from `formalization/`.
"""
import re, sys
sys.setrecursionlimit(100000)
SRC = 'lemmas/Compiler/CompRunShapeSixCaseCut.lean'
OUT = 'lemmas/Compiler/CompRunShapeSixNCut.lean'
src = open(SRC).read()
defs = {m.group(1): m.group(2) for m in re.finditer(r'^def (\w+) : Noun :=\n  (.*)$', src, re.M)}
tokre = re.compile(r'\(|\)|[A-Za-z_][A-Za-z0-9_.]*|0x[0-9a-fA-F]+|[0-9]+')

def parse(text):
    toks = tokre.findall(text); pos = [0]
    def e():
        t = toks[pos[0]]
        if t == '(':
            pos[0] += 1; x = e(); assert toks[pos[0]] == ')'; pos[0] += 1; return x
        if t == 'C':
            pos[0] += 1; a = e(); b = e(); return ('C', a, b)
        if t == 'A':
            pos[0] += 1; n = int(toks[pos[0]], 0); pos[0] += 1; return ('A', n)
        pos[0] += 1; return ('R', t)
    x = e(); assert pos[0] == len(toks); return x

def lean(n):
    if n[0] == 'A':
        return '(A %s)' % (str(n[1]) if n[1] < 1000 else hex(n[1]))
    if n[0] == 'R':
        return n[1]
    return '(C %s %s)' % (lean(n[1]), lean(n[2]))

def A(k): return ('A', k)
def C(a, b): return ('C', a, b)
def L(*xs):
    r = xs[-1]
    for x in reversed(xs[:-1]): r = C(x, r)
    return r

rest = parse(defs['rs6Rest'])
kerf = parse(defs['rs6Kerf'])
NEXT = 0x7478656e
F_rest = [L(A(0), A(2)), L(A(0), A(6)), L(A(1), A(0x6b636970), A(0))]
F_kerf = [L(L(A(1), A(NEXT)), A(0), A(5)), L(L(A(1), A(NEXT)), A(0), A(12)), L(L(A(1), A(NEXT)), A(0), A(254))]

def subst(n, olds, holes):
    """Replace the subterm `[26 F]` for each F in olds (in order of a preorder walk) by `[26 hole]`."""
    found = []
    def go(x):
        if x[0] == 'C' and x[1] == A(26) and x[2] in olds:
            i = olds.index(x[2]); found.append(i)
            return C(A(26), ('R', holes[i]))
        if x[0] == 'C':
            return C(go(x[1]), go(x[2]))
        return x
    y = go(n)
    assert found == [0, 1, 2], found
    return y

tailT = subst(rest, F_rest, ['F1', 'F2', 'F3'])
def inst(n, fs):
    if n[0] == 'R' and n[1] in ('F1', 'F2', 'F3'):
        return fs[int(n[1][1]) - 1]
    if n[0] == 'C':
        return C(inst(n[1], fs), inst(n[2], fs))
    return n
assert inst(tailT, F_rest) == rest
# rs6Kerf = [6 KTEST KREC [7 [0 1] [8 [KLBR [7 [10 [1022 0 5] 0 1] [7 [[0 4] 0 3] TAIL]]]]]]
assert kerf[0] == 'C' and kerf[1] == A(6)
ktest = kerf[2][1]
krec = kerf[2][2][1]
kfork = kerf[2][2][2]
assert kfork[1] == A(7) and kfork[2][1] == L(A(0), A(1))
k8 = kfork[2][2]
assert k8[1] == A(8)
klbr = k8[2][1]
k7 = k8[2][2]
assert k7[1] == A(7) and k7[2][1] == L(A(10), L(A(1022), A(0), A(5)), A(0), A(1))
k7b = k7[2][2]
assert k7b[1] == A(7) and k7b[2][1] == L(L(A(0), A(4)), A(0), A(3))
ktail = k7b[2][2]
assert inst(tailT, F_kerf) == ktail
assert klbr == L(A(7), L(A(0), A(1)), A(8), L(A(9), A(0x15576), A(0), A(127)), A(9), A(2), A(10), L(A(6), A(0), A(2037)), A(0), A(2))
assert krec == L(A(9), A(2), A(10), L(A(26), L(A(1), A(NEXT)), A(0), A(14)), A(0), A(31))

out = '''import lemmas.Compiler.CompRunShapeSixCaseCut

/-!
# The parts of `rs6Arm` for `%6` under `[%next laz]` (track A, 2026-11-28)

Generated by `tools/gen/runshapesixn.py` from `CompRunShapeSixCaseCut.lean`; do not edit by hand.

* `sixTailN F1 F2 F3`: the runs of `r` (goal `F1`) and `q` (goal `F2`), `+laze-sect`,
  `+laze-past-fork`, `+laze-big`, the run of `p` (goal `F3`), `+laze-copy`.  `rs6Rest_tail`:
  `rs6Rest` is it on `goal-branch`, `goal-branch`, `[%pick ~]`.
* `rs6Kerf_eq`: `rs6Kerf` is `?:  rs6KTest  rs6KRec  fork`, with `rs6KRec` the recursion
  `$(goal [%next this])` and the fork the call of `+laze-branch` (`rs6KLbr`), its `=^`, and
  `sixTailN` on `[%next goal-1]`, `[%next goal-0]`, `[%next this]`.
-/

namespace Formalization
namespace Compiler

open Nock Pill Hoon

/-- The tail of the case, with the formulas of the three goals as holes. -/
def sixTailN (F1 F2 F3 : Noun) : Noun :=
  @TAIL@

/-- The test of the kerf: `?|  &((whole q) (whole r))  (laze-this-only laz)  (laze-big laz)
(laze-soft-fork laz q r)  ==`. -/
def rs6KTest : Noun :=
  @KTEST@

/-- `$(goal [%next this])`. -/
def rs6KRec : Noun :=
  @KREC@

/-- `(laze-branch laz.goal)`. -/
def rs6KLbr : Noun :=
  @KLBR@

theorem rs6Rest_tail : rs6Rest = sixTailN @R1@ @R2@ @R3@ := rfl

theorem rs6Kerf_eq : rs6Kerf = C (A 6) (C rs6KTest (C rs6KRec (C (A 7) (C (C (A 0) (A 1)) (C (A 8) (C rs6KLbr
    (C (A 7) (C (C (A 10) (C (C (A 1022) (C (A 0) (A 5))) (C (A 0) (A 1)))) (C (A 7) (C (C (C (A 0) (A 4)) (C (A 0) (A 3)))
    (sixTailN @K1@ @K2@ @K3@))))))))))) := rfl

end Compiler
end Formalization
'''
for k, v in [('@TAIL@', lean(tailT)), ('@KTEST@', lean(ktest)), ('@KREC@', lean(krec)), ('@KLBR@', lean(klbr)),
             ('@R1@', lean(F_rest[0])), ('@R2@', lean(F_rest[1])), ('@R3@', lean(F_rest[2])),
             ('@K1@', lean(F_kerf[0])), ('@K2@', lean(F_kerf[1])), ('@K3@', lean(F_kerf[2]))]:
    assert out.count(k) == 1, k
    out = out.replace(k, v)
open(OUT, 'w').write(out)
print('wrote', OUT)
