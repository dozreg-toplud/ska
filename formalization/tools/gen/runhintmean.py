#!/usr/bin/env python3
"""Read the output of tools/hoon/hintmean.hoon (runhoon.sh) and
* --sum OUT: per entry and subject, whether the raw whole-subject code under +eval-blob gives
  +mink's tone (no scry gate and with the gate), traces as in hintcheck.py (a %meac / %meaf
  frame stands for a %mean frame);
* --lean OUT: write lemmas/Compiler/CompRunHintMeanData.lean, the cued jam of each entry
  ([nomm [need nargs blocks] [need nargs blocks] formula subjects table]) as a Lean `Noun`.
"""
import sys, re, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hintcheck as H

def text(path):
    t = open(path).read()
    t = re.sub(r'"[^"]*"', 'TAPE', t)
    return re.sub(r'^\s*(mink-g|ir-g|mink|ir)\s*$', '', t, flags=re.M)

if __name__ == '__main__':
    mode, path = sys.argv[1], sys.argv[2]
    recs = [H.parse(r) for r in H.records(text(path))]
    if mode == '--sum':
        ok = bad = 0; seen = set(); cases = set()
        for r in recs:
            if repr(r) in seen: continue
            seen.add(repr(r))
            if H.strip(r[0]) != '%run': continue
            nam = r[1][0]; rest = r[1][1]; sub = rest[0]
            mk, ir, mkg, irg = rest[1][0], rest[1][1][0], rest[1][1][1][0], rest[1][1][1][1]
            cases.add(nam)
            for (a, b, g) in ((mk, ir, '~'), (mkg, irg, 'gul')):
                if H.same(a, b): ok += 1
                else:
                    bad += 1; print('DIFF', nam, g, 'sub', H.strip(sub), 'mink', H.strip(a), 'ir', H.strip(b))
        print('entries', len(cases), 'runs', ok + bad, 'same', ok, 'diff', bad)
    else:
        out = ['import lemmas.Ska.Types', '',
               '/-! Generated by `tools/gen/runhintmean.py --lean` from the output of',
               '`tools/hoon/hintmean.hoon` (README Gaps 25): per entry the cued jam of `[nomm [need',
               'nargs blocks] [need nargs blocks] formula subjects table]` (the whole-subject and the',
               'n-ary raw blocks, sorted by label; the table: `[bell pure nomm (unit need)]` of the',
               'bells the nomm names). -/', '',
               'namespace Formalization', 'namespace SkaModel', 'namespace MeanData', '', 'open Nock', '']
        names = []
        for r in recs:
            if H.strip(r[0]) != '%jam': continue
            nam = H.strip(r[1][0]).lstrip('%'); a = H.atom(r[1][1])
            if nam in names: continue
            out.append(f'def j{nam} : Noun :=\n  {H.lean(H.cue(a))}\n')
            names.append(nam)
        assert len(names) >= 20, names
        out.append('def all : List (String × Noun) := [' + ', '.join(f'("{n}", j{n})' for n in names) + ']')
        out += ['', 'end MeanData', 'end SkaModel', 'end Formalization', '']
        open('lemmas/Compiler/CompRunHintMeanData.lean', 'w').write('\n'.join(out))
        print('wrote', len(names), 'entries')
