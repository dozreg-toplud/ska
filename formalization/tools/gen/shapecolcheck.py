#!/usr/bin/env python3
"""Write lemmas/Ska/ShapeColCheck.lean from the output of tools/hoon/shapecoldump.hoon.

usage: shapecolcheck.py DUMP.txt OUT.lean

Each `[%sc %name [laz less res]]` print becomes a `#guard` that `shapeCol` (with the
sets as lists in the order of +rep:in, `LS`) gives `res`, and a `#guard` that says
whether `+sure-of` of the sure part alone (`sccSur`, the old `ord`) gives the same.
"""
import re, sys

TAG = {1752461154: 'both', 1936287860: 'this', 1701736302: 'none'}

def tokens(s):
    for m in re.finditer(r'\[|\]|%[a-z0-9-]+|[0-9][0-9.]*', s):
        yield m.group(0)

def parse(toks):
    t = next(toks)
    if t == '[':
        items = []
        while True:
            x = parse(toks)
            if x == ']':
                break
            items.append(x)
        # right-associated tuple
        r = items[-1]
        for x in reversed(items[:-1]):
            r = (x, r)
        return r
    if t == ']':
        return ']'
    if t.startswith('%'):
        return t
    return int(t.replace('.', ''))

def ordL(n):
    if isinstance(n, tuple) and isinstance(n[0], tuple):
        return f'(NeedOrd.pair {ordL(n[0])} {ordL(n[1])})'
    tag = TAG[n[0]]
    if tag == 'both':
        return f'(NeedOrd.both {ordL(n[1][0])} {ordL(n[1][1])})'
    return f'NeedOrd.{tag}'

def needL(n):
    if isinstance(n[0], tuple):
        return f'(Need.pair {needL(n[0])} {needL(n[1])})'
    tag = TAG[n[0]]
    if tag == 'both':
        return f'(Need.both {n[1][0]} {needL(n[1][1][0])} {needL(n[1][1][1])})'
    if tag == 'this':
        return f'(Need.this {n[1]})'
    return 'Need.none'

def listP(n):
    out = []
    while n != 0:
        out.append(n[0]); n = n[1]
    return out

def capeL(n):
    if n == 0: return 'Cape.yes'
    if n == 1: return 'Cape.no'
    return f'(Cape.cell {capeL(n[0])} {capeL(n[1])})'

def lazyL(n):
    (ned, lok), (fk, bd) = n[0], n[1]
    lok = ', '.join(str(x) for x in listP(lok))
    forks = ', '.join(f'(({y[0]}, {lazyL(y[1])}), ({nn[0]}, {lazyL(nn[1])}))' for (y, nn) in listP(fk))
    bonds = ', '.join(f'({b[0]}, {lazyL(b[1])})' for b in listP(bd))
    return f'(Lazy.mk ⟨{needL(ned)}, ⟨[{lok}]⟩⟩ [{forks}] [{bonds}])'

def main():
    src, out = sys.argv[1], sys.argv[2]
    # with a third argument, the build log of a first pass: the `#eval`s become `#guard`s
    pol = None
    if len(sys.argv) > 3:
        pol = [l.split(': ')[-1].strip() == 'true' for l in open(sys.argv[3]) if l.startswith('info:')]
    txt = open(src).read()
    cases = []
    for m in re.finditer(r'\[\s*%sc\s+(%[a-z0-9]+)(.*?)(?=\n\[\s*%nomm)', txt, re.S):
        name = m.group(1)[1:]
        body = parse(tokens('[' + m.group(2)))
        laz, (less, res) = body[0], body[1]
        mm = re.search(r'\[\s*%nomm\s+%' + name + r'\s+(.*?)\]\n\[\s*%res', txt, re.S)
        noms = ' '.join(mm.group(1).split()) if mm else ''
        if any(c[0] == name for c in cases):
            assert [c for c in cases if c[0] == name][0][2:] == (laz, less, res), name
            continue
        cases.append((name, noms, laz, less, res))
    L = ['import lemmas.Ska.ShapeCol', '',
         '/-!', '# `+shape-collapse` against the real compiler',
         '',
         'Generated by `tools/gen/shapecolcheck.py` from the output of',
         '`tools/hoon/shapecoldump.hoon` (2026-11-27): for each formula, the lazy need',
         '`laz.nex` of its one-bell final pass, the cape, and the product of',
         '`+shape-collapse`.  `shapeCol` gives that product on every case, and',
         '`sccSur` (`+sure-of` of the sure part, the old `ord`) is marked where it',
         'gives the same (`= some`) or not (`≠ some`).',
         '-/', '',
         'namespace Formalization', 'namespace SkaModel', 'namespace Comp', '',
         'open Nock Compiler', '']
    same = 0
    for (name, noms, laz, less, res) in cases:
        L.append(f'/-- `%{name}`: `{noms}`. -/')
        L.append(f'def sc_{name}_laz : Lazy LS := {lazyL(laz)}')
        L.append(f'def sc_{name}_res : NeedOrd := {ordL(res)}')
        L.append(f'#guard shapeCol 64 sc_{name}_laz {capeL(less)} = some sc_{name}_res')
        L.append('')
    L += ['/-! ## The old `ord`: `+sure-of` of the sure part alone -/', '']
    for k, (name, noms, laz, less, res) in enumerate(cases):
        if pol is not None:
            same += pol[k]
            rel = '=' if pol[k] else '≠'
            L.append(f'#guard sureOfS (needToOrd sc_{name}_laz.sure.ned) sc_{name}_laz.sure.lok {capeL(less)} {rel} some sc_{name}_res')
            continue
        L.append(f'#eval decide (sureOfS (needToOrd sc_{name}_laz.sure.ned) sc_{name}_laz.sure.lok {capeL(less)} = some sc_{name}_res)')
    L += ['', 'end Comp', 'end SkaModel', 'end Formalization', '']
    open(out, 'w').write('\n'.join(L))
    print(len(cases), 'cases', same, 'same')

main()
