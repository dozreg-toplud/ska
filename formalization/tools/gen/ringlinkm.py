def decl(path, name):
    """The text of the declaration `name` (from its line to the next blank line before a
    docstring, declaration or section end)."""
    lines = open(path).read().split("\n")
    start = None
    for i, l in enumerate(lines):
        if re.match(r"^(theorem|def|noncomputable def|abbrev|noncomputable abbrev) " + re.escape(name) + r"\b", l):
            start = i
            break
    assert start is not None, name
    end = start + 1
    while end < len(lines):
        l = lines[end]
        if l == "" and end + 1 < len(lines) and re.match(r"^(/--|/-!|theorem|def|noncomputable|abbrev|end|section)", lines[end + 1]):
            break
        if l == "" and end + 1 < len(lines) and lines[end + 1] == "":
            break
        end += 1
    return "\n".join(lines[start:end])


def rep(text, pairs):
    for old, new, n in pairs:
        c = text.count(old)
        assert c == n, (old, c, n)
        text = text.replace(old, new)
    return text


