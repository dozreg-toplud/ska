"""The #guard checks of lemmas/Ska/PokeFlagsCheck.lean from the output of
tools/hoon/flagsck.hoon (track P, README Gaps 23, sixth session): after each
poke, the SCC loop of the model (`sccLoop` of lemmas/Ska/PokeFlags.lean), run
over the SCCs of the whole table callees first from no flags at all, gives
every key of `code` the flags the real compiler wrote.
usage: flagscheck.py OUT.txt > lemmas/Ska/PokeFlagsCheck.lean
       flagscheck.py --trim OUT.txt > tools/hoon/flagsck.txt"""
import re, sys
tok = re.compile(r'\[|\]|%\.[yn]|%[a-z0-9-]+|~|&|\||[0-9][0-9.]*')
def cord(s):
    return int.from_bytes(s.encode(), 'little')
def parse(ts, i):
    t = ts[i]
    if t == '[':
        items = []; i += 1
        while ts[i] != ']':
            x, i = parse(ts, i); items.append(x)
        i += 1
        n = items[-1]
        for x in reversed(items[:-1]): n = (x, n)
        return n, i
    if t in ('%.y', '&', '~'): return 0, i + 1
    if t in ('%.n', '|'): return 1, i + 1
    if t.startswith('%'): return cord(t[1:]), i + 1
    return int(t.replace('.', '')), i + 1
def lean(n):
    if isinstance(n, int): return f'(A {n})' if n < 10**6 else f'(A {hex(n)})'
    return f'(C {lean(n[0])} {lean(n[1])})'
def hlist(n):
    out = []
    while isinstance(n, tuple):
        out.append(n[0]); n = n[1]
    return out
def records(path):
    ts = tok.findall(open(path).read())
    NB, PK = cord('nb'), cord('pk')
    nb, pk = {}, {}
    i = 0
    while i < len(ts):
        if ts[i] == '[' and ts[i + 1] in ('%nb', '%pk'):
            n, i = parse(ts, i)
            if n[0] == NB:
                ph, (k, (b, nm)) = n[1][0], n[1][1]
                key = (ph, k)
                if key in nb: assert nb[key] == (b, nm), key
                else: nb[key] = (b, nm)
            else:
                ph, (k, (sc, fs)) = n[1][0], n[1][1]
                key = (ph, k)
                if key in pk: assert pk[key] == (sc, fs), key
                else: pk[key] = (sc, fs)
        else:
            i += 1
    return nb, pk
def show(n):
    if isinstance(n, int): return str(n)
    return '[' + ' '.join(show(x) for x in [n[0]] + ([n[1]] if not isinstance(n[1], tuple) else hlistT(n[1]))) + ']'
def hlistT(n):
    out = []
    while isinstance(n, tuple):
        out.append(n[0]); n = n[1]
    out.append(n)
    return out
if sys.argv[1] == '--trim':
    nb, pk = records(sys.argv[2])
    print('flagsck.hoon on 2026-11-27 (first run of the two the harness makes), raw nouns')
    for ph in sorted({k[0] for k in pk}):
        for k in sorted(x[1] for x in nb if x[0] == ph):
            b, nm = nb[(ph, k)]
            print(f'nb {ph} {k} {show(b)} {show(nm)}')
        for k in sorted(x[1] for x in pk if x[0] == ph):
            sc, fs = pk[(ph, k)]
            print(f'pk {ph} {k} {show(sc)} {show(fs)}')
    sys.exit(0)
nb, pk = records(sys.argv[1])
phases = sorted({k[0] for k in pk})
out = []
out.append('''import lemmas.Ska.PokeFlags

/-!
# The flags of `code` against the real compiler

Generated by `tools/gen/flagscheck.py` from the output of
`tools/hoon/flagsck.hoon` (track P, README Gaps 23, sixth session).  Phase 0
is the 32 pokes of `tools/hoon/invdump2.hoon` (`%full`, `%fast` with and
without `reset`, `%jets` that drop compiled bells, `%dire`), phase 1 the 21
`%full` pokes of `tools/hoon/sprestdump.hoon` from a fresh state.  After each
poke the driver dumped every entry of `code` (its bell and nomm, once per
phase), the SCCs of the whole table callees first (`(flop (tarjan g))`, `g`
the `calls` restricted to keys, as `+ska-poke` builds it), each SCC as its
members in `~(rep in scc)` order, and the flags `[pure total]` of every key.

Each `#guard`: the table decodes (`nommOf` inverts `Nomm.toNoun`), every key
is in exactly one listed SCC, and `sccLoop` of `PokeFlags.lean` over that
SCC list, from NO flags (`fun _ => none`: a bell of a later SCC is not there,
as in the loop of `+ska-poke`), returns and gives every key the dumped flags.
So `+eval-finalized` and the loop are modelled exactly on these tables, and the
flags of every entry are the replay over the whole table (history
independence, after `%jets` and `%fast` too).  The last `#guard` flips one
flag and shows the check fails.
-/

namespace Formalization
namespace SkaModel
namespace PokeF
namespace FlagsCheck

open Nock

/-- A unit noun: `~` or `[~ x]`. -/
def unitOf : Noun → Option (Option Noun)
  | Noun.atom 0 => some none
  | Noun.cell (Noun.atom 0) x => some (some x)
  | _ => none

/-- The `info` of a `%2`: `(unit [bell (unit *)])`. -/
def infoOf : Noun → Option (Option (Bell × Option Noun))
  | Noun.atom 0 => some none
  | Noun.cell (Noun.atom 0) (Noun.cell b k) =>
    (Bell.ofNoun? b).bind fun bl => (unitOf k).map fun kk => some (bl, kk)
  | _ => none

/-- The nomm of a noun: the inverse of `Nomm.toNoun`. -/
def nommOf : Noun → Option Nomm
  | Noun.cell (Noun.cell a b) q => (nommOf (Noun.cell a b)).bind fun x => (nommOf q).map fun y => Nomm.cons x y
  | Noun.cell (Noun.atom 0) (Noun.atom p) => some (Nomm.n0 p)
  | Noun.cell (Noun.atom 1) x => some (Nomm.n1 x)
  | Noun.cell (Noun.atom 2) (Noun.cell p (Noun.cell q u)) =>
    (nommOf p).bind fun x => (nommOf q).bind fun y => (infoOf u).map fun i => Nomm.n2 x y i
  | Noun.cell (Noun.atom 3) p => (nommOf p).map Nomm.n3
  | Noun.cell (Noun.atom 4) p => (nommOf p).map Nomm.n4
  | Noun.cell (Noun.atom 5) (Noun.cell p q) => (nommOf p).bind fun x => (nommOf q).map fun y => Nomm.n5 x y
  | Noun.cell (Noun.atom 6) (Noun.cell p (Noun.cell q r)) =>
    (nommOf p).bind fun x => (nommOf q).bind fun y => (nommOf r).map fun z => Nomm.n6 x y z
  | Noun.cell (Noun.atom 7) (Noun.cell p q) => (nommOf p).bind fun x => (nommOf q).map fun y => Nomm.n7 x y
  | Noun.cell (Noun.atom 10) (Noun.cell (Noun.cell (Noun.atom a) v) q) =>
    (nommOf v).bind fun x => (nommOf q).map fun y => Nomm.n10 a x y
  | Noun.cell (Noun.atom 11) (Noun.cell (Noun.atom t) (Noun.cell q body)) =>
    (nommOf q).map fun y => Nomm.n11s t y body
  | Noun.cell (Noun.atom 11) (Noun.cell (Noun.cell (Noun.atom t) h) (Noun.cell q body)) =>
    (nommOf h).bind fun x => (nommOf q).map fun y => Nomm.n11d t x y body
  | Noun.cell (Noun.atom 12) (Noun.cell p q) => (nommOf p).bind fun x => (nommOf q).map fun y => Nomm.n12 x y
  | Noun.cell (Noun.atom t) (Noun.cell p (Noun.cell b (Noun.cell q (Noun.cell body k)))) =>
    if t = Tag.mean then
      (nommOf p).bind fun x => (Bell.ofNoun? b).bind fun bl => (nommOf q).bind fun y =>
        (unitOf k).map fun kk => Nomm.mean x bl y body kk
    else none
  | _ => none

/-- The table of a phase, decoded. -/
def decTab (tab : List (Noun × Noun)) : Option (List (Bell × Nomm)) :=
  tab.mapM fun e => (Bell.ofNoun? e.1).bind fun b => (nommOf e.2).map fun n => (b, n)

/-- **One poke**: the table decodes, every key is in exactly one SCC, and
the model's loop over the SCCs from no flags gives every key its flags. -/
def checkPoke (tab : List (Noun × Noun)) (sccs : List (List Nat)) (fs : List (Nat × Bool × Bool)) : Bool :=
  match decTab tab with
  | none => false
  | some dt =>
    let bellAt : Nat → Option Bell := fun i => (dt[i]?).map (·.1)
    let nm : Bell → Option Nomm := fun b => dt.lookup b
    let ks := sccs.flatten
    (ks.length == fs.length && fs.all (fun e => ks.contains e.1)) &&
    match sccs.mapM (fun s => s.mapM bellAt) with
    | none => false
    | some sb =>
      match sccLoop nm (fun _ => none) sb with
      | none => false
      | some ft => fs.all fun e =>
        match bellAt e.1 with
        | some b => ft b == some (e.2.1, e.2.2)
        | none => false
''')
stats = []
for ph in phases:
    ks = sorted(x[1] for x in nb if x[0] == ph)
    assert ks == list(range(len(ks)))
    out.append(f'/-- The bells and nomms of phase {ph}, by index. -/')
    out.append(f'def tab{ph} : List (Noun × Noun) := [')
    out.append(',\n'.join(f'  ({lean(nb[(ph, k)][0])}, {lean(nb[(ph, k)][1])})' for k in ks))
    out.append(']\n')
    for k in sorted(x[1] for x in pk if x[0] == ph):
        sc, fs = pk[(ph, k)]
        scl = [hlist(s) for s in hlist(sc)]
        fsl = []
        for e in hlist(fs):
            i, (p, t) = e
            fsl.append((i, p == 0, t == 0))
        stats.append((ph, k, len(fsl), [len(s) for s in scl if len(s) > 1]))
        sct = '[' + ', '.join('[' + ', '.join(map(str, s)) + ']' for s in scl) + ']'
        fst = '[' + ', '.join(f'({i}, {str(p).lower()}, {str(t).lower()})' for i, p, t in fsl) + ']'
        out.append(f'def p{ph}_{k} : List (List Nat) × List (Nat × Bool × Bool) :=\n  ({sct},\n   {fst})')
        out.append(f'#guard checkPoke tab{ph} p{ph}_{k}.1 p{ph}_{k}.2\n')
# the negative check: flip the pure flag of the first entry of the last poke of phase 0
ph = phases[0]
k = max(x[1] for x in pk if x[0] == ph)
out.append(f'''/-- The check bites: one flag flipped. -/
def flipFirst (fs : List (Nat × Bool × Bool)) : List (Nat × Bool × Bool) :=
  match fs with
  | [] => []
  | (i, p, t) :: r => (i, !p, t) :: r

#guard !(checkPoke tab{ph} p{ph}_{k}.1 (flipFirst p{ph}_{k}.2))
''')
out.append('end FlagsCheck\nend PokeF\nend SkaModel\nend Formalization')
print('\n'.join(out))
tot = sum(s[2] for s in stats)
multi = [s for s in stats if s[3]]
sys.stderr.write(f'pokes {len(stats)}, entries checked {tot}, pokes with multi-bell SCCs {len(multi)}: '
                 + ' '.join(f'{s[0]}.{s[1]}:{s[3]}' for s in multi) + '\n')
