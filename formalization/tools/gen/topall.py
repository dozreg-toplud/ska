#!/usr/bin/env python3
"""Generate `finishTop_genA` (lemmas/Ska/CompConsCallTop.lean) from
`finishTop_gen` (lemmas/Ska/CompIndirectTop.lean): the property of the run's
code is asked with the program agreeing with the run at every state of the
oracle, which the proof gives (the ops of `+kern` do not touch the state).
Exact-match replacements with asserted counts; prints the theorem."""
import os
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, '../../lemmas/Ska/CompIndirectTop.lean')).read()
i = src.index('theorem finishTop_gen ')
j = src.index('/-! ## The blocks before the runs of the indirect call -/')
body = src[i:j].rstrip() + '\n'
def rep(a, b, n=1):
    global body
    c = body.count(a)
    assert c == n, (a, c)
    body = body.replace(a, b)
rep('theorem finishTop_gen ', 'theorem finishTop_genA ')
rep("""      AgreeU lib O c gul st t cf ned gen0 g1 nex.laz s s → (∀ r, NMem ned r → g1.re ≤ r) →""",
    """      (∀ st' : σ, AgreeU lib O c gul st' t cf ned gen0 g1 nex.laz s s) → (∀ r, NMem ned r → g1.re ≤ r) →""")
rep("""  have ag : AgreeU lib O c1 gul st t g4.cond (Need.this g1.re) gen0 g1 nex.laz s s := by
    refine""", """  have ag : ∀ st' : σ, AgreeU lib O c1 gul st' t g4.cond (Need.this g1.re) gen0 g1 nex.laz s s := fun st' => by
    refine""")
rep("""        obtain ⟨S1, S2⟩ := KS lib σ O c1 gul st t R s hR""", """        obtain ⟨S1, S2⟩ := KS lib σ O c1 gul st' t R s hR""")
doc = """/-- **`finishTop_gen` with the program agreeing at every state**: the
`AgreeU` handed to `hsem` holds at every state of the oracle, as a run that
calls asks (`SemNC`).  Generated by `tools/gen/topall.py`. -/
"""
print(doc + body, end='')
