#!/usr/bin/env python3
"""Read the output of tools/hoon/hintdump.hoon (runhoon.sh) and
* --sum OUT: print, per case and subject, whether the raw whole-subject code under
  +eval-blob gives +mink's tone (no scry gate and with the gate), traces compared as
  raw frames except that a %meac / %meaf frame stands for a %mean frame;
* --lean OUT: write lemmas/Ska/CompHintData.lean, the cued jam of each case
  ([nomm [need nargs blocks] [need nargs blocks] formula]) as a Lean `Noun`.
"""
import sys, re
sys.setrecursionlimit(100000)

def records(text):
    out, cur, bal = [], [], 0
    for line in text.split('\n'):
        if not cur and not line.startswith('['):
            continue
        cur.append(line.strip())
        bal += line.count('[') - line.count(']')
        if bal == 0:
            out.append(' '.join(cur)); cur = []
    return out

def tokens(s):
    return [x for x in re.findall(r'\[|\]|[^\s\[\]]+', s) if not x.endswith('=')]

def parse(s):
    t = tokens(s); i = 0
    def e():
        nonlocal i
        if t[i] == '[':
            i += 1; xs = []
            while t[i] != ']':
                xs.append(e())
            i += 1
            r = xs[-1]
            for x in reversed(xs[:-1]):
                r = (x, r)
            return r
        a = t[i]; i += 1
        return a
    return e()

def bits(n):
    return n.bit_length()

def cue(a):
    m = {}
    def rd(pos):
        if (a >> pos) & 1 == 0:
            v, w = mat(pos + 1); m[pos] = v; return v, w + 1
        if (a >> (pos + 1)) & 1 == 0:
            h, wh = rd(pos + 2); t, wt = rd(pos + 2 + wh); v = (h, t); m[pos] = v
            return v, 2 + wh + wt
        p, w = mat(pos + 2); return m[p], w + 2
    def mat(pos):
        if (a >> pos) & 1:
            return 0, 1
        c = 0
        while (a >> (pos + c)) & 1 == 0:
            c += 1
        # c zeros then a 1
        b = pos + c + 1
        ln = ((a >> b) & ((1 << (c - 1)) - 1)) | (1 << (c - 1)) if c > 1 else 1
        b2 = b + c - 1
        v = (a >> b2) & ((1 << ln) - 1)
        return v, 2 * c + ln
    return rd(0)[0]

def lean(n):
    if isinstance(n, int):
        return f'(A {n})'
    return f'(C {lean(n[0])} {lean(n[1])})'

def atom(s):
    if isinstance(s, tuple): return None
    s = s.split('=')[-1]
    if s.startswith('0x'): return int(s[2:].replace('.', ''), 16)
    if re.fullmatch(r'[0-9.]+', s): return int(s.replace('.', ''))
    return s

def strip(n):
    if isinstance(n, tuple): return (strip(n[0]), strip(n[1]))
    return n.split('=')[-1].replace('.', '') if isinstance(n, str) and not n.startswith('%.') else n

def frames(t):
    out = []
    while isinstance(t, tuple):
        out.append(t[0]); t = t[1]
    return out

def same(m, i):
    m, i = strip(m), strip(i)
    if m == i: return True
    if not (isinstance(m, tuple) and isinstance(i, tuple)): return False
    if m[0] != '2' or i[0] != '2': return False
    fm, fi = frames(m[1]), frames(i[1])
    if len(fm) != len(fi): return False
    MEAN, MEAF, MEAC = str(0x6e61656d), str(0x6661656d), str(0x6361656d)
    for a, b in zip(fm, fi):
        if a == b: continue
        if a[0] == MEAN and b[0] in (MEAF, MEAC): continue
        return False
    return True

if __name__ == '__main__':
    mode, path = sys.argv[1], sys.argv[2]
    recs = [parse(r) for r in records(open(path).read())]
    if mode == '--sum':
        ok = bad = 0
        seen = set()
        for r in recs:
            if repr(r) in seen: continue
            seen.add(repr(r))
            if strip(r[0]) != '%run': continue
            nam = r[1][0]; rest = r[1][1]
            sub = rest[0]; mk, ir, mkg, irg = [x for x in [rest[1][0], rest[1][1][0], rest[1][1][1][0], rest[1][1][1][1]]]
            mk, ir, mkg, irg = [strip(x) for x in (mk, ir, mkg, irg)]
            for (a, b, g) in ((mk, ir, '~'), (mkg, irg, 'gul')):
                if same(a, b): ok += 1
                else:
                    bad += 1; print('DIFF', nam, g, 'sub', strip(sub), 'mink', a, 'ir', b)
        print('runs', ok + bad, 'same', ok, 'diff', bad)
    else:
        out = ['import lemmas.Ska.Types', '', '/-! Generated by `tools/gen/hintcheck.py --lean` from the output of',
               '`tools/hoon/hintdump.hoon`: per case the cued jam of `[nomm [need nargs blocks] [need nargs',
               'blocks] formula]` (the whole-subject and the n-ary raw blocks, sorted by label). -/', '',
               'namespace Formalization', 'namespace SkaModel', 'namespace HintData', '', 'open Nock', '']
        names = []
        for r in recs:
            if strip(r[0]) != '%jam': continue
            nam = strip(r[1][0]).lstrip('%'); a = atom(r[1][1])
            if nam in names: continue
            n = cue(a)
            out.append(f'def j{nam} : Noun :=\n  {lean(n)}\n')
            names.append(nam)
        out.append('def all : List (String × Noun) := [' + ', '.join(f'("{n}", j{n})' for n in names) + ']')
        out += ['', 'end HintData', 'end SkaModel', 'end Formalization', '']
        open('lemmas/Ska/CompHintData.lean', 'w').write('\n'.join(out))
        print('wrote', len(names), 'cases')
