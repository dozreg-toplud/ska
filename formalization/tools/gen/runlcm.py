#!/usr/bin/env python3
"""Write lemmas/Ska/CompRunLCM.lean: runLCM env mono, the model of +run with
its flag `mono`, generated from the text of runLC in lemmas/Ska/CompRunLC.lean
(itself generated by runlc.py; neither is changed).

Run from formalization/.  Every extraction and replacement asserts its count.

* runLCM env mono: runLC with the flag `mono` passed to every recursive run
  (the Hoon's `$(...)` keeps it) and the case %2 as `callLM env mono`
  (lemmas/Ska/CompDirectM.lean): `callDM`, the direct call through
  +mono-try-call, when `mono`, else `callL`.  The arms of %6 are the
  `sixNextLC` of CompRunLC.lean, which take the runs as parameters.
"""
src = open('lemmas/Ska/CompRunLC.lean').read()

def extract(start, end):
    i = src.index(start)
    assert src.count(start) == 1, start
    j = src.index(end, i)
    return src[i:j]

def rep(s, old, new, n):
    c = s.count(old)
    assert c == n, (old, c, n)
    return s.replace(old, new)

run = extract('def runLC [HoonMapKeys Map] (env : CallEnv) :', 'end Comp')
run = rep(run, 'def runLC [HoonMapKeys Map] (env : CallEnv) :',
          'def runLCM [HoonMapKeys Map] (env : CallEnv) (mono : Bool) :', 1)
run = rep(run, 'callL env (runLC env sup p) (runLC env sup q)',
          'callLM env mono (runLC env sup p) (runLC env sup q)', 1)
n = run.count('runLC env ')
assert n == 25, n
run = run.replace('runLC env ', 'runLCM env mono ')
assert 'runLC ' not in run and 'callL ' not in run

head = '''import lemmas.Ska.CompRunLC
import lemmas.Ska.CompDirectM

/-!
# `run` with the flag `mono`: `runLCM` (generated)

Written by `tools/gen/runlcm.py` from the text of `runLC`
(`CompRunLC.lean`); do not edit by hand.

* `runLCM env mono sup`: `runLC env sup` with the flag `mono` of `+run`,
  passed to every recursive run (the Hoon's `$(...)` keeps it), and the case
  `%2` as `callLM env mono` (`CompDirectM.lean`): with `mono` `&` a direct
  call goes through `+mono-try-call` (`callDM`), otherwise it is `callL`.

With `mono := false` it is `runLC`, and with `mono := true` on nomms without
a direct call too (`runLCM_eq`, `CompDirectMEq.lean`).
-/

set_option linter.unusedSectionVars false
set_option linter.unusedVariables false

namespace Formalization
namespace SkaModel
namespace Comp

open Nock Lazy

variable {S : Type} [HoonSet S] {Map : Type → Type} [HoonMap Map]

'''
tail = '''end Comp
end SkaModel
end Formalization
'''
out = head + run + tail
open('lemmas/Ska/CompRunLCM.lean', 'w').write(out)
print('wrote lemmas/Ska/CompRunLCM.lean', len(out.splitlines()), 'lines')
