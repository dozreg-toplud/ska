#!/usr/bin/env python3
"""Write lemmas/Ska/CompHintLS.lean and lemmas/Ska/CompHintLSCons.lean: the
copies, for the run with hints (`runLCH env snd true`, CompRunLCH.lean), of
the generated `LOKSM` constructors (CompDirectMLS.lean, CompDirectMLSCons.lean,
themselves copies by tools/gen/loksm.py of track C's lemmas), from their
text.  README Gaps 24.12.

Run from formalization/:  python3 tools/gen/lokh.py

* The direct-call lemmas at the end of CompDirectMLS.lean (`callLBM_runM`,
  `lokSM_directF`, `tailP_doneM`) are not copied: a direct call sits in the
  class with hints only as a part without hints (`LOKSM.toH`).
* Substitutions, each counted against COUNTS:
  - `runLCM env true` / `runLCM (Map := Map) env true` -> `runLCH ... env snd true`;
  - `unfold runLCM` -> `unfold runLCH`, `simp only [runLCM,` -> `simp only [runLCH,`;
  - the relations `LOKSM`, `LOKSFM`, `JNewLSM`, `JNewLSFM` -> `LOKSH`,
    `LOKSFH`, `JNewLSH`, `JNewLSFH`, each use `X (S := S) (Map := Map)`
    getting `(snd := snd)`, and each definition the parameter
    `(snd : Nomm → NeedOrd → Bool)` first;
  - every other name `XM` defined in the files -> `XMH` (`runLCM_x` ->
    `runLCH_x`); the theorems take `snd` from `variable {snd}`.
* A copy is sound as text since `runLCH env snd true` unfolds to the same
  case bodies as `runLCM env true` with `runLCH env snd true` on the parts
  (runlch.py writes it from the text of `runLCM`) on every case but the hints,
  which no copied lemma unfolds.
"""
import re, sys

SRC = ['lemmas/Ska/CompDirectMLS.lean', 'lemmas/Ska/CompDirectMLSCons.lean']
OUT = ['lemmas/Ska/CompHintLS.lean', 'lemmas/Ska/CompHintLSCons.lean']
IMPORTS = [['lemmas.Ska.CompHintLOKS'], ['lemmas.Ska.CompHintLS']]
CUT = '/-- (Generated by `tools/gen/loksm.py`: `callLBM_run` for a `p` that meets `LOKSFM`.)'
TYPES = {'LOKSM': 'LOKSH', 'LOKSFM': 'LOKSFH', 'JNewLSM': 'JNewLSH', 'JNewLSFM': 'JNewLSFH'}
DECL = re.compile(r'^(theorem|def|structure|abbrev)\s+([^\s(:{\[]+)', re.M)

texts = [open(f).read() for f in SRC]
assert texts[0].count(CUT) == 1
i = texts[0].index(CUT)
j = texts[0].index('end Comp\n', i)
texts[0] = texts[0][:i] + texts[0][j:]

names = set()
for t in texts:
    names |= {m.group(2) for m in DECL.finditer(t)}
ren = {}
for n in names:
    if n in TYPES:
        continue
    if '.' in n:
        continue  # renamed through its prefix (`LOKSM.toF`, `JNewLSM.toF`)
    if n.startswith('runLCM_'):
        ren[n] = 'runLCH_' + n[len('runLCM_'):]
        continue
    assert n.endswith('M'), n
    ren[n] = n + 'H'
for n in TYPES:
    ren[n] = TYPES[n]

def sub(rx, rp, text, key, counts):
    text, c = re.subn(rx, rp, text, flags=re.M)
    counts[key] = counts.get(key, 0) + c
    return text

COUNTS = [
    {'gen': 37, 'env': 53, 'unfold': 9, 'simp': 4, 'uses': 55, 'defs': 3, 'names': 170},
    {'gen': 9, 'env': 22, 'unfold': 0, 'simp': 0, 'uses': 33, 'defs': 0, 'names': 70},
]
outs = []
for k, t in enumerate(texts):
    counts = {}
    t = sub(r'Generated by `tools/gen/loksm.py`: `([^`]+)` for `runLCM env true`\.',
            r'Generated by `tools/gen/lokh.py` from the copy by `tools/gen/loksm.py` of `\1`, for `runLCH env snd true`.',
            t, 'gen', counts)
    t = sub(r'\brunLCM((?:\s+\(Map := Map\))?)\s+env true\b', r'runLCH\1 env snd true', t, 'env', counts)
    t = sub(r'\bunfold runLCM\b', 'unfold runLCH', t, 'unfold', counts)
    t = sub(r'\bsimp only \[runLCM,', 'simp only [runLCH,', t, 'simp', counts)
    t = sub(r'\b(LOKSM|LOKSFM|JNewLSM|JNewLSFM) \(S := S\) \(Map := Map\)', r'\1 (S := S) (Map := Map) (snd := snd)',
            t, 'uses', counts)
    t = sub(r'^(def|structure) (JNewLSM|JNewLSFM|LOKSFM) \(', r'\1 \2 (snd : Nomm → NeedOrd → Bool) (', t, 'defs',
            counts)
    tot = 0
    for r in sorted(ren, key=len, reverse=True):
        t, c = re.subn(r"(?<![A-Za-z0-9_.'])" + re.escape(r) + r"(?![A-Za-z0-9_'])", ren[r], t)
        tot += c
    counts['names'] = tot
    left = re.findall(r'\brunLCM\b|\bLOKS[A-Z]*M\b|\bJNewLS[A-Z]*M\b', re.sub(r'/-.*?-/', '', t, flags=re.S))
    assert not left, ('left', k, left[:5])
    if '--counts' in sys.argv:
        print(k, counts)
        continue
    assert counts == COUNTS[k], ('substitution counts changed', k, counts, COUNTS[k])
    # the header: imports, the module doc, the variable `snd`
    body = t[t.index('set_option'):]
    body = body.replace('variable {S : Type} [HoonSet S] {Map : Type → Type} [HoonMap Map] [HoonMapKeys Map]\n',
                        'variable {S : Type} [HoonSet S] {Map : Type → Type} [HoonMap Map] [HoonMapKeys Map]\n'
                        'variable {snd : Nomm → NeedOrd → Bool}\n', 1)
    assert 'variable {snd' in body
    doc = ('the copies of `LOKSF`, `JNewLS`, `JNewLSF`, the equations of the cases of the run they unfold, and the '
           'constructors of `[7 p q]`, `[4 p]`, `[3 p]`, `[5 p q]`, the indirect call and the `DoneOK` lemmas at the top'
           if k == 0 else 'the copies of the constructors of the cons')
    head = '\n'.join(f'import {x}' for x in IMPORTS[k]) + f'''

/-!
# `LOKSH` constructors{' of the cons' if k else ''} (generated)

Written by `tools/gen/lokh.py` from `{SRC[k].split('/')[-1]}` (the copies by
`tools/gen/loksm.py` of track C's lemmas for `runLCM env true`); do not edit
by hand.  For the run with hints `runLCH env snd true` (README Gaps 24.12):
{doc}.
-/

'''
    outs.append(head + body)
if '--counts' in sys.argv:
    sys.exit(0)

# `finishLUCM_contractGB` (CompDirectMTail.lean) for `finishLUCH`: the top of
# the whole-subject code from a run that meets `RunOKGB`, appended to the cons file.
src = open('lemmas/Ska/CompDirectMTail.lean').read()
a = src.index('/-- **`finishLUC_contractGB` for `finishLUCM`**')
b = src.index('/-- **The direct tail call at the top meets both halves')
top = src[a:b]
for o, nw, c in [('theorem finishLUCM_contractGB ', 'theorem finishLUCH_contractGB ', 1),
                 ('finishLUCM (S := S) env nm', 'finishLUCH (S := S) env snd nm', 1),
                 ('unfold finishLUCM at h', 'unfold finishLUCH at h', 1),
                 ('runLCM env true', 'runLCH env snd true', 1),
                 ('/-- **`finishLUC_contractGB` for `finishLUCM`** (its text, with `runLCM env\ntrue`)',
                  '/-- (Generated by `tools/gen/lokh.py` from `finishLUCM_contractGB`.)\n'
                  '**`finishLUC_contractGB` for `finishLUCH`** (its text, with `runLCH env snd\ntrue`)', 1)]:
    assert top.count(o) == c, (o, top.count(o), c)
    top = top.replace(o, nw)
assert not re.search(r'\brunLCM\b|\bfinishLUCM\b', top), 'M left in the top'
k = outs[1].rindex('end Comp\n')
outs[1] = outs[1][:k] + top + outs[1][k:]
for f, o in zip(OUT, outs):
    open(f, 'w').write(o)
    print('wrote', f, len(o.splitlines()), 'lines')

# ---------------------------------------------------------------------------
# The direct call (README Gaps 24.20): `lemmas/Ska/CompHintLSDirect.lean`, the
# copies of `runLCM_cal` (CompDirectMCal.lean), `runLCM_tailP`
# (CompDirectMTailP.lean) and of the three lemmas cut above (`callLBM_runM`,
# `lokSM_directF`, `tailP_doneM`, CompDirectMLS.lean) for `runLCH env snd
# true`.  The run of `[2 p q b]` is `callLM` with the runs of the parts in
# both models, so the texts carry over; every replace is counted.

def grab(path, start, stop):
    src = open(path).read()
    assert src.count(start) == 1, (path, start)
    a = src.index(start)
    b = src.index(stop, a)
    return src[a:b]

DIRECT = (grab('lemmas/Ska/CompDirectMCal.lean',
               '/-- **The run of the direct call under `%next L th` with `mono` `&`, `q`',
               '/-! ## `callLBM` -/') +
          grab('lemmas/Ska/CompDirectMTailP.lean',
               '/-- **The run of the direct call under `%done` with `mono` `&`, `q`',
               '/-! ## The run meets `DoneOK` -/') +
          grab('lemmas/Ska/CompDirectMLS.lean', CUT, 'end Comp\n'))

def rep(text, old, new, count):
    assert text.count(old) == count, ('direct', old, text.count(old), count)
    return text.replace(old, new)

d = DIRECT
for old, new, c in [
        ('theorem runLCM_cal ', 'theorem runLCH_cal ', 1),
        ('theorem runLCM_tailP ', 'theorem runLCH_tailP ', 1),
        ('theorem callLBM_runM ', 'theorem callLBM_runMH ', 1),
        ('theorem lokSM_directF ', 'theorem lokSH_directF ', 1),
        ('theorem tailP_doneM ', 'theorem tailP_doneMH ', 1),
        ('runLCM_cal hring', 'runLCH_cal hring', 2),
        ('runLCM_tailP hring', 'runLCH_tailP hring', 1),
        ('callLBM_runM lib env', 'callLBM_runMH lib env', 1),
        ('runLCM env true', 'runLCH env snd true', 6),
        ('simp only [runLCM, callLM', 'simp only [runLCH, callLM', 2),
        ('LOKSFM (S := S) (Map := Map)', 'LOKSFH (S := S) (Map := Map) (snd := snd)', 3),
        ('LOKSM (S := S) (Map := Map)', 'LOKSH (S := S) (Map := Map) (snd := snd)', 1),
        ('(Generated by `tools/gen/loksm.py`: ', '(Generated by `tools/gen/lokh.py` from the copy by `tools/gen/loksm.py` of ', 3)]:
    d = rep(d, old, new, c)
left = re.findall(r'\brunLCM\b|\bLOKS[A-Z]*M\b|\bcallLBM_runM\b|\blokSM_directF\b|\btailP_doneM\b|\brunLCM_[a-zA-Z]+\b',
                  re.sub(r'/-.*?-/', '', d, flags=re.S))
assert not left, ('direct: left', left[:5])
head = '''import lemmas.Ska.CompHintLS
import lemmas.Ska.CompDirectMLS

/-!
# `LOKSH` of the direct call (generated)

Written by `tools/gen/lokh.py` from the texts of `runLCM_cal`
(`CompDirectMCal.lean`), `runLCM_tailP` (`CompDirectMTailP.lean`) and the
three direct-call lemmas at the end of `CompDirectMLS.lean` (`callLBM_runM`,
`lokSM_directF`, `tailP_doneM`, themselves copies by `tools/gen/loksm.py`);
do not edit by hand.  For the run with hints `runLCH env snd true` (README
Gaps 24.20): the run of `[2 p q b]` is `callLM` with the runs of the parts in
both models, so the equations of the run and the proofs carry over.

* `runLCH_cal`, `runLCH_tailP`: the run of the direct call under `%next L
  th` and under `%done`;
* `callLBM_runMH`, **`lokSH_directF`** (the direct call meets `LOKSH
  false`, `p` meeting `LOKSFH`), **`tailP_doneMH`** (under `%done`, `DoneOK`).
-/

set_option linter.unusedSectionVars false
set_option linter.unusedVariables false
set_option linter.unusedSimpArgs false

namespace Formalization
namespace SkaModel
namespace Comp

open Nock Lazy

variable {S : Type} [HoonSet S] {Map : Type → Type} [HoonMap Map] [HoonMapKeys Map]
variable {snd : Nomm → NeedOrd → Bool}

'''
open('lemmas/Ska/CompHintLSDirect.lean', 'w').write(head + d + 'end Comp\nend SkaModel\nend Formalization\n')
print('wrote lemmas/Ska/CompHintLSDirect.lean', len((head + d).splitlines()), 'lines')
