#!/usr/bin/env python3
"""Write lemmas/Ska/CompHintLSU.lean: the copies of the `LOKSH` constructors
(CompHintLS.lean, CompHintLSCons.lean, by tools/gen/lokh.py) whose parts'
`kind` is the old one, `(p.pure = true ∧ MinkEq lib P fb p) ∨ hinted env.cod p
= some true`, with the kind of the class with unkept hints around pure
formulas (`KindU`, CompHintKind.lean): `(hinted env.cod p = some false ∧
TotalC lib P fb) ∨ hinted env.cod p = some true`.  README Gaps 24.13.

Run from formalization/:  python3 tools/gen/lokhu.py

* Copied: every declaration that states the old kind, and every one that
  uses a copied one (closure), in the order of the files, each name `X` as
  `XU`.
* In the copies: the kind as above; `pastL_pure _ _ h` as `pastL_unhinted _ _
  h` (`+past` returns its need for a nomm with `+hinted` `|`, pure or not);
  `totalC_of_minkEq M` as `M` (the only use of `MinkEq` in these lemmas is
  `TotalC`, which the new kind carries).  Counts asserted.
* Sound as text: the old kind's first branch was read only through these
  two lemmas (asserted: no other use of the bound names `pp`/`qp`/`Mp`/`Mq`
  survives).
"""
import re, sys

SRC = ['lemmas/Ska/CompHintLS.lean', 'lemmas/Ska/CompHintLSCons.lean']
OUT = 'lemmas/Ska/CompHintLSU.lean'
DECL = re.compile(r'^(?:theorem|def|structure|abbrev)\s+([^\s(:{\[]+)', re.M)
KIND = re.compile(r'\((\w+)\.pure = true ∧ MinkEq lib (\w+) (\w+) \1\) ∨ hinted env\.cod \1 = some true')

chunks = []  # (name, text)
for f in SRC:
    t = open(f).read()
    lines = t.split('\n')
    i = next(k for k, l in enumerate(lines) if l.startswith('/-- `omega` after'))
    j = max(k for k, l in enumerate(lines) if l.startswith('end Comp'))
    cur, doc = [], False
    for l in lines[i:j]:
        if l.startswith('/--'):
            if cur:
                chunks.append(cur)
            cur, doc = [l], True
        elif re.match(r'^(theorem|def|structure|abbrev|local macro) ', l):
            if cur and not doc:
                chunks.append(cur)
                cur = []
            cur.append(l)
            doc = False
        else:
            if cur and doc and not l.startswith(' ') and l.endswith('-/'):
                cur.append(l)
                continue
            cur.append(l)
    if cur:
        chunks.append(cur)
named = []
for c in chunks:
    t = '\n'.join(c).rstrip('\n') + '\n'
    m = DECL.search(t)
    named.append((m.group(1) if m else None, t))
marked = {n for n, t in named if n and KIND.search(t)}
while True:
    new = {n for n, t in named if n and n not in marked and
           any(re.search(r"(?<![A-Za-z0-9_.'])" + re.escape(m) + r"(?![A-Za-z0-9_'])", t) for m in marked)}
    if not new:
        break
    marked |= new
counts = {'kind': 0, 'past': 0, 'total': 0, 'names': 0}
outs = []
for n, t in named:
    if n not in marked:
        continue
    t, c = KIND.subn(r'(hinted env.cod \1 = some false ∧ TotalC lib \2 \3) ∨ hinted env.cod \1 = some true', t)
    counts['kind'] += c
    t, c = re.subn(r'\bpastL_pure _ _ (\w+)', r'pastL_unhinted _ _ \1', t)
    counts['past'] += c
    t, c = re.subn(r'\btotalC_of_minkEq (\w+)', r'\1', t)
    counts['total'] += c
    for r in sorted(marked, key=len, reverse=True):
        t, c = re.subn(r"(?<![A-Za-z0-9_.'])" + re.escape(r) + r"(?![A-Za-z0-9_'])", r + 'U', t)
        counts['names'] += c
    t = re.sub(r'^/-- \(Generated by `tools/gen/lokh.py`', '/-- (Generated by `tools/gen/lokhu.py` from the copy by `tools/gen/lokh.py`', t)
    assert 'pastL_pure' not in t and 'totalC_of_minkEq' not in t and '.pure = true ∧ MinkEq' not in t, n
    outs.append(t)
if '--counts' in sys.argv:
    print(counts, sorted(marked))
    sys.exit(0)
EXPECT = {'kind': 26, 'past': 17, 'total': 8, 'names': 40}
assert counts == EXPECT, ('counts changed', counts, EXPECT)
head = '''import lemmas.Ska.CompHintKind

/-!
# `LOKSH` constructors for the kind `KindU` (generated)

Written by `tools/gen/lokhu.py` from `CompHintLS.lean` and `CompHintLSCons.lean`
(themselves by `tools/gen/lokh.py`); do not edit by hand.  The constructors
whose parts' kind was `(p.pure = true ∧ MinkEq lib P fb p) ∨ hinted = some
true`, with the kind `(hinted = some false ∧ TotalC lib P fb) ∨ hinted = some
true` (`KindU`), so that a part may be a pure formula under hints that are
not kept (README Gaps 24.13).  Each name `X` is `XU`.
-/

set_option linter.unusedSectionVars false
set_option linter.unusedVariables false
set_option linter.unusedSimpArgs false

namespace Formalization
namespace SkaModel
namespace Comp

open Nock Lazy

variable {S : Type} [HoonSet S] {Map : Type → Type} [HoonMap Map] [HoonMapKeys Map]
variable {snd : Nomm → NeedOrd → Bool}

/-- `omega` after reducing the projections of the states. -/
local macro "romega" : tactic =>
  `(tactic| first | omega | (simp only [emitted_re, emitted_bo] at *; omega) | (dsimp only at *; omega))

'''
open(OUT, 'w').write(head + '\n'.join(outs) + '\nend Comp\nend SkaModel\nend Formalization\n')
print('wrote', OUT, len(marked), 'declarations')
