#!/usr/bin/env python3
"""Read the output of tools/hoon/hintdump3.hoon (runhoon.sh; track J, README Gaps 24) and
* --sum OUT: per entry of the code table after the 16 pokes, its `%case` line (less, pure,
  total, the number of kept hints);
* --lean OUT: write lemmas/Ska/CompHintClsData.lean, the cued jam of each entry
  ([nomm formula table], the table `[bell pure nomm (unit need)]` of the bells the nomm names,
  two levels) as a Lean `Noun`, named t01.. in `~(tap by code)` order, with `kept`, the names
  of the entries with a kept hint.
"""
import sys, re, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hintcheck as H

def text(path):
    t = open(path).read()
    return re.sub(r'"[^"]*"', 'TAPE', t)

if __name__ == '__main__':
    mode, path = sys.argv[1], sys.argv[2]
    recs = [H.parse(r) for r in H.records(text(path))]
    if mode == '--sum':
        seen = set()
        for r in recs:
            if H.strip(r[0]) not in ('%case', '%total'): continue
            if repr(r) in seen: continue
            seen.add(repr(r)); print(H.strip(r))
    else:
        out = ['import lemmas.Ska.Types', '',
               '/-! Generated by `tools/gen/hintcls.py --lean` from the output of',
               '`tools/hoon/hintdump3.hoon` (track J, README Gaps 24): every entry of `code.long-ska`',
               'after the 16 pokes of `tools/hoon/hinttab.hoon` (6 `!:` gates on an unknown sample, then',
               'the 10 `%full` pokes of `flagsdump.hoon`), in `~(tap by code)` order, as the cued jam of',
               '`[nomm formula table]`: `formula` the `fol` of the bell, `table` the list of `[bell pure',
               'nomm (unit need)]` of the bells the nomm names (two levels; `need` that of the n-ary',
               'version, when compiled).  `kept`: the entries whose nomm has a kept hint (static `%bout`',
               '`%xray`, a dynamic tag, `%mean`). -/', '',
               'namespace Formalization', 'namespace SkaModel', 'namespace HintClsData', '', 'open Nock', '']
        names = []; kept = {}
        for r in recs:
            h = H.strip(r[0])
            if h == '%case':
                k = int(H.strip(r[1][0]).replace('.', ''))
                x = r[1][1]
                while isinstance(x, tuple): x = x[-1]
                kept[k] = int(H.strip(x).replace('.', ''))
            if h != '%jam': continue
            k = int(H.strip(r[1][0]).replace('.', '')); a = H.atom(r[1][1])
            nam = f't{k:02d}'
            if nam in names: continue
            out.append(f'def j{nam} : Noun :=\n  {H.lean(H.cue(a))}\n')
            names.append(nam)
        assert len(names) >= 20, names
        kn = [f't{k:02d}' for k, v in sorted(kept.items()) if v > 0]
        out.append('def all : List (String × Noun) := [' + ', '.join(f'("{n}", j{n})' for n in names) + ']')
        out.append('')
        out.append('def kept : List String := [' + ', '.join(f'"{n}"' for n in kn) + ']')
        out += ['', 'end HintClsData', 'end SkaModel', 'end Formalization', '']
        open('lemmas/Ska/CompHintClsData.lean', 'w').write('\n'.join(out))
        print('wrote', len(names), 'entries, kept', kn)
