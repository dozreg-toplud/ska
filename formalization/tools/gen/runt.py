#!/usr/bin/env python3
"""Write lemmas/Compiler/CompRunT{Leaf,Cons,Five,Ten}.lean: the case lemmas of
`+run` of CompRunR*.lean (themselves generated by runr.py) with the run link
THREADING the rest (`CompRunAtXT ... X Y`, CompCalleeComp.lean; `YOk X Y`,
`PartRT`, CompRunTBase.lean; README Gaps 19 (g)).  Rerun after runr.py.
Run from formalization/.

Every copied declaration `n` is renamed `nT`.  The rules are textual, and
each asserts its count per file (`--counts` prints them):

* links: `CompRunAtX (runLCM env true msup) ctx X` -> `CompRunAtXT ... ctx X Y`,
  `PartR env msup ctx X` -> `PartRT env msup ctx X Y`; every copied theorem
  gets a last binder `(hYk : YOk X Y := by assumption)`;
* a lemma with the rest `x` as a parameter concludes `∃ x', Y x x' ∧ ...`
  with `genNoun p.2 x'` on the right;
* the proofs SHADOW the rest: `hY0 : Y x0 x` (x0 the rest the lemma starts
  at, `x` the current one) is made at the start; each application of a
  link at `x mono sup hx hX` (and each `have` of a copied lemma with an
  `∃` conclusion) becomes `obtain ⟨x, hyN, h⟩ := ...` followed by
  `replace hY0 := hYk.trans hY0 hyN`, `replace hx := hYk.soft hx hyN`,
  `replace hX := hYk.pres hX hyN`: every later use of `x`, `hx`, `hX` in the
  old text (the next run, `+past`, `+copy`, ...) is then at the new rest,
  because the old proofs follow the order the Hoon runs things in;
* each closing `simp [` gets `refine ⟨x, hY0, ?_⟩` before it.
"""
import re, sys

D = 'lemmas/Compiler/'
COUNTS = '--counts' in sys.argv

TOP = re.compile(r'^(?:/--|/-!|theorem |def |noncomputable def |structure |end |example|@\[|abbrev |variable |open |namespace |set_option )', re.M)

def chunks(path):
    src = open(path).read()
    st = [m.start() for m in TOP.finditer(src)] + [len(src)]
    cs = [src[a:b] for a, b in zip(st, st[1:])]
    out = []
    i = 0
    while i < len(cs):
        if cs[i].startswith('/--') and i + 1 < len(cs):
            out.append(cs[i] + cs[i + 1]); i += 2
        else:
            out.append(cs[i]); i += 1
    return out

DECL = re.compile(r'^(?:/--.*?-/\s*)?(?:theorem|def|noncomputable def|structure) (\S+)', re.S)

def extract(path, names):
    got = {}
    for c in chunks(path):
        m = DECL.match(c)
        if m and m.group(1) in names:
            got[m.group(1)] = c.rstrip() + '\n'
    for n in names:
        assert n in got, (path, n)
    return [got[n] for n in names]

RENAMED = []      # copied names (get the suffix T)
EXL = []          # copied lemmas with the rest `x` as a parameter (an `∃` conclusion)

def rename(s):
    for n in RENAMED:
        s = re.sub(r'(?<![\w.])' + re.escape(n) + r'(?![\w\'])', n + 'T', s)
    return s

SHADOW = ('{i}replace hY0 := hYk.trans hY0 {y}\n{i}replace hx := hYk.soft hx {y}\n'
          '{i}replace hX := hYk.pres hX {y}\n')

def stmt_end(lines, k):
    """The index after the statement starting at line k (lines indented deeper continue it)."""
    ind = len(lines[k]) - len(lines[k].lstrip())
    if lines[k].lstrip().startswith('· '):
        ind += 2
    j = k + 1
    while j < len(lines) and lines[j].strip() and (len(lines[j]) - len(lines[j].lstrip())) > ind:
        j += 1
    return j

def transform(block, pre, cnt):
    for old, new in pre:
        c = block.count(old)
        cnt['pre:' + old[:30]] = cnt.get('pre:' + old[:30], 0) + c
        block = block.replace(old, new)
    def sub(key, pat, rep, s):
        s, c = re.subn(pat, rep, s)
        cnt[key] = cnt.get(key, 0) + c
        return s
    block = sub('link', r'CompRunAtX \(runLCM env true msup\) ctx X\b', 'CompRunAtXT (runLCM env true msup) ctx X Y', block)
    block = sub('part', r'\bPartR env msup ctx X\b', 'PartRT env msup ctx X Y', block)
    block = sub('six', r'\bSixPartsR env msup ctx X\b', 'SixPartsRT env msup ctx X Y', block)
    name = DECL.match(block).group(1)
    if not re.match(r'^(?:/--.*?-/\s*)?theorem ', block, re.S):
        return block
    # header / proof
    hm = re.search(r'[\)\}\]] :\n', block)
    pm = block.find(':= by\n')
    if pm < 0:
        cnt['term'] = cnt.get('term', 0) + 1
        return block
    assert hm, name
    hdr, concl, proof = block[:hm.start() + 1], block[hm.start() + 1:pm], block[pm:]
    xparam = '(x : GenRest)' in hdr
    hdr = hdr + ' (hYk : YOk X Y := by assumption)'
    cnt['hyk'] = cnt.get('hyk', 0) + 1
    if xparam:
        assert concl.count('(genNoun p.2 x)') == 1, (name, concl)
        concl = re.sub(r':\n    nock \(', ':\n    ∃ x\', Y x x\' ∧ nock (', concl, count=1)
        assert '∃ x\'' in concl, name
        concl = concl.replace('(genNoun p.2 x)', "(genNoun p.2 x')")
        cnt['exconcl'] = cnt.get('exconcl', 0) + 1
        EXL.append(name)
        proof = proof.replace(':= by\n', ':= by\n  have hY0 : Y x x := hYk.refl x\n', 1)
    proof = sub('intro', r'\n(\s*)intro x mono sup hx hX\n', r'\n\1intro x mono sup hx hX\n\1have hY0 : Y x x := hYk.refl x\n', proof)
    # link applications and `have`s of copied ∃-lemmas: obtain and shadow
    lines = proof.split('\n')
    out = []
    k = 0
    nobt = 0
    last_ref = None
    while k < len(lines):
        ln = lines[k]
        ind = len(ln) - len(ln.lstrip())
        if ln.strip() and (ind < (last_ref or 0) or ln.lstrip().startswith(('|', '·'))):
            last_ref = None
        mh = re.match(r'^(\s*(?:· )?)have (\w+)( : [^=]*)? := (.*)$', ln)
        if mh:
            j = stmt_end(lines, k)
            st = '\n'.join(lines[k:j])
            isapp = re.search(r'\bx mono sup hx hX\b', st) is not None
            iscall = any(re.match(r'(\(\w+ := \w+\) )*' + re.escape(n) + r'\b', mh.group(4)) for n in EXL)
            if (isapp or iscall) and not mh.group(3):
                nobt += 1
                i, h = mh.group(1), mh.group(2)
                y = 'hy' + str(nobt)
                out.append(f'{i}obtain ⟨x, {y}, {h}⟩ := {mh.group(4)}')
                out.extend(lines[k + 1:j])
                out.extend(SHADOW.format(i=' ' * len(i), y=y).rstrip('\n').split('\n'))
                cnt['obtain'] = cnt.get('obtain', 0) + 1
            else:
                out.extend(lines[k:j])
            k = j
            continue
        me = re.match(r'^(\s*(?:· )?)exact (.*)$', ln)
        if me:
            j = stmt_end(lines, k)
            st = '\n'.join(lines[k:j])
            isapp = re.search(r'\bx mono sup hx hX\b', st) is not None
            iscall = any(re.match(re.escape(n) + r'\b', me.group(2)) for n in EXL)
            if (isapp or iscall) and not st.rstrip().endswith('⟩'):
                nobt += 1
                i = me.group(1)
                y = 'hy' + str(nobt)
                body = [f'{i}exact xt_trans hYk hY0 ({me.group(2)}'] + lines[k + 1:j]
                body[-1] = body[-1] + ')'
                out.extend(body)
                cnt['exact'] = cnt.get('exact', 0) + 1
                k = j
                continue
        mt = re.match(r'^(\s*)(· )?(?:simp \[|nock_open |conv )', ln)
        if mt and mt.group(2):
            ln = ln.replace('· ', '· refine ⟨x, hY0, ?_⟩\n' + mt.group(1) + '  ', 1)
            cnt['refine'] = cnt.get('refine', 0) + 1
            last_ref = ind + 2
        elif mt and last_ref != ind:
            out.append(f'{mt.group(1)}refine ⟨x, hY0, ?_⟩')
            cnt['refine'] = cnt.get('refine', 0) + 1
            last_ref = ind
        out.append(ln)
        k += 1
    proof = '\n'.join(out)
    return hdr + concl + proof

def gen(out, header, parts, expect):
    total = {}
    body = []
    for path, names, pre in parts:
        RENAMED.extend(names)
        for blk in extract(D + path, names):
            body.append(transform(blk, pre, total))
    body = [rename(b) for b in body]
    if COUNTS:
        print(out, {k: v for k, v in sorted(total.items()) if v})
        return
    for k, v in total.items():
        assert expect.get(k, 0) == v, (out, k, v, expect.get(k, 0))
    for k, v in expect.items():
        assert total.get(k, 0) == v, (out, k, total.get(k, 0), v)
    open(D + out, 'w').write(header + '\n'.join(body) + '\nend Compiler\nend Formalization\n')

def head(imports, doc):
    return ('\n'.join('import ' + i for i in imports) + '\n\n/-!\n' + doc +
            '\n\nGenerated by `tools/gen/runt.py`; do not edit.\n-/\n\n'
            'namespace Formalization\nnamespace Compiler\n\nopen Nock Pill Hoon SkaModel SkaModel.Comp\n\n'
            'set_option linter.unusedSimpArgs false\nset_option linter.unusedSectionVars false\n'
            'set_option linter.unusedVariables false\n\n'
            'variable {ctx : Noun} {X : GenRest → Noun → Noun → Prop} {Y : GenRest → GenRest → Prop}\n\n')

