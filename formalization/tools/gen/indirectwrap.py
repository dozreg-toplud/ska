#!/usr/bin/env python3
"""Generate lemmas/Ska/CompIndirectGen.lean: `indirect_semM` and
`indirect_semBM`, the code of the indirect call from the run's jump meets
`fwdPhi` and `bwdPhi` for any formula `f` with `MinkN2 lib P f p q`, from
the text of `indirect_sem` (CompIndirectFwd.lean) and `indirect_semB`
(CompIndirectBwd.lean).  Run from formalization/:
python3 tools/gen/indirectwrap.py.  Every extraction and replacement
asserts its match count.
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SKA = ROOT / "lemmas" / "Ska"


def extract(name, head):
    ls = (SKA / name).read_text().split("\n")
    hits = [i for i, l in enumerate(ls) if l.startswith(head)]
    assert len(hits) == 1, (head, hits)
    i = hits[0]
    j = i
    while ls[j] != "":
        j += 1
    return "\n".join(ls[i:j])


def rep(text, old, new, count=1):
    n = text.count(old)
    assert n == count, (old, n, count)
    return text.replace(old, new)


SIG_OLD = """{lib : Lib} {code : Bell → Option Nomm} (hok : CodeOK lib code) {P : Noun → Prop}
    {fb fc : Noun} {p q : Nomm} (hp : p.pure = true) (hq : q.pure = true) (hAp : Annot lib code P fb p)
    (hAq : Annot lib code P fc q) (N : Needs)"""
SIG_NEW = """{lib : Lib} {P : Noun → Prop}
    {f : Noun} {p q : Nomm} (M : MinkN2 lib P f p q) (N : Needs)"""

# forward
fwd = extract("CompIndirectFwd.lean", "theorem indirect_sem ")
fwd = rep(fwd, "theorem indirect_sem ", "theorem indirect_semM ")
fwd = rep(fwd, SIG_OLD, SIG_NEW)
fwd = rep(fwd, "fwdPhi lib N P (n3 (A 2) fb fc) σ", "fwdPhi lib N P f σ")
fwd = rep(fwd, "rcases minkF_n2_pure hok hp hq hAp hAq hs hm with ⟨n', x, y, rfl, ex, ey, hm'⟩ | ⟨en, er⟩",
          "rcases M.fwd hs hm with ⟨n', x, y, hlt, ex, ey, hm'⟩ | ⟨en, er⟩")
fwd = rep(fwd, "hF.nok st x y gul n' r0 hI (Nat.lt_succ_self n') h0", "hF.nok st x y gul n' r0 hI hlt h0")

# backward
bwd = extract("CompIndirectBwd.lean", "theorem indirect_semB ")
bwd = rep(bwd, "theorem indirect_semB ", "theorem indirect_semBM ")
bwd = rep(bwd, SIG_OLD, SIG_NEW)
bwd = rep(bwd, "bwdPhi lib N P (n3 (A 2) fb fc) σ", "bwdPhi lib N P f σ")
bwd = rep(bwd, """  have mp : Mink lib gul tm s fb (pureTone tm p s) := (mink_pure hok hp hAp hs gul tm _).mpr rfl
  have mq : Mink lib gul tm s fc (pureTone tm q s) := (mink_pure hok hq hAq hs gul tm _).mpr rfl
""", "")
bwd = rep(bwd, """    rw [pureTone, ex] at mp
    exact ⟨_, mink_n2_crash1 mp, ToneRel.two htr⟩""",
          """    exact ⟨_, M.crash hs (by simp [ex]), ToneRel.two htr⟩""")
bwd = rep(bwd, """    rw [pureTone, ex] at mp
    cases ey""", """    cases ey""")
bwd = rep(bwd, """      rw [pureTone, ey] at mq
      exact ⟨_, mink_n2_crash2 mp mq, ToneRel.two htr⟩""",
          """      exact ⟨_, M.crash hs (by simp [ex, ey]), ToneRel.two htr⟩""")
bwd = rep(bwd, """      rw [pureTone, ey] at mq
      rw [ex, ey] at G""", """      rw [ex, ey] at G""")
bwd = rep(bwd, """      have M : Mink lib gul tm s (n3 (A 2) fb fc) (r0.app tm) :=
        mink_n2_of mp mq ⟨k, by rw [minkF_trace, hM]; rfl⟩""",
          """      have M' : Mink lib gul tm s f (r0.app tm) :=
        M.bwd hs ex ey ⟨k, by rw [minkF_trace, hM]; rfl⟩""")
bwd = rep(bwd, "exact ⟨_, M, ToneRel.", "exact ⟨_, M', ToneRel.", 3)

HEAD = """import lemmas.Ska.CompIndirectWrap

/-!
# The code of the indirect call meets `fwdPhi` and `bwdPhi` on `MinkN2`

Generated by `tools/gen/indirectwrap.py` from `indirect_sem`
(`CompIndirectFwd.lean`) and `indirect_semB` (`CompIndirectBwd.lean`); do
not edit.  README Gaps 12.12 (sixteenth session).  The two lemmas there are
stated for the formula `[2 b c]` with `Annot` of `b` and `c`; here the
formula is any `f` with `MinkN2 lib P f p q`, which `minkN2_of_annot` gives
for every `Annot` of `[2 p q]` with pure parts and `bareLitQ q = false`.
-/

set_option linter.unusedSectionVars false
set_option linter.unusedSimpArgs false

namespace Formalization
namespace SkaModel
namespace Comp

open Nock Lazy

variable {S : Type} [HoonSet S] {Map : Type → Type} [HoonMap Map] [HoonMapKeys Map]

/-- **The code of the indirect call from the run's jump meets `fwdPhi`** on
any formula with `MinkN2` (`indirect_sem` on `[2 b c]`). -/
"""

MID = """

/-- **The code of the indirect call from the run's jump meets `bwdPhi`** on
any formula with `MinkN2` (`indirect_semB` on `[2 b c]`). -/
"""

TAIL = """

end Comp
end SkaModel
end Formalization
"""

(SKA / "CompIndirectGen.lean").write_text(HEAD + fwd + MID + bwd + TAIL)
