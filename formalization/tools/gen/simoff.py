#!/usr/bin/env python3
"""Generate lemmas/Compiler/CompSofOff.lean: `callLS_sim` / `runLCS_sim` of
`lemmas/Ska/SccLoopSoftEq.lean` with `sof` false only at the nomm's own calls
(`SofOff`), by asserted textual replacements.  Run from `formalization/`."""
import re, sys

src = open('lemmas/Ska/SccLoopSoftEq.lean').read().split('\n')

def block(start_pat, end_pat):
    i = next(k for k, l in enumerate(src) if l.startswith(start_pat))
    j = next(k for k in range(i + 1, len(src)) if src[k].startswith(end_pat))
    return '\n'.join(src[i:j]).rstrip('\n')

def rep(s, a, b, n=None):
    c = s.count(a)
    assert c > 0, a
    if n is not None:
        assert c == n, (a, c)
    return s.replace(a, b)

# callLS_sim -> callLS_simB
cl = block('theorem callLS_sim ', '/-- **Without soft calls, `runLCS` is `runLC`**')
cl = rep(cl, 'theorem callLS_sim ', 'theorem callLS_simB ', 1)
cl = rep(cl, '(hsof : ∀ b n, env.sof (made p sup) p q b n = false) :',
         '(hsof : ∀ b k nb, info = some (b, k) → env.need b = some nb → env.sof (made p sup) p q b nb = false) :', 1)
cl = rep(cl, 'simp only [hsof, Bool.false_eq_true, if_false]',
         'simp only [hsof b _ bNed rfl hn, Bool.false_eq_true, if_false]', 3)

# runLCS_sim -> runLCS_simD
rl = block('theorem runLCS_sim ', '/-- **`runLCS_eq`**')
rl = rep(rl, 'theorem runLCS_sim ', 'theorem runLCS_simD ', 1)
rl = rep(rl, '''    (hsof : ∀ m p q b n, env.sof m p q b n = false) :
    ∀ (nm : Nomm) (sup : Option Nomm) (goal : CGoalL S) (region : List Nat),''',
         '''    : ∀ (nm : Nomm) (sup : Option Nomm), SofOff env sup nm → ∀ (goal : CGoalL S) (region : List Nat),''', 1)
head, *cases = re.split(r'\n(?=  \| )', rl)
out = [head]
for c in cases:
    name = c.split()[1]
    c = rep(c, 'intro sup goal region', 'intro sup hs goal region', 1)
    if name in ('cons', 'n5', 'n7', 'n10'):
        a, b = {'cons': ('p', 'q'), 'n5': ('p', 'q'), 'n7': ('p', 'q'), 'n10': ('v', 'q')}[name]
        c = rep(c, 'intro sup hs goal region', 'intro sup hs goal region\n    obtain ⟨hs%s, hs%s⟩ := hs' % (a, b), 1)
        c = c.replace('ih%s _ _ _' % a, 'ih%s _ hs%s _ _' % (a, a)).replace('ih%s _ _ _' % b, 'ih%s _ hs%s _ _' % (b, b))
    elif name in ('n3', 'n4'):
        c = c.replace('ihp _ _ _', 'ihp _ hs _ _')
    elif name == 'n6':
        c = rep(c, 'intro sup hs goal region', 'intro sup hs goal region\n    obtain ⟨hsp, hsq, hsr⟩ := hs', 1)
        for v in 'pqr':
            c = c.replace('ih%s _ _ _' % v, 'ih%s _ hs%s _ _' % (v, v))
            c = c.replace('ih%s sup g rg' % v, 'ih%s sup hs%s g rg' % (v, v))
    elif name == 'n2':
        c = rep(c, 'intro sup hs goal region', 'intro sup hs goal region\n    obtain ⟨hsp, hsq, hsb⟩ := sofOff_n2 hs', 1)
        c = rep(c, '''    exact callLS_sim env (fun g rg => ihp sup g rg) (fun g rg => ihq sup g rg) p q info sup goal region
      (fun b n => hsof _ _ _ b n)''',
                '''    exact callLS_simB env (fun g rg => ihp sup hsp g rg) (fun g rg => ihq sup hsq g rg) p q info sup goal region
      hsb''', 1)
    assert ' _ _ _)' not in c.replace('simS_bind3', '').replace('fun g rg', '') or name in ('n0', 'n1'), (name, c)
    out.append(c)
rl = '\n'.join(out)
assert 'hsof' not in rl, rl

hdr = '''import lemmas.Ska.SccLoopSoftEq

/-! # `runLCS` is `runLC` with `sof` false at the nomm's own calls (README Gaps 19 (g), `sim`)

GENERATED by `tools/gen/simoff.py` from `Ska/SccLoopSoftEq.lean`: `callLS_sim` and `runLCS_sim` with
the hypothesis "`sof` false at every call of every nomm" (`∀ m p q b n, env.sof m p q b n = false`)
replaced by `SofOff env sup nm`: `sof` false at each direct call of `nm`, at the `made` of its
`sup`, for the callee's need (the fact `CallOkTN` records per call).  `runLCS_sim` asked it
everywhere, which fails in an SCC with a soft call; here it is asked of one member's nomm.

* `SofOff`, `sofOff_n2`; **`callLS_simB`**; **`runLCS_simD`**; `runLCS_eqD`.  Do not edit by hand. -/

set_option linter.unusedSectionVars false
set_option linter.unusedVariables false

namespace Formalization
namespace SkaModel
namespace Comp

open Nock Lazy

/-- **`sof` false at each direct call of the nomm**, at the `made` of the `sup` its run gets and
the callee's need. -/
def SofOff (env : CallEnv) : Option Nomm → Nomm → Prop
  | ms, Nomm.cons p q => SofOff env ms p ∧ SofOff env ms q
  | ms, Nomm.n2 p q Option.none => SofOff env ms p ∧ SofOff env ms q
  | ms, Nomm.n2 p q (some (b, _)) =>
      (∀ nb, env.need b = some nb → env.sof (made p ms) p q b nb = false) ∧ SofOff env ms p ∧ SofOff env ms q
  | ms, Nomm.n3 p => SofOff env ms p
  | ms, Nomm.n4 p => SofOff env ms p
  | ms, Nomm.n5 p q => SofOff env ms p ∧ SofOff env ms q
  | ms, Nomm.n6 p q r => SofOff env ms p ∧ SofOff env ms q ∧ SofOff env ms r
  | ms, Nomm.n7 p q => SofOff env ms p ∧ SofOff env (some p) q
  | ms, Nomm.n10 _ v q => SofOff env ms v ∧ SofOff env ms q
  | _, _ => True

theorem sofOff_n2 {env : CallEnv} {ms : Option Nomm} {p q : Nomm} {info : Option (Bell × Option Noun)}
    (h : SofOff env ms (Nomm.n2 p q info)) : SofOff env ms p ∧ SofOff env ms q ∧
      ∀ b k nb, info = some (b, k) → env.need b = some nb → env.sof (made p ms) p q b nb = false := by
  rcases info with _ | ⟨b, k⟩
  · exact ⟨h.1, h.2, fun _ _ _ e => by cases e⟩
  · exact ⟨h.2.1, h.2.2, fun b' k' nb e hn => by
      simp only [Option.some.injEq, Prod.mk.injEq] at e
      obtain ⟨rfl, rfl⟩ := e
      exact h.1 nb hn⟩

variable {S : Type} [HoonSet S] {Map : Type → Type} [HoonMap Map] [HoonMapKeys Map]

'''
ftr = '''

/-- **`runLCS_eqD`**: the equation of `runLCS_simD` at a state. -/
theorem runLCS_eqD (env : CallEnv) (snd : Nomm → NeedOrd → Bool) (nm : Nomm) (sup : Option Nomm)
    (hs : SofOff env sup nm) (goal : CGoalL S) (region : List Nat) (g : Gen Map) :
    runLCS env snd sup nm goal region (GenSf.ofGen g) = (runLC env sup nm goal region g).map embS :=
  runLCS_simD env snd nm sup hs goal region g

end Comp
end SkaModel
end Formalization
'''
open('lemmas/Compiler/CompSofOff.lean', 'w').write(hdr + cl + '\n\n' + rl + ftr)
print('ok')
