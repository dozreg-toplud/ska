"""The fixed point `csiFix` of `+compile-scc-in` (README Gaps 21.11), cut into its pushes, as
Lean definitions.

    tools/capped.sh -m 3G python3 tools/gen/csifix.py > lemmas/Compiler/CompSccLoopNouns.lean

`csiFix` (957 cells, the `?.  done` branch of the body of arm `2732` of `K`, as cut by
`tools/gen/member.py`) is

    [8 ORDER [7 [0 1] [8 MAY [7 PUT [7 CONS [8 TOP [8 [1 ST0] [8 [1 0] [8 [1 TRAP] [9 2 0 1]]]]]]]]]]

ORDER the DFS postorder (`=|  [vis out]`, `=|  stk`, `=/  roots ~(tap in scc)`, its trap),
MAY the `=^  may  cache` of the `%may` `+roll` (PUT puts `cache` back at axis 8183, CONS
reshapes the subject around `may`), TOP `(~(run by may) |=(s=straight need.s))`, ST0 `[| 0 ~ ~]`,
`counter` 0, and TRAP the `|-` of the sweeps:

    [7 [0 1] [8 SWROLL [6 [0 8] REC FIN]]]

SWROLL the `+roll` of `order` with the gate of one sweep step, `[0 8]` its `any.st`, REC the
print and the `%=  sweep-loop` (on `any`), FIN `(final & map-local cache)` (on no `any`).
Each part is named inside the larger ones (by structural equality), so that `csiFix_cut` is a
`rfl` fact."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from nouns import *
K = ('C', ('R', 'nhe0b859c3d8aa'), ('C', ('R', 'nh15c74912d225'), ('C', ('A', 0), ('R', 'ana'))))


def seq(n, k):
    out = []
    n = norm(n)
    for _ in range(k - 1):
        assert n[0] == 'C', n
        out.append(norm(n[1]))
        n = norm(n[2])
    out.append(n)
    return out


def op(n, o):
    n = norm(n)
    assert n[0] == 'C' and norm(n[1]) == ('A', o), show(n, maxd=3)[:200]
    return norm(n[2])


carm = slot(2732, K)
_, ccore, _ = seq(carm, 3)
_, _, cb = seq(ccore, 3)
cbody = norm(norm(cb[1])[2])
_, _, _, csiMiss = seq(cbody, 4)
_, _, m1 = seq(csiMiss, 3)
_, _, m2 = seq(m1, 3)
_, _, m3 = seq(m2, 3)
_, _, m4 = seq(m3, 3)
_, _, m5 = seq(m4, 3)
_, _, _, csiFix = seq(m5, 4)

order, r1 = seq(op(csiFix, 8), 2)
r1 = op(r1, 7)
_, r2 = seq(r1, 2)                       # [[0 1] R2]
may, r3 = seq(op(r2, 8), 2)
put, r4 = seq(op(r3, 7), 2)
cons, r5 = seq(op(r4, 7), 2)
top, r6 = seq(op(r5, 8), 2)
st0q, r7 = seq(op(r6, 8), 2)
cnt0, r8 = seq(op(r7, 8), 2)
trapq, r9 = seq(op(r8, 8), 2)
assert norm(cnt0) == ('C', ('A', 1), ('A', 0))
st0 = op(st0q, 1)
trap = op(trapq, 1)
_, t1 = seq(op(trap, 7), 2)
swroll, t2 = seq(op(t1, 8), 2)
ttest, rec, fin = seq(op(t2, 6), 3)
assert norm(ttest) == ('C', ('A', 0), ('A', 8))
obunt, o1 = seq(op(order, 8), 2)
ostk, o2 = seq(op(o1, 8), 2)
oroots, o3 = seq(op(o2, 8), 2)
otrapq, o4 = seq(op(o3, 8), 2)
otrap = op(otrapq, 1)


TEXT = {}


def emit(f, defs):
    subs = []
    for name, n, doc in defs:
        f.write('/-- %s -/\n' % doc)
        TEXT[name] = lean(n, subs)
        f.write('def %s : Noun :=\n  %s\n\n' % (name, TEXT[name]))
        subs.insert(0, (name, n))


f = sys.stdout
f.write('''import lemmas.Compiler.CompSccGate

/-! Generated by `tools/gen/csifix.py`: the fixed point `csiFix` of `+compile-scc-in` cut into
its pushes (README Gaps 21.11). -/

namespace Formalization
namespace Compiler

open Nock

''')
emit(f, [
    ('csfOrdTrap', otrap, 'The trap of the DFS postorder: `?~  stk` (the roots), `?~  kids.i.stk` (pop), the next kid.'),
    ('csfOrdRoots', oroots, '`=/  roots=(list bell)  ~(tap in scc)`.'),
    ('csfOrdBunt', op(obunt, 1), 'The bunt of `[vis=(set bell) out=(list bell)]`.'),
    ('csfOrder', order, '`order`: the DFS postorder of the members over `kids`.'),
    ('csfMay', may, 'The `+roll` over `order` of `member b %may | m ~ c` from an empty `m`: `[may cache]`.'),
    ('csfPut', put, 'The `=^`: `cache` (axis 8183) set to the tail of the pair.'),
    ('csfCons', cons, 'The `=^`: the head of the pair, `may`, pushed on the subject.'),
    ('csfTop', top, '`top`: `(~(run by may) |=(s=straight need.s))`.'),
    ('csfSt0', st0, '`st`: `[| 0 ~ ~]`.'),
    ('csfSwRoll', swroll, 'One sweep: the `+roll` over `order` of the step of `dirty` and `member b %must ..`.'),
    ('csfRec', rec, '`any` set: the print and `%=  sweep-loop` with `st.res(any |)`, `m.res`, `c.res`, `+(counter)`.'),
    ('csfFin', fin, 'No `any`: `(final & map-local cache)`.'),
    ('csfTrap', trap, 'The `|-` of the sweeps: `=/  res` (one sweep), then `?.  any.st.res`.'),
    ('csfFix', csiFix, '`csiFix` from its pushes.'),
])
f.write('''/-- `csiFix` is its pushes. -/
theorem csiFix_cut : csiFix = csfFix := rfl

''')
for name, doc in [('csfFix', 'The pushes of `csiFix`: the DFS, the `%may` sweep and its `=^`, `top`, `st`, `counter` and the trap of the sweeps.'),
                  ('csfTrap', 'The trap of the sweeps: one sweep, then the test on `any.st.res` (axis 8).'),
                  ('csfOrder', 'The DFS: the bunt of `[vis out]`, `stk` empty, `roots`, then its trap.')]:
    f.write('/-- %s -/\ntheorem %s_eq : %s =\n    %s := rfl\n\n' % (doc, name, name, TEXT[name]))
f.write('''end Compiler
end Formalization
''')
