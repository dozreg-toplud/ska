#!/usr/bin/env python3
"""Write lemmas/Compiler/CompRunShapeECases.lean: the cases of +run-shape restated on RsAtE.

Each case lemma on `RsAt` (every rest `y` of `gen`) uses its recursive hypotheses only at the
`y` it was given, so its proof is copied with `RsAt ctx env` -> `RsAtE ctx env E`, `intro y` ->
`intro y hy`, and every use `have h' := H .. y` of a recursive hypothesis `H` -> `.. y hy`.
Every replacement is asserted.  Run from `formalization/`.
"""
import re, sys

BASE = 'lemmas/Compiler/'
OUT = BASE + 'CompRunShapeECases.lean'
IH = {'hp1', 'hp2', 'hp', 'hq', 'hr', 'hv', 'hn'}

def grab(f, name):
    L = open(BASE + 'CompRunShape' + f + '.lean').read().split('\n')
    i = [k for k, l in enumerate(L) if l.startswith('theorem ' + name + ' ')]
    assert len(i) == 1, name
    i = i[0]
    j = i
    while j > 0 and L[j - 1].strip() != '':
        j -= 1
    k = i + 1
    while k < len(L) and not (L[k].strip() == '' and (k + 1 >= len(L) or not L[k + 1].startswith(' '))):
        k += 1
    return '\n'.join(L[j:k])

def ren(name):
    assert name.endswith('W') or name in ('rs_n4', 'rs_n7W', 'rs_consN', 'rs_consP', 'rs_consD', 'rs_n6DP'), name
    if name.endswith('W'):
        return name[:-1] + 'E'
    return name + 'E'

def conv(f, name):
    t = grab(f, name)
    n0 = t.count('RsAt ctx env')
    assert n0 >= 2, name
    t = t.replace('RsAt ctx env', 'RsAtE ctx env E')
    t = t.replace('theorem ' + name + ' ', 'theorem ' + ren(name) + ' ', 1)
    if name != 'rs_consW':
        assert t.count('\n  intro y\n') == 1, name
        t = t.replace('\n  intro y\n', '\n  intro y hy\n')
        cnt = 0
        out = []
        for l in t.split('\n'):
            m = re.match(r'^(\s*(?:· )?have \S+ := )(\S+)(.*) y$', l)
            if m and m.group(2) in IH:
                l = l + ' hy'
                cnt += 1
            out.append(l)
        assert cnt >= 1, name
        t = '\n'.join(out)
    else:
        for s in ('rs_consN', 'rs_consP', 'rs_consD'):
            assert (' ' + s + ' ') in t or ('(' + s + ' ') in t, s
            t = re.sub(r'\b' + s + r'\b', s + 'E', t)
    t = t.replace('`RsAt`', '`RsAtE`')
    return t

def main():
    six = open(BASE + 'CompRunShapeSix.lean').read().split('\n')
    mi = [k for k, l in enumerate(six) if l.startswith('set_option hygiene false in')]
    assert len(mi) == 1
    macro = '\n'.join(six[mi[0]:mi[0] + 5])
    assert 'local macro "six_simp"' in macro and macro.rstrip().endswith('$xs,*])')
    top = [conv('Three', 'rs_n3W'), conv('Leaf', 'rs_n4'), conv('Ind', 'rs_n7W')]
    sec = [conv('Cons', n) for n in ('rs_n5W', 'rs_consN', 'rs_consP', 'rs_consD', 'rs_consW')]
    sec += [conv('Ten', 'rs_n10W'), conv('TwoI', 'rs_n2iW')]
    six6 = conv('Six', 'rs_n6DP')
    hdr = '''import lemmas.Compiler.CompRunShapeTwoI
import lemmas.Compiler.CompRunShapeSix

/-!
# `+run-shape`: the cases restated on `RsAtE` (track A, 2026-11-28)

Generated by `tools/gen/runshapee.py`: the case lemmas on `RsAt` (`rs_n3W`, `rs_n4`, `rs_n7W`,
`rs_n5W`, `rs_consN`/`P`/`D`/`W`, `rs_n10W`, `rs_n2iW`, `rs_n6DP`) use their recursive hypotheses
only at the rest `y` of `gen` they are given, so their proofs are copied on `RsAtE` (the rests of a
property `E`): `rs_n3E`, `rs_n4E`, `rs_n7E`, `rs_n5E`, `rs_consNE`, `rs_consPE`, `rs_consDE`,
`rs_consE`, `rs_n10E`, `rs_n2iE`, `rs_n6DPE`.  `[0 a]` and `[1 k]` have no recursive call and lift by
`rsAtE_of`; the direct `%2` is `rs_n2dW`.
-/

namespace Formalization
namespace Compiler

open Nock Pill Hoon SkaModel SkaModel.Comp

set_option linter.unusedSimpArgs false
set_option linter.unusedSectionVars false
set_option linter.unusedVariables false

variable {ctx : Noun} {E : RsRest → Prop}

'''
    body = hdr + '\n\n'.join(top) + '\n\n' + macro + '\n\nsection\nvariable (hc : CompIn ctx) (h7 : slot? 7 ctx = some compK) {cod : Noun} (hcode : slot? 52 ctx = some cod)\ninclude hc h7 hcode\n\n' + '\n\n'.join(sec + [six6]) + '\n\nend\n\nend Compiler\nend Formalization\n'
    open(OUT, 'w').write(body)
    print('wrote', OUT, len(body.split('\n')), 'lines')

main()
