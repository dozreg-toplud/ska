"""The parts of the sweeps of `+compile-scc-in` (README Gaps 21.11), cut out of the pushes of
`tools/gen/csifix.py`, as Lean definitions.

    tools/capped.sh -m 3G python3 tools/gen/csiloop.py > lemmas/Compiler/CompSccLoopParts.lean

* `csfSwRoll` is `[8 [9 0x2fbdfc 0 0x1fffffff] 9 2 10 [6 [0 254] 7 [0 3] 8 csfSwBunt [1 csfSwGate]
  0 1] 0 2]`: the `+roll` over `order` (axis 126 of the trap core) with the gate whose body is
  `csfSwGate` and whose sample bunt is `csfSwBunt` (`[bell-bunt st map-local cache]`).
* `csfSwGate` is `[8 csfSwDirty 6 [0 2] csfSwYes csfSwNo]`; `csfSwYes` is `[8 [4 0 234] 8
  csfSwMem csfSwOut]`, `csfSwMem` the call of `member` with `keep` `csfSwKeep`, `csfSwOut` the
  new `[st m c]` (`csfSwSt` the new `st`).
* `csfMay` is `[7 [0 1] 8 [9 0x2fbdfc 0 0xffffff] 9 2 10 [6 [0 6] 7 [0 3] 8 csfMayBunt [1
  csfMayGate] 0 1] 0 2]`.
* `csfRec` is `[8 csfRecPrint 9 2 10 [6 7 [0 3] csfRecCall] 0 2]`."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'csifix.py')).read()
exec(src.split('TEXT = {}')[0])


def lit(n):
    """the quoted noun of [1 n]"""
    return op(n, 1)


# csfSwRoll
_, sw1 = seq(op(swroll, 8), 2)
sw2 = op(sw1, 9)
assert norm(norm(sw2)[1]) == ('A', 2)
sw3 = op(norm(sw2)[2], 10)
swsam, swk = seq(sw3, 2)
swsam = op(swsam, 6)
swlist, swg = seq(swsam, 2)
assert norm(swlist) == ('C', ('A', 0), ('A', 254))
swg = op(swg, 7)
_, swg = seq(swg, 2)
swbunt, swq = seq(op(swg, 8), 2)
swbodyq, _ = seq(swq, 2)
swgate = lit(swbodyq)
swdirty, sg1 = seq(op(swgate, 8), 2)
_, swyes, swno = seq(op(sg1, 6), 3)
swinc, sy1 = seq(op(swyes, 8), 2)

swmem, swout = seq(op(sy1, 8), 2)
swst, _ = seq(swout, 2)
# the keep inside the member call: [8 [0 8190] 9 2 10 [6 [0 124] MUST KEEP ..] 0 2]
_, sm1 = seq(op(swmem, 8), 2)
sm2 = op(norm(op(sm1, 9))[2], 10)
smsam, _ = seq(sm2, 2)
smsam = op(smsam, 6)
_, _, smkeep, _, _, _ = seq(smsam, 6)
swkeep = op(smkeep, 7)
_, swkeep = seq(swkeep, 2)

# csfMay
may1 = op(may, 7)
_, may2 = seq(may1, 2)
_, may3 = seq(op(may2, 8), 2)
may4 = op(norm(op(may3, 9))[2], 10)
maysam, _ = seq(may4, 2)
maysam = op(maysam, 6)
_, mayg = seq(maysam, 2)
_, mayg = seq(op(mayg, 7), 2)
maybunt, mayq = seq(op(mayg, 8), 2)
maybodyq, _ = seq(mayq, 2)
maygate = lit(maybodyq)

# csfRec
recprint, rc1 = seq(op(rec, 8), 2)
rc2 = op(norm(op(rc1, 9))[2], 10)
rcsam, _ = seq(rc2, 2)
rcsam = op(rcsam, 6)
_, reccall = seq(op(rcsam, 7), 2)

TEXT = {}


def emit(f, defs, subs):
    for name, n, doc in defs:
        f.write('/-- %s -/\n' % doc)
        TEXT[name] = lean(n, subs)
        f.write('def %s : Noun :=\n  %s\n\n' % (name, TEXT[name]))
        subs.insert(0, (name, n))


f = sys.stdout
f.write('''import lemmas.Compiler.CompSccLoopNouns

/-! Generated by `tools/gen/csiloop.py`: the gates of the sweep `+roll`, of the `%may` `+roll`
and the two halves of `csfRec` (README Gaps 21.11). -/

namespace Formalization
namespace Compiler

open Nock

''')
subs = []
emit(f, [
    ('csfSwKeep', swkeep, '`keep`: `(gth t (mul 4 ~(wyt in scc)))`.'),
    ('csfSwDirty', swdirty, '`dirty`: `?~  r=(~(get by ran.st) b)  &` then `+any:in` over `(~(get ju kids) b)`.'),
    ('csfSwMem', swmem, '`r`: `(member b %must keep m top c)`.'),
    ('csfSwSt', swst, 'The new `st`: `[& t (~(put by ran.st) b t) ?:(chg.r (~(put by chg.st) b t) chg.st)]`.'),
    ('csfSwOut', swout, 'The new `[st m c]`: `[st [ray cache]:r]`.'),
    ('csfSwYes', swyes, 'A dirty member: `t`, `r`, the new `[st m c]`.'),
    ('csfSwNo', swno, 'A clean member: `[st m c]` of the sample.'),
    ('csfSwGate', swgate, 'The body of the gate of one sweep step.'),
    ('csfSwBunt', swbunt, 'The sample bunt of that gate: `[bell-bunt st map-local cache]` of the trap core.'),
    ('csfMayGate', maygate, 'The body of the gate of the `%may` `+roll`: `[ray cache]:(member b %may | m ~ c)`.'),
    ('csfMayBunt', maybunt, 'Its sample bunt: `[bell-bunt (bunt of the map) cache]`.'),
    ('csfRecPrint', recprint, '`(print-comp 0 |.(..))`.'),
    ('csfRecCall', reccall, 'The `%=  sweep-loop`: the core edited at `cache`, `map-local`, `st`, `counter`, then `$`.'),
], subs)
for name, doc, n in [
        ('csfSwRoll', 'The sweep: the `+roll` over `order` with the gate `csfSwGate`.', swroll),
        ('csfSwGate', 'The gate of one sweep step: `dirty`, then the two cases.', swgate),
        ('csfSwYes', 'A dirty member: `t`, `r`, the new `[st m c]`.', swyes),
        ('csfMay', 'The `%may` `+roll`.', may),
        ('csfRec', 'The print and the `%=  sweep-loop`.', rec)]:
    t = lean(n, [s for s in subs if s[0] != name])
    f.write('/-- %s -/\ntheorem %s_eq : %s =\n    %s := rfl\n\n' % (doc, name, name, t))
f.write('''end Compiler
end Formalization
''')
