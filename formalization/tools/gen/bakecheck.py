import re, sys
HERE = __file__.rsplit('/', 1)[0]
def cord(s):
    return int.from_bytes(s.encode(), 'little')
tok = re.compile(r'\[|\]|%\.[yn]|%[a-z0-9-]+|~|&|\||[0-9][0-9.]*')
def parse(ts, i):
    t = ts[i]
    if t == '[':
        items = []; i += 1
        while ts[i] != ']':
            x, i = parse(ts, i); items.append(x)
        i += 1
        n = items[-1]
        for x in reversed(items[:-1]): n = (x, n)
        return n, i
    if t == '%.y' or t == '&' or t == '~': return 0, i + 1
    if t == '%.n' or t == '|': return 1, i + 1
    if t.startswith('%'): return cord(t[1:]), i + 1
    return int(t.replace('.', '')), i + 1
def lean(n):
    if isinstance(n, int): return f'(A {n})' if n < 10**6 else f'(A {hex(n)})'
    return f'(C {lean(n[0])} {lean(n[1])})'
def fill(cape, data, v):
    if cape == 0: return data
    if cape == 1: return v
    h = data[0] if isinstance(data, tuple) else 0
    t = data[1] if isinstance(data, tuple) else 0
    return (fill(cape[0], h, v), fill(cape[1], t, v))
def treap(t, out):
    if t == 0: return
    (k, b), l, r = t[0], t[1][0], t[1][1]
    out[k] = b; treap(l, out); treap(r, out)
txt = open(sys.argv[1]).read()
