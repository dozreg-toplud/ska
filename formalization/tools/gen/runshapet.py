def grab(f, name):
    L = open(BASE + f).read().split('\n')
    i = [k for k, l in enumerate(L) if l.startswith('theorem ' + name + ' ')]
    assert len(i) == 1, name
    i = i[0]
    j = i
    while j > 0 and L[j - 1].strip() != '':
        j -= 1
    k = i + 1
    while k < len(L) and not (L[k].strip() == '' and (k + 1 >= len(L) or not L[k + 1].startswith(' '))):
        k += 1
    return '\n'.join(L[j:k])


def rep(t, a, b, n=None):
    c = t.count(a)
    assert c >= 1 and (n is None or c == n), (a, c)
    return t.replace(a, b)


