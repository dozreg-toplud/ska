#!/usr/bin/env python3
"""Write lemmas/Compiler/CompRunSoftMede.lean: `+mede` at a soft rest (README Gaps 19 (g)).

Copies `md_loop`, `md_gate` (CompMedeLink.lean), `comp_mede_all` (CompMedeGen.lean) and
`comp_run_n1_next` (CompRunLeafL.lean) with the hypothesis `x.SoftOut o` replaced by
`x.SoftOut o ∨ MedeFits som ned` (the block is soft only where `+crash-need` is not reached:
`+crash-need` is the only reader of `soft.gen` in `+mede`).  Asserted replacements."""
import re, sys, os
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.join(here, '..', '..')
C = os.path.join(root, 'lemmas', 'Compiler')

def grab(path, start, stop):
    s = open(os.path.join(C, path)).read()
    i = s.index(start)
    j = s.index(stop, i)
    return s[i:j]

def rep(s, a, b, n=None):
    c = s.count(a)
    assert c > 0, a
    if n is not None:
        assert c == n, (a, c)
    return s.replace(a, b)

loop = grab('CompMedeLink.lean', 'theorem md_loop', '/-- The arm `sure-require-look`')
loop = rep(loop, 'theorem md_loop', 'theorem md_loopF', 1)
loop = rep(loop, '''    (hs : x.SoftOut o') : ∀ (ned : Need) (som : Noun) (g : Gen (TreapMap mugF)),
    nock''', ''' : ∀ (ned : Need) (som : Noun) (g : Gen (TreapMap mugF)), (x.SoftOut o' ∨ MedeFits som ned) →
    nock''', 1)
loop = rep(loop, '    intro som g\n', '    intro som g hs\n', 4)
loop = rep(loop, '(Sum.inl n) (Need.pair p q) hs', "(Sum.inl n) (Need.pair p q) (hs.resolve_right (by simp [MedeFits]))", 1)
loop = rep(loop, '(Sum.inl n) (Need.both r h t) hs', "(Sum.inl n) (Need.both r h t) (hs.resolve_right (by simp [MedeFits]))", 1)
loop = rep(loop, 'have h1 := ihp a g\n', 'have h1 := ihp a g (hs.imp id fun h => by simp only [MedeFits] at h; exact h.1)\n', 1)
loop = rep(loop, 'have h2 := ihq b g1\n', 'have h2 := ihq b g1 (hs.imp id fun h => by simp only [MedeFits] at h; exact h.2)\n', 1)
loop = rep(loop, 'have h1 := ihh a g0\n', 'have h1 := ihh a g0 (hs.imp id fun h => by simp only [MedeFits] at h; exact h.1)\n', 1)
loop = rep(loop, 'have h2 := iht b g1\n', 'have h2 := iht b g1 (hs.imp id fun h => by simp only [MedeFits] at h; exact h.2)\n', 1)

gate = grab('CompMedeLink.lean', 'theorem md_gate', '/-! ## `+mede`')
gate = rep(gate, 'theorem md_gate', 'theorem md_gateF', 1)
gate = rep(gate, "(g : Gen (TreapMap mugF)) (hs : x.SoftOut o')",
           "(g : Gen (TreapMap mugF))\n    (hs : ∀ ned g1, sureRequireLook sur g = some (ned, g1) → x.SoftOut o' ∨ MedeFits som ned)", 1)
gate = rep(gate, 'md_loop hc x sur.toNoun (genNoun g x) B TH LAZ o o\' hs ned som g1',
           'md_loopF hc x sur.toNoun (genNoun g x) B TH LAZ o o\' ned som g1 (hs ned g1 e)', 1)

mede = grab('CompMedeGen.lean', 'theorem comp_mede_all', '\nend Compiler')
mede = rep(mede, 'theorem comp_mede_all', 'theorem comp_mede_allF', 1)
mede = rep(mede, '(hP : WalkP (mdP x) g.bo laz)', '(hP : WalkP (mdPF x som) g.bo laz)', 1)
mede = rep(mede, '(mdP x)\n', '(mdPF x som)\n', 1)
mede = rep(mede, "(fun o s g' hp => md_gate hc hl x _ mdBat th.toNoun laz.toNoun g.bo o som s g' hp.1 hp.2)",
           "(fun o s g' hp => md_gateF hc hl x _ mdBat th.toNoun laz.toNoun g.bo o som s g' (hp.1 g') hp.2)", 1)

n1 = grab('CompRunLeafL.lean', 'theorem comp_run_n1_next', '/-- **The case `%1` on every goal')
n1 = rep(n1, 'theorem comp_run_n1_next', 'theorem comp_run_n1_nextF', 1)
n1 = rep(n1, '''(region : List Nat) (g : Gen (TreapMap mugF)) (hlok : LAll CrLok laz) :
    CompRunAt ctx (Nomm.n1 k) (CGoalL.next laz th) region g := by''',
'''(region : List Nat) (g : Gen (TreapMap mugF)) (x : GenRest) (hP : WalkP (mdPF x k) g.bo laz)
    (mono sup : Noun) :
    nock (crSubj mono (Nomm.n1 k).toNoun (CGoalL.next laz th).toNoun (listNoun A region) sup (compCore g x ctx)) crDol
      = (runL (Nomm.n1 k) (CGoalL.next laz th) region g).map fun p => C p.1.goal.toNoun (genNoun p.2 x) := by''', 1)
n1 = rep(n1, '  intro x mono sup hx\n', '', 1)
n1 = rep(n1, '(walk_mdP hx g.bo hlok)', 'hP', 1)
n1 = rep(n1, 'comp_mede_all hc', 'comp_mede_allF hc', 1)

head = '''import lemmas.Compiler.CompMedeGen
import lemmas.Compiler.CompRunLeafL

/-!
# `+mede` at a soft rest (README Gaps 19 (g))

Generated by `tools/gen/softmede.py`; do not edit.  `+mede` (the case `%1` on a `%next` goal)
reads `soft.gen` only in `+crash-need` (line 5961: `?:  (~(has by soft.gen) o)  (soft-ask ..)`),
which it reaches only where the constant is an atom and the need asks a cell.  After a soft tail
call the goal holds the bond `+soft-bond` made, whose block is a key of `soft`, so `mdP`
(`x.SoftOut` at every visited block) fails there; `mdPF` asks `x.SoftOut o` or `MedeFits`
(no `+crash-need` on the need `+sure-require-look` gives).  The model `medeL` has no
`+soft-ask`, so where `MedeFits` fails at a soft block the model (`runLCS`'s `%1`, a lift of
`runL`) and the Hoon part ways: the hypothesis is needed, not an artefact of the proof.

* `MedeFits som ned`: the constant has a cell wherever the need asks one;
* `md_loopF`, `md_gateF`, **`comp_mede_allF`**: `md_loop`, `md_gate`, `comp_mede_all` with
  `x.SoftOut o ∨ MedeFits`;
* **`comp_run_n1_nextF`**: the case `%1` on a `%next` goal at any rest, under `WalkP (mdPF x k)`.
-/

namespace Formalization
namespace Compiler

open Nock Pill Hoon SkaModel SkaModel.Comp

set_option linter.unusedSimpArgs false
set_option linter.unusedSectionVars false
set_option linter.unusedVariables false

variable {ctx : Noun}

/-- **The constant fits the need**: no `+crash-need` in `+mede`'s loop (a cell wherever the need
is `^` or `%both`). -/
def MedeFits : Noun → Need → Prop
  | Noun.cell a b, Need.pair p q => MedeFits a p ∧ MedeFits b q
  | Noun.cell a b, Need.both _ h t => MedeFits a h ∧ MedeFits b t
  | Noun.atom _, Need.pair _ _ => False
  | Noun.atom _, Need.both _ _ _ => False
  | _, _ => True

/-- What the walk of `+mede` needs at a visited block: not a key of `soft`, or no `+crash-need`
on the need `+sure-require-look` gives there; and no lock at axis `0`. -/
def mdPF (x : GenRest) (som : Noun) (o : Nat) (s : Sure CSet) : Prop :=
  (∀ (g : Gen (TreapMap mugF)) ned g1, sureRequireLook s g = some (ned, g1) → x.SoftOut o ∨ MedeFits som ned) ∧ lok0 o s

theorem mdPF_of_mdP {x : GenRest} {som : Noun} {o : Nat} {s : Sure CSet} (h : mdP x o s) : mdPF x som o s :=
  ⟨fun _ _ _ _ => Or.inl h.1, h.2⟩

'''
out = head + loop + '/-- The gate of `+mede` with `mdPF`. -/\n' + gate + '/-- **`+mede` on every lazy need at a soft rest.** -/\n' + mede + '\n/-- **The case `%1` on a `%next` goal at any rest.** -/\n' + n1 + 'end Compiler\nend Formalization\n'
open(os.path.join(C, 'CompRunSoftMede.lean'), 'w').write(out)
print('ok', len(out))
