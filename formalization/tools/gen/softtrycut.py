"""Cut `seTryPath` (the try path of `+soft-emit`, `CompSccLoopSoftEmitCut.lean`) into named nouns
at every push (`7` / `8`) and `%6` that `tools/gen/softtry.py` prints (README Gaps 21.22).

    python3 tools/gen/softtrycut.py > lemmas/Compiler/CompSccLoopSoftTryCut.lean

Names: a chain of pushes with prefix `P` is `P0 P1 ..` (`Pi` the rest before push `i`, so
`P0` is the whole chain), `PHi` the head of push `i` (inline when it has at most 3 cells); a
`%6` ending the chain is `[6 PT [PY0 PN0]]` (the yes chain `PY`, the no chain `PN`), a tail
`PZ`.  Every definition is its own equation; `seTryPath_eq : seTryPath = tp0` by `rfl`."""
import os, re, sys
sys.setrecursionlimit(100000)
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', '..', 'lemmas', 'Compiler', 'CompSccLoopSoftEmitCut.lean')
s = open(SRC).read()
defs = {m.group(1): m.group(2) for m in re.finditer(r'def (\w+) : Noun :=\n((?:  .*\n)+)', s)}


def parse_text(body):
    toks = re.findall(r'\(|\)|0x[0-9a-fA-F]+|\d+|[A-Za-z_][A-Za-z0-9_]*', body)
    pos = [0]

    def p():
        t = toks[pos[0]]
        if t == '(':
            pos[0] += 1
            v = p()
            assert toks[pos[0]] == ')'
            pos[0] += 1
            return v
        if t == 'C':
            pos[0] += 1
            a = p()
            b = p()
            return ('c', a, b)
        if t == 'A':
            pos[0] += 1
            n = toks[pos[0]]
            pos[0] += 1
            return ('a', int(n, 0))
        pos[0] += 1
        return ('n', t)
    return p()


memo = {}


def cells(v):
    if v[0] == 'c':
        return 1 + cells(v[1]) + cells(v[2])
    if v[0] == 'n' and v[1] in defs:
        if v[1] not in memo:
            memo[v[1]] = cells(parse_text(defs[v[1]]))
        return memo[v[1]]
    return 0


def show(v):
    if v[0] == 'a':
        return '(A %s)' % (hex(v[1]) if v[1] > 9999 else str(v[1]))
    if v[0] == 'n':
        return v[1]
    return '(C %s %s)' % (show(v[1]), show(v[2]))


out = []   # (name, text, doc), emitted in reverse (leaves first)
shapes = []


def head(nm, v):
    if cells(v) <= 3:
        return show(v)
    out.append((nm, show(v)))
    return nm


def chain(pre, cur, depth):
    parts = []
    while cur[0] == 'c' and cur[1][0] == 'a' and cur[1][1] in (7, 8) and cur[2][0] == 'c':
        parts.append((cur[1][1], cur[2][1]))
        cur = cur[2][2]
    k = len(parts)
    if cur[0] == 'c' and cur[1][0] == 'a' and cur[1][1] == 6:
        t, y, n = cur[2][1], cur[2][2][1], cur[2][2][2]
        shapes.append('%s%d: %d pushes, %%6 (test %d cells)' % (pre, k, k, cells(t)))
        tn = head(pre + 'T', t)
        chain(pre + 'Y', y, depth + 1)
        chain(pre + 'N', n, depth + 1)
        out.append(('%s%d' % (pre, k), '(C (A 6) (C %s (C %sY0 %sN0)))' % (tn, pre, pre)))
    else:
        shapes.append('%s%d: %d pushes, tail (%d cells)' % (pre, k, k, cells(cur)))
        out.append(('%s%d' % (pre, k), show(cur)))
    for i in range(k - 1, -1, -1):
        op, h = parts[i]
        hn = head('%sH%d' % (pre, i), h)
        out.append(('%s%d' % (pre, i), '(C (A %d) (C %s %s%d))' % (op, hn, pre, i + 1)))


v = parse_text(defs['seTryPath'])
chain('tp', v, 0)
print('import lemmas.Compiler.CompSccLoopSoftEmitCut\n')
print('/-! # The try path of `+soft-emit` cut at its pushes (README Gaps 21.22)\n')
print('Generated by `tools/gen/softtrycut.py` (do not edit by hand): `seTryPath` (1707 cells) as chains')
print('of pushes.  `tpPi` is the rest of chain `P` before its push `i`, `tpPHi` that push\'s head, `tpPT`')
print('the test of the `%6` ending chain `P`, `tpPY0` / `tpPN0` its branches.  The `%6`s, against the')
print('Hoon of `+soft-emit` (line 5323):')
print('* `tp1` (test 52): `?>  ?=([~ ~ %hop ~ *] lat)`;')
print('* `tpY6` (test 4): `?:  ?=(%mean kin.s)` (`tpYY` the trap path `%mean`, `tpYN` the others);')
print('* `tpYY0` (test 2): `?>  ?=(^ aux.s)`; `tpYYY14` (test 44): `?>  ?=([~ * %hop ~ *] pla)`;')
print('* `tpYN9` (test 16): `?.  (soft-free o last.s def)`: `tpYNY` the tries last (`+soft-free` `&`),')
print('  `tpYNN` `+:(flag(gen gen) fail)` (`|`).')
print('The chains:')
for x in shapes:
    print('* `%s`' % x)
print('-/\n')
print('namespace Formalization\nnamespace Compiler\n\nopen Nock\n')
for nm, txt in out:
    print('def %s : Noun :=\n  %s\n' % (nm, txt))
print('theorem seTryPath_eq : seTryPath = tp0 := by rfl\n')
print('end Compiler\nend Formalization')
