#!/usr/bin/env python3
"""Track A: `csi_gate_ranked_soft2T` from track I's `csi_gate_ranked_soft2F`.

Copies the theorem out of `lemmas/Compiler/CompSccLoopSoft2Loop.lean` and replaces its sweep
hypotheses `SweepLeft` by `SweepLeftT` (`CompRunShapeSweepT.lean`: a callee compiled inside
`+run-shape` allowed) and `memSweepCall_of_A` by `memSweepCall_of_AT`.  Every replacement is
asserted to occur exactly the given number of times, so a change of the source fails loudly.
Run from `formalization/`: `python3 tools/gen/runshapeloopt.py`.
"""
import pathlib
import sys

SRC = pathlib.Path("lemmas/Compiler/CompSccLoopSoft2Loop.lean")
DST = pathlib.Path("lemmas/Compiler/CompSccLoopSoft2T.lean")

src = SRC.read_text()
start = src.index("/-- **The loop's gate for a real SCC on the fixed soft model, no `RunAgree`**")
end = src.index("end Compiler", start)
body = src[start:end].rstrip() + "\n"

REPS = [
    ("/-- **The loop's gate for a real SCC on the fixed soft model, no `RunAgree`**: the sweeps' calls\n"
     "from `SweepLeft` (track A's branch), ",
     "/-- **The loop's gate for a real SCC on the fixed soft model, no `RunAgree`, callees compiled\n"
     "inside the sweeps**: the sweeps' calls from `SweepLeftT` (track A's threaded branch, K's leaf\n"
     "`SweepMissStep` per outside callee), ", 1),
    ("theorem csi_gate_ranked_soft2F", "theorem csi_gate_ranked_soft2T", 1),
    ("SweepLeft r xs order kids inl P Mode.may", "SweepLeftT r xs order kids inl env (RK SC0 inl) P SCC x Mode.may", 1),
    ("SweepLeft r xs order kids inl P Mode.must", "SweepLeftT r xs order kids inl env (RK SC0 inl) P SCC x Mode.must", 1),
    ("memSweepCall_of_A ", "memSweepCall_of_AT ", 2),
]
for a, b, n in REPS:
    c = body.count(a)
    if c != n:
        sys.exit(f"replacement {a!r}: {c} occurrences, expected {n}")
    body = body.replace(a, b)
for bad in ["SweepLeft r", "memSweepCall_of_A ", "soft2F"]:
    if bad in body:
        sys.exit(f"left over: {bad!r}")

HEAD = '''import lemmas.Compiler.CompSccLoopSoft2Loop
import lemmas.Compiler.CompRunShapeSweepT

/-! # The loop on the fixed soft model, callees compiled inside the sweeps (track A, generated)

GENERATED by `tools/gen/runshapeloopt.py` from track I's `csi_gate_ranked_soft2F`
(`CompSccLoopSoft2Loop.lean`): do not edit by hand.

**`csi_gate_ranked_soft2T`**: `csi_gate_ranked_soft2F` with the sweep hypotheses `SweepLeftT`
(`CompRunShapeSweepT.lean`) in place of `SweepLeft`: a direct call's callee outside the SCC may
miss `nary.cache` inside `+run-shape` and be compiled there (K's leaf `SweepMissStep`), and the
sweep gates come from `memSweepCall_of_AT`.  The loop itself is unchanged: track I's `MemSweepCall`
already asks `QK` and the members' `sure` entries at the cache the branch leaves, which may be
bigger than the cache of `+inlined`. -/

namespace Formalization
namespace Compiler

open Nock Pill Hoon SkaModel SkaModel.Comp SkaModel.SccLoop

set_option linter.unusedVariables false

'''
DST.write_text(HEAD + body + "\nend Compiler\nend Formalization\n")
print(f"wrote {DST}")
