#!/usr/bin/env python3
"""pill2core.py PILL OUT.lean: the pill file as a Lean atom, byte by byte.

    python3 tools/pill2core.py pill/steel.pill core/Pill.lean
    python3 tools/pill2core.py --check pill/steel.pill core/Pill.lean
    python3 tools/pill2core.py --check pill/steel.pill path/to/steel.c

The lines between the braces are those of `xxd -i`, which vere's steel.c is
made with: twelve bytes to a line, in file order.  --check reads the bytes
back from the Lean file (or from a steel.c) and compares them with the pill
file, byte for byte.
"""
import hashlib, re, sys

def body(data):
    rows = [data[i:i + 12] for i in range(0, len(data), 12)]
    return ',\n'.join('  ' + ', '.join('0x%02x' % b for b in r) for r in rows)

def main():
    check = sys.argv[1] == '--check'
    pill, out = sys.argv[2:4] if check else sys.argv[1:3]
    data = open(pill, 'rb').read()
    if check:
        text = open(out).read()
        text = text[text.rindex('{', 0, text.index('0x')):]
        text = text[:text.index('}')]
        back = bytes(int(b, 16) for b in re.findall(r'0x([0-9a-f]{2})\b', text))
        ok = back == data
        print('pill matches' if ok else 'PILL DIFFERS')
        sys.exit(0 if ok else 1)
    sha = hashlib.sha256(data).hexdigest()
    with open(out, 'w') as f:
        f.write('''module

public import core.Bytes

/-!
Generated by `tools/pill2core.py` from `pill/steel.pill`; check it against the
file with `python3 tools/pill2core.py --check pill/steel.pill core/Pill.lean`.

The steel pill as an atom: the number whose bytes, lowest first, are the
bytes of the file.  %d bytes, sha256 %s.

The lines between the braces are the lines between the braces of vere's
`pkg/vere/steel/steel.c` (`xxd -i`), and can be copied either way.
-/

@[expose] public section

namespace Formalization

def pill : Nat := bytes%% {
''' % (len(data), sha))
        f.write(body(data))
        f.write('\n}\n\nend Formalization\n')
    print('%d bytes, sha256 %s' % (len(data), sha))

main()
