#!/usr/bin/env python3
"""pill2core.py PILL OUT.lean: the pill file as a Lean atom, in 1024-byte chunks.

    python3 tools/pill2core.py pill/steel.pill core/Pill.lean
    python3 tools/pill2core.py --check pill/steel.pill core/Pill.lean

--check reads the chunks back from the Lean file and compares them with the
pill file, byte for byte.
"""
import hashlib, re, sys

CHUNK = 1024

def main():
    check = sys.argv[1] == '--check'
    pill, out = sys.argv[2:4] if check else sys.argv[1:3]
    data = open(pill, 'rb').read()
    if check:
        text = open(out).read()
        body = text[text.index('def pill'):]
        chunks = re.findall(r'0x([0-9a-f]+)', body)
        back = b''.join(int(c, 16).to_bytes(CHUNK, 'little') for c in chunks)
        ok = back.rstrip(b'\0') == data.rstrip(b'\0') and len(back) - len(data) < CHUNK
        print('pill matches' if ok else 'PILL DIFFERS')
        sys.exit(0 if ok else 1)
    sha = hashlib.sha256(data).hexdigest()
    chunks = [data[i:i + CHUNK] for i in range(0, len(data), CHUNK)]
    with open(out, 'w') as f:
        f.write('''module

/-!
Generated by `tools/pill2core.py` from `pill/steel.pill`; check it against the
file with `python3 tools/pill2core.py --check pill/steel.pill core/Pill.lean`.

The steel pill as an atom: the number whose bytes, lowest first, are the
bytes of the file.  %d bytes, sha256 %s.

Lean cannot read a literal of this size in one piece, so the atom is given in
chunks of %d bytes.  A chunk is written as a number, so its last byte comes
first on the line.
-/

@[expose] public section

namespace Formalization

/-- The atom whose bytes, lowest first, are the chunks in order, each chunk
%d bytes wide. -/
def glue : List Nat → Nat
  | [] => 0
  | chunk :: rest => chunk + 2 ^ %d * glue rest

def pill : Nat := glue [
''' % (len(data), sha, CHUNK, CHUNK, 8 * CHUNK))
        f.write(',\n'.join('  0x%x' % int.from_bytes(c, 'little') for c in chunks))
        f.write(']\n\nend Formalization\n')
    print('%d bytes, %d chunks, sha256 %s' % (len(data), len(chunks), sha))

main()
