#!/usr/bin/env python3
"""pill2cue.py PILL OUTDIR: the files of lemmas/Pill/Cue, which prove that
`cue pill` is the noun of lemmas/Pill (`CueRoot`).

The pill is cued here as a stream of tokens (an atom, the two bits of a cell,
a reference back), each at a bit position.  The nouns that some reference
points to are the entries of the table `KV` of lemmas/CueRel.lean, numbered in
the order in which their decoding ends.  The files are:

* `Win.lean`: the windows `W<k>`, the bits `8192 * k` to `8192 * k + 16384`
  of the pill as one literal, and `win<k>`, that they are those bits.
* `J000.lean`, ...: a chain of the nouns of the pill, in the order in which
  their decoding ends.  `k<j>` is the entry `j` of the table; `s<b>` is a noun
  that starts at bit `b` and is named only to keep each term below `JLIMIT`
  cells.  Each file ends with the part `KV<f>` of the table for its entries.
* `KV.lean`: the table `KV`, which picks the part by the entry's number.
* `D<b>.lean`: theorems `d<b> : Dec pill KV b n e i i'` for the nouns `n`
  that start at bit `b`, each proved by `cue_dec` from the windows and the
  theorems below it.  A file imports the files of the theorems it uses.
* `Root.lean`: `cue pill = some root`.

A file is rewritten only when its text changes, so a regenerated file is
byte-identical when its content did not change.
"""
import os
import sys

JLIMIT = 128        # cells per named noun, at most
LLIMIT = 1200       # tokens per theorem, about
FLIMIT = 24000      # tokens per file of theorems, about
JFILE = 1500        # nouns per file of the chain, about

sys.setrecursionlimit(100000)

GEN = '/-\nGenerated by tools/pill2cue.py from a steel pill; do not edit.\n-/\n'


def lit(n):
    return str(n) if n < 1 << 16 else hex(n)


def decode(data):
    """the tokens of the jam, in the order of their bits: kind ('a', 'c',
    'r'), start, end, value (the atom, or the bit a reference points to),
    and the head and tail of a cell"""
    n = int.from_bytes(data, 'little')
    bits = bin(n)[2:][::-1]

    def rub(pos):
        z = 0
        while bits[pos + z] == '0':
            z += 1
        if z == 0:
            return 1, 0
        lb = bits[pos + z + 1:pos + z + z]
        ln = (int(lb[::-1], 2) if lb else 0) | (1 << (z - 1))
        s = pos + z + z
        body = bits[s:s + ln]
        return z + z + ln, (int(body[::-1], 2) if body else 0)

    kind, start, end, val, kids = [], [], [], [], []
    pos = 0
    todo = [('cue', -1, 0)]
    while todo:
        op, par, slot = todo.pop()
        if op == 'cue':
            t = len(kind)
            b = pos
            if bits[pos] == '0':
                u, v = rub(pos + 1)
                pos += 1 + u
                kind.append('a'); val.append(v); end.append(pos); kids.append(None)
            elif bits[pos + 1] == '0':
                pos += 2
                kind.append('c'); val.append(None); end.append(None); kids.append([None, None])
                todo.append(('end', t, 0))
                todo.append(('cue', t, 1))
                todo.append(('cue', t, 0))
            else:
                u, v = rub(pos + 2)
                pos += 2 + u
                kind.append('r'); val.append(v); end.append(pos); kids.append(None)
            start.append(b)
            if par >= 0:
                kids[par][slot] = t
        else:
            end[par] = pos
    assert pos == len(bits), (pos, len(bits))
    return kind, start, end, val, kids, len(bits)


def postorder(kids, kind, root=0):
    out = []
    st = [(root, False)]
    while st:
        t, done = st.pop()
        if done or kind[t] != 'c':
            out.append(t)
            continue
        st.append((t, True))
        st.append((kids[t][1], False))
        st.append((kids[t][0], False))
    return out


def write(path, text, written):
    written.add(os.path.abspath(path))
    if os.path.exists(path):
        with open(path) as fh:
            if fh.read() == text:
                return
    with open(path, 'w') as fh:
        fh.write(text)


def main():
    pill, outdir = sys.argv[1], sys.argv[2]
    data = open(pill, 'rb').read()
    kind, start, end, val, kids, nbits = decode(data)
    ntok = len(kind)
    at = {start[t]: t for t in range(ntok)}
    post = postorder(kids, kind)
    post_index = {t: k for k, t in enumerate(post)}

    # the table: the tokens that a reference points to, by the end of their decoding
    targets = set(val[t] for t in range(ntok) if kind[t] == 'r')
    key = {}
    for t in post:
        if kind[t] != 'r' and start[t] in targets:
            key[t] = len(key)
    nkeys = len(key)

    # the named nouns: the entries, the root, and cells cut off to keep terms small
    named = {}
    for t, j in key.items():
        named[t] = 'k%d' % j
    if 0 not in named:
        named[0] = 's0'
    size = {}
    for t in post:
        if kind[t] != 'c':
            continue
        s = 1 + sum(size[c] for c in kids[t] if kind[c] == 'c' and c not in named)
        if s > JLIMIT and t not in named:
            named[t] = 's%d' % start[t]
            s = 1
        size[t] = 1 if t in named else s

    def name_of_ref(t):
        return named[at[val[t]]]

    def term(t, top):
        """the term of the token t inside a named noun"""
        if kind[t] == 'r':
            return name_of_ref(t)
        if not top and t in named:
            return named[t]
        if kind[t] == 'a':
            return 'A %s' % lit(val[t])
        out = []

        def go(u, paren):
            if kind[u] == 'r':
                out.append(name_of_ref(u))
            elif u in named and u != t:
                out.append(named[u])
            elif kind[u] == 'a':
                out.append('(A %s)' % lit(val[u]) if paren else 'A %s' % lit(val[u]))
            else:
                if paren:
                    out.append('(')
                out.append('C ')
                go(kids[u][0], True)
                out.append(' ')
                go(kids[u][1], True)
                if paren:
                    out.append(')')
        go(t, False)
        return ''.join(out)

    os.makedirs(outdir, exist_ok=True)
    written = set()
    head = 'module\n\n'
    ns_open = '\nnamespace Formalization\nnamespace Pill\nnamespace Cue\n\nopen Nock CueRel\n\n'
    ns_close = '\nend Cue\nend Pill\nend Formalization\n'

    # the windows
    nwin = (nbits + 8191) // 8192
    lines = [head, 'public import lemmas.CuePill\n', '\n', GEN,
             '\n/-! The windows of the pill: `W<k>` holds its bits `8192 * k` to\n'
             '`8192 * k + 16384`, as `win<k>` says. -/\n',
             '\n@[expose] public section\n', ns_open]
    for k in range(nwin):
        lines.append('def W%d : Nat := win%% %d\n' % (k, k))
        lines.append('theorem win%d : WinOK pill W%d %d := winOK_pill %d W%d (by kernel_rfl)\n'
                     % (k, k, 8192 * k, k, k))
    lines.append(ns_close + '\nend\n')
    write(os.path.join(outdir, 'Win.lean'), ''.join(lines), written)

    # the chain of named nouns
    order = [t for t in post if t in named]
    jfiles = [[]]
    for t in order:
        jfiles[-1].append(t)
        if len(jfiles[-1]) >= JFILE and t in key:
            jfiles.append([])
    if not jfiles[-1]:
        jfiles.pop()

    def kv_tree(keys, lo, hi):
        # keys: list of (j, start), sorted, covering j in [lo, hi)
        if hi - lo == 1:
            j, b = keys[0]
            return '(%d, k%d)' % (b, j)
        mid = (lo + hi) // 2
        k = mid - lo
        return ('bif Nat.ble %d j then %s else %s' %
                (mid, kv_tree(keys[k:], mid, hi), kv_tree(keys[:k], lo, mid)))

    parts = []
    for f, chunk in enumerate(jfiles):
        lines = [head]
        lines.append('public import lemmas.CueRel\n' if f == 0
                     else 'public import lemmas.Pill.Cue.J%03d\n' % (f - 1))
        lines.append('\n' + GEN)
        lines.append('\nset_option maxRecDepth 100000\n')
        lines.append('\n@[expose] public section\n' + ns_open)
        for t in chunk:
            lines.append('noncomputable def %s : Noun := %s\n' % (named[t], term(t, True)))
        ks = sorted((key[t], start[t]) for t in chunk if t in key)
        if ks:
            lo, hi = ks[0][0], ks[-1][0] + 1
            assert hi - lo == len(ks)
            lines.append('\n/-- The entries %d to %d of the table. -/\n' % (lo, hi - 1))
            lines.append('noncomputable def KV%d (j : Nat) : Nat × Noun :=\n  %s\n' % (f, kv_tree(ks, lo, hi)))
            parts.append((lo, hi, f))
        lines.append(ns_close + '\nend\n')
        write(os.path.join(outdir, 'J%03d.lean' % f), ''.join(lines), written)

    def part_tree(ps, indent):
        if len(ps) == 1:
            return 'KV%d j' % ps[0][2]
        m = len(ps) // 2
        pad = '\n' + '  ' * (indent + 1)
        return ('bif Nat.ble %d j then%s%s%selse%s%s' %
                (ps[m][0], pad, part_tree(ps[m:], indent + 1), '\n' + '  ' * indent,
                 pad, part_tree(ps[:m], indent + 1)))

    lines = [head, 'public import lemmas.Pill.Cue.J%03d\n' % (len(jfiles) - 1), '\n', GEN,
             '\n@[expose] public section\n', ns_open,
             '/-- The table of the nouns of the pill that a reference points to, in the\n'
             'order in which their decoding ends (%d entries): the bit where each starts\n'
             'and the noun. -/\n' % nkeys,
             'noncomputable def KV (j : Nat) : Nat × Noun :=\n  %s\n' % part_tree(parts, 1),
             ns_close, '\nend\n']
    write(os.path.join(outdir, 'KV.lean'), ''.join(lines), written)

    # the theorems: a tree of the named cells, cut into theorems and files
    ncells = [t for t in post if t in named and kind[t] == 'c']
    ntoks = {}          # tokens of a named cell, without the named cells below it
    children = {}       # the named cells right below a named cell
    for t in ncells:
        cnt = 0
        ch = []
        st = [t]
        while st:
            u = st.pop()
            if u != t and u in named and kind[u] == 'c':
                ch.append(u)
                continue
            cnt += 1
            if kind[u] == 'c':
                st.append(kids[u][1])
                st.append(kids[u][0])
        ntoks[t] = cnt
        children[t] = ch

    def cut(nodes, limit, weight, children):
        """roots among nodes (in post-order) so that each root's part weighs
        about limit; returns roots and the weight of each root's part"""
        acc = {}
        roots = set()
        for t in nodes:
            cs = sorted(children[t], key=lambda c: (-acc[c], start[c]))
            total = weight[t] + sum(acc[c] for c in cs)
            for c in cs:
                if total <= limit:
                    break
                roots.add(c)
                total -= acc[c]
            acc[t] = total
        roots.add(nodes[-1])
        return roots, acc

    lroots, lsize = cut(ncells, LLIMIT, ntoks, children)
    # the tree of theorems
    lorder = [t for t in ncells if t in lroots]
    lchildren = {}
    for t in lorder:
        ch = []
        st = list(children[t])
        while st:
            u = st.pop()
            if u in lroots:
                ch.append(u)
            else:
                st.extend(children[u])
        lchildren[t] = ch
    lweight = {t: lsize[t] for t in lorder}
    froots, _ = cut(lorder, FLIMIT, lweight, lchildren)
    fileof = {}
    forder = [t for t in lorder if t in froots]
    members = {}
    for t in forder:
        mem = []
        st = [t]
        while st:
            u = st.pop()
            mem.append(u)
            for c in lchildren[u]:
                if c not in froots:
                    st.append(c)
        mem.sort(key=lambda u: post_index[u])
        members[t] = mem
        for u in mem:
            fileof[u] = t

    # the count when the decoding of each token starts, and when it ends
    count = {}
    i = 0
    for t in post:
        if t in key:
            i += 1
        count[t] = i
    begin = {}
    i = 0
    st = [(0, False)]
    while st:
        t, done = st.pop()
        if done:
            if t in key:
                i += 1
            continue
        begin[t] = i
        if kind[t] == 'c':
            st.append((t, True))
            st.append((kids[t][1], False))
            st.append((kids[t][0], False))
        elif t in key:
            i += 1

    for top in forder:
        mem = members[top]
        deps = set()
        for u in mem:
            for c in lchildren[u]:
                if fileof[c] != top:
                    deps.add(fileof[c])
        lines = [head, 'public import lemmas.Pill.Cue.KV\n', 'public import lemmas.Pill.Cue.Win\n']
        for d in sorted(deps, key=lambda d: start[d]):
            lines.append('public import lemmas.Pill.Cue.D%d\n' % start[d])
        lines.append('\n' + GEN)
        lines.append('\nset_option Elab.async false\n\npublic section\n' + ns_open)
        for u in mem:
            lines.append('theorem d%d : Dec pill KV %d %s %d %d %d := by cue_dec\n'
                         % (start[u], start[u], named[u], end[u], begin[u], count[u]))
        lines.append(ns_close + '\nend\n')
        write(os.path.join(outdir, 'D%d.lean' % start[top]), ''.join(lines), written)

    # the root
    assert start[0] == 0 and named[0] == 's0'
    pdir = os.path.join(outdir, '..')
    chain = sorted(f for f in os.listdir(os.path.join(pdir, 'Nouns')) if f.endswith('.lean'))
    arms = sorted(f[:-5] for f in os.listdir(os.path.join(pdir, 'Arm')) if f.endswith('.lean'))
    last = (nbits - 1) // 8192
    lines = [head, 'public import lemmas.Pill.Cue.D0\n',
             'public import lemmas.Pill.Nouns.%s\n' % chain[-1][:-5]]
    lines += ['import all lemmas.Pill.Arm.%s\n' % a for a in arms]
    lines += ['\n', GEN,
              '\n/-! The kernel compares the noun of the derivation with `root`, through\n'
              '`import all` of the arm files. -/\n',
              '\npublic section\n', ns_open,
              'theorem last_bit : bits pill %d 1 = 1 := by\n'
              '  rw [win%d %d 1 (by decide) (by decide)]; kernel_rfl\n\n' % (nbits - 1, last, nbits - 1),
              '/-- The noun of the derivation is the noun of `lemmas/Pill`. -/\n'
              'theorem s0_eq : s0 = root := by kernel_rfl\n\n',
              '/-- `CueRoot`: the pill decodes to `root`. -/\n'
              'theorem cue_pill : cue pill = some root := by\n'
              '  rw [← s0_eq]; exact cue_of_dec d0 last_bit\n',
              ns_close, '\nend\n']
    write(os.path.join(outdir, 'Root.lean'), ''.join(lines), written)

    for f in os.listdir(outdir):
        path = os.path.abspath(os.path.join(outdir, f))
        if f.endswith('.lean') and path not in written:
            os.remove(path)
    sizes = sorted(lsize[t] for t in lorder)
    print('tokens', ntok, 'entries', nkeys, 'named', len(named), 'chain files', len(jfiles),
          'theorems', len(lorder), 'files of theorems', len(forder),
          'largest theorems', sizes[-5:])


if __name__ == '__main__':
    main()
