#!/usr/bin/env python3
"""lemmas/Pill/Arms.lean: the arms of the pill by Hoon path (track T, README
Gaps 32).

    armlean.py [--paths cited.json] [--out ../../lemmas/Pill/Arms.lean]

For every arm path P of the list (default: tools/armtab/cited.json, the arms
that files outside lemmas/Pill cite by axis, from axischeck.py) and its core
Q, in the namespace `Formalization.Pill.armtab`:

    def «Q».bat : Noun          the battery of Q: its lemmas/Pill name, or
                                (slot? AX N).getD (A 0) for the nearest named
                                noun N that holds it at axis AX
    def «P».arm : Noun          the same for the arm's formula
    theorem «P».arm_at : slot? BAX «Q».bat = some «P».arm
    theorem «Q».bat_at : slot? AX core = some «Q».bat     (a spine core)

all by `kernel_rfl`.  A link file that cites `armtab.«s6/hinted».arm_at`
needs no edit when a switch renames the hash names or moves the arm: the
generator re-emits the file from the table and the names.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FORM = os.path.normpath(os.path.join(HERE, '..', '..'))


def main():
    a = sys.argv[1:]

    def opt(k, d):
        return a[a.index(k) + 1] if k in a else d
    tab = json.load(open(HERE + '/armtab.json'))
    nam = json.load(open(HERE + '/names.json'))
    paths = json.load(open(opt('--paths', HERE + '/cited.json')))
    out = opt('--out', FORM + '/lemmas/Pill/Arms.lean')
    facts = open(FORM + '/lemmas/Pill/Facts.lean').read().split('\n')
    imports = [ln for ln in facts if ln.startswith('public import') or ln.startswith('import all')]
    sha = [ln for ln in facts if ln.startswith('sha256 of the pill')]

    def term(e, kind):
        names = e.get(kind, [])
        if names:
            return names[0]
        nm, ax = e['in']
        return '((slot? %d %s).getD (A 0))' % (ax, nm)
    cores = sorted(set(p.rsplit('/', 1)[0] for p in paths))
    L = ['module', '']
    L += ['public import lemmas.Fuel'] + imports
    L += ['', '/-', 'Generated by tools/armtab/armlean.py from tools/armtab/armtab.json and',
          'names.json; do not edit.  ' + (sha[0] if sha else ''), '-/', '',
          '/-! The arms that the link files cite by axis, by their Hoon path (README',
          'Gaps 32): `armtab.«path».arm` is the formula of the arm, `armtab.«core».bat`',
          'the battery of its core, and `armtab.«path».arm_at` puts the one in the other',
          'at the arm\'s battery axis.  Paths: `s<i>` the i-th core of the tail spine of',
          '`core` (s0 = `core`, s1 = `interp`, s2 = `cor`, s5 the optimizer, s6 the',
          'compiler core `K`, s8 = `ana`, s10 = `lib`), then arm names, `$` the arm of a',
          'gate. -/', '', 'set_option maxRecDepth 100000', '', '@[expose] public section', '',
          'namespace Formalization', 'namespace Pill', 'namespace armtab', '', 'open Nock', '']
    for q in cores:
        e = nam['cores'][q]
        L.append('def «%s».bat : Noun := %s' % (q, term(e, 'battery')))
        c = tab['cores'][q]
        if c['abs'] is not None:
            L.append('')
            L.append('theorem «%s».bat_at : slot? %d core = some «%s».bat := by kernel_rfl'
                     % (q, 2 * c['abs'], q))
        L.append('')
    for p in paths:
        q = p.rsplit('/', 1)[0]
        e = nam['arms'][p]
        t = tab['arms'][p]
        L.append('def «%s».arm : Noun := %s' % (p, term(e, 'arm')))
        L.append('')
        L.append('/-- `%s`: battery axis %d, core axis %d%s. -/' % (
            p, t['bax'], t['cax'], '' if t['abs'] is None else ', axis %d of `core`' % t['abs']))
        L.append('theorem «%s».arm_at : slot? %d «%s».bat = some «%s».arm := by kernel_rfl'
                 % (p, t['bax'], q, p))
        L.append('')
    L += ['end armtab', 'end Pill', 'end Formalization', '']
    open(out, 'w').write('\n'.join(L))
    print('%s: %d cores, %d arms' % (out, len(cores), len(paths)))


if __name__ == '__main__':
    main()
